// Classic type-challenges with their usual solutions.
type MyPick<T, K extends keyof T> = { [P in K]: T[P] };
type C1 = MyPick<{ a: 1; b: 2; c: 3 }, "a" | "c">;
type MyReadonly<T> = { readonly [K in keyof T]: T[K] };
type C2 = MyReadonly<{ a: 1; b: string }>;
type TupleToObject<T extends readonly (string | number)[]> = { [K in T[number]]: K };
type C3 = TupleToObject<["tesla", "model 3", 1]>;
type First<T extends any[]> = T extends [infer F, ...any[]] ? F : never;
type C4 = First<[3, 2, 1]>;
type C5 = First<[]>;
type Length<T extends readonly any[]> = T["length"];
type C6 = Length<["a", "b", "c"]>;
type MyExclude<T, U> = T extends U ? never : T;
type C7 = MyExclude<"a" | "b" | "c", "a">;
type If<C extends boolean, T, F> = C extends true ? T : F;
type C8 = If<true, "a", "b">;
type Concat<T extends any[], U extends any[]> = [...T, ...U];
type C9 = Concat<[1, 2], [3, 4]>;
type Includes<T extends readonly any[], U> = T extends [infer F, ...infer R]
  ? (<V>() => V extends F ? 1 : 2) extends (<V>() => V extends U ? 1 : 2) ? true : Includes<R, U>
  : false;
type C10 = Includes<["Kars", "Esidisi", "Wamuu"], "Kars">;
type C11 = Includes<[{ a: "A" }], { readonly a: "A" }>;
type Push<T extends any[], U> = [...T, U];
type C12 = Push<[1, 2], "3">;
type Unshift<T extends any[], U> = [U, ...T];
type C13 = Unshift<[1, 2], 0>;
type MyParameters<T extends (...args: any[]) => any> = T extends (...args: infer P) => any ? P : never;
type C14 = MyParameters<(a: string, b: number) => void>;
type MyReturnType<T> = T extends (...args: any[]) => infer R ? R : never;
type C15 = MyReturnType<() => 1 | 2>;
type MyOmit<T, K extends keyof T> = { [P in keyof T as P extends K ? never : P]: T[P] };
type C16 = MyOmit<{ a: 1; b: 2; c: 3 }, "b">;
type DeepReadonly<T> = { readonly [K in keyof T]: T[K] extends object ? DeepReadonly<T[K]> : T[K] };
type C17 = DeepReadonly<{ a: { b: 1 } }>;
type TupleToUnion<T extends any[]> = T[number];
type C18 = TupleToUnion<[1, "2", true]>;
type Last<T extends any[]> = T extends [...infer _, infer L] ? L : never;
type C19 = Last<[3, 2, 1]>;
type Pop<T extends any[]> = T extends [...infer R, any] ? R : [];
type C20 = Pop<[3, 2, 1]>;
type LookUp<U, T> = U extends { type: T } ? U : never;
type Cat = { type: "cat"; breeds: "Abyssinian" };
type Dog = { type: "dog"; breeds: "Hound"; color: "brown" };
type C21 = LookUp<Cat | Dog, "dog">;
type TrimLeft<S extends string> = S extends `${" " | "\n" | "\t"}${infer R}` ? TrimLeft<R> : S;
type C22 = TrimLeft<"   hello  ">;
type Trim<S extends string> = S extends `${" " | "\n" | "\t"}${infer R}` ? Trim<R> : S extends `${infer L}${" " | "\n" | "\t"}` ? Trim<L> : S;
type C23 = Trim<"   hello  ">;
type MyCapitalize<S extends string> = S extends `${infer F}${infer R}` ? `${Uppercase<F>}${R}` : S;
type C24 = MyCapitalize<"foo bar">;
type Replace<S extends string, From extends string, To extends string> = From extends "" ? S : S extends `${infer L}${From}${infer R}` ? `${L}${To}${R}` : S;
type C25 = Replace<"types are fun!", "fun", "awesome">;
type ReplaceAll<S extends string, From extends string, To extends string> = From extends "" ? S : S extends `${infer L}${From}${infer R}` ? `${L}${To}${ReplaceAll<R, From, To>}` : S;
type C26 = ReplaceAll<"t y p e s", " ", "">;
type AppendArgument<Fn extends (...args: any[]) => any, A> = Fn extends (...args: infer P) => infer R ? (...args: [...P, A]) => R : never;
type C27 = AppendArgument<(a: number, b: string) => number, boolean>;
type Permutation<T, K = T> = [T] extends [never] ? [] : K extends K ? [K, ...Permutation<Exclude<T, K>>] : never;
type C28 = Permutation<"A" | "B" | "C">;
type LengthOfString<S extends string, A extends string[] = []> = S extends `${infer F}${infer R}` ? LengthOfString<R, [...A, F]> : A["length"];
type C29 = LengthOfString<"kumiko">;
type Flatten<T> = T extends [] ? [] : T extends [infer F, ...infer R] ? [...Flatten<F>, ...Flatten<R>] : [T];
type C30 = Flatten<[1, 2, [3, 4], [[[5]]]]>;
type AppendToObject<T, U extends keyof any, V> = { [K in keyof T | U]: K extends keyof T ? T[K] : V };
type C31 = AppendToObject<{ id: "1" }, "value", 4>;
type Absolute<T extends number | string | bigint> = `${T}` extends `-${infer U}` ? U : `${T}`;
type C32 = Absolute<-5>;
type StringToUnion<T extends string> = T extends `${infer L}${infer R}` ? L | StringToUnion<R> : never;
type C33 = StringToUnion<"123">;
type Merge<F, S> = { [K in keyof F | keyof S]: K extends keyof S ? S[K] : K extends keyof F ? F[K] : never };
type C34 = Merge<{ a: number; b: string }, { b: number; c: boolean }>;
type KebabCase<S extends string> = S extends `${infer S1}${infer S2}` ? S2 extends Uncapitalize<S2> ? `${Uncapitalize<S1>}${KebabCase<S2>}` : `${Uncapitalize<S1>}-${KebabCase<S2>}` : S;
type C35 = KebabCase<"FooBarBaz">;
type Diff<O, O1> = { [K in Exclude<keyof O | keyof O1, keyof O & keyof O1>]: K extends keyof O ? O[K] : K extends keyof O1 ? O1[K] : never };
type C36 = Diff<{ name: string; age: string }, { name: string; gender: number }>;
type AnyOf<T extends readonly any[]> = T[number] extends 0 | "" | false | [] | { [key: string]: never } | undefined | null ? false : true;
type C37 = AnyOf<[0, "", false, [], {}]>;
type C38 = AnyOf<[1, "", false, [], {}]>;
type IsNever<T> = [T] extends [never] ? true : false;
type C39 = IsNever<never>;
type C40 = IsNever<undefined>;
type IsUnion<T, B = T> = [T] extends [never] ? false : T extends B ? ([B] extends [T] ? false : true) : never;
type C41 = IsUnion<string | number>;
type C42 = IsUnion<string>;
type ReplaceKeys<U, T, Y> = { [K in keyof U]: K extends T ? (K extends keyof Y ? Y[K] : never) : U[K] };
type C43 = ReplaceKeys<{ type: "a"; name: string }, "name", { name: number }>;
type RemoveIndexSignature<T> = { [K in keyof T as string extends K ? never : number extends K ? never : K]: T[K] };
type C44 = RemoveIndexSignature<{ [key: string]: any; foo(): void }>;
type PercentageParser<A extends string> = A extends `${infer S extends "+" | "-"}${infer R}` ? R extends `${infer N}%` ? [S, N, "%"] : [S, R, ""] : A extends `${infer N}%` ? ["", N, "%"] : ["", A, ""];
type C45 = PercentageParser<"-85%">;
type DropChar<S, C extends string> = S extends `${infer L}${C}${infer R}` ? DropChar<`${L}${R}`, C> : S;
type C46 = DropChar<" b u t t e r f l y ! ", " ">;
type MinusOne<T extends number, A extends any[] = []> = [...A, 1]["length"] extends T ? A["length"] : MinusOne<T, [...A, 1]>;
type C47 = MinusOne<55>;
type PickByType<T, U> = { [K in keyof T as T[K] extends U ? K : never]: T[K] };
type C48 = PickByType<{ name: string; count: number; isReadonly: boolean; isEnable: boolean }, boolean>;
type StartsWith<T extends string, U extends string> = T extends `${U}${string}` ? true : false;
type C49 = StartsWith<"abc", "ac">;
type C50 = StartsWith<"abc", "ab">;
type PartialByKeys<T, K extends keyof T = keyof T> = Omit<{ [P in keyof T as P extends K ? P : never]?: T[P] } & { [P in keyof T as P extends K ? never : P]: T[P] }, never>;
type C51 = PartialByKeys<{ name: string; age: number; address: string }, "name">;
type Mutable<T> = { -readonly [K in keyof T]: T[K] };
type C52 = Mutable<{ readonly a: 1; readonly b: "2" }>;
type ObjectEntries<T, K = keyof T> = K extends keyof T ? [K, T[K] extends infer V | undefined ? V : never] : never;
type C53 = ObjectEntries<{ name: string; age: number }>;
type Shift<T extends any[]> = T extends [any, ...infer R] ? R : [];
type C54 = Shift<[3, 2, 1]>;
type TupleToNestedObject<T extends string[], U> = T extends [infer F extends string, ...infer R extends string[]] ? { [K in F]: TupleToNestedObject<R, U> } : U;
type C55 = TupleToNestedObject<["a", "b"], string>;
type Reverse<T extends any[]> = T extends [infer F, ...infer R] ? [...Reverse<R>, F] : [];
type C56 = Reverse<["a", "b", "c"]>;
type FlipArguments<T extends (...args: any[]) => any> = T extends (...args: infer P) => infer R ? (...args: Reverse<P>) => R : never;
type C57 = FlipArguments<(a: string, b: number, c: boolean) => void>;
type FlattenDepth<T extends any[], D extends number = 1, C extends any[] = []> = C["length"] extends D ? T : T extends [infer F, ...infer R] ? F extends any[] ? [...FlattenDepth<F, D, [...C, 1]>, ...FlattenDepth<R, D, C>] : [F, ...FlattenDepth<R, D, C>] : T;
type C58 = FlattenDepth<[1, 2, [3, 4], [[[5]]]], 2>;
