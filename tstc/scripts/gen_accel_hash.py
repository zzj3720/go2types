#!/usr/bin/env python3
"""Records the hashes of the files of tstst's lib/pure whose definitions the
runtime's natives were checked against (src/main/accel_hash.mbt). Run after
checking that a program gives the same output with and without --no-accel.

usage: gen_accel_hash.py <lib/pure directory>"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = sys.argv[1]
M = (1 << 64) - 1
rows = []
for name in sorted(f for f in os.listdir(D) if f.endswith('.ts')):
    h = 0xCBF29CE484222325
    for b in open(os.path.join(D, name), 'rb').read():
        h = ((h ^ b) * 0x100000001B3) & M
    s = h - (1 << 64) if h >= 1 << 63 else h
    rows.append(f'  ("{name}", {s}L),')
open(os.path.join(ROOT, 'src', 'main', 'accel_hash.mbt'), 'w').write(
    '// Generated by scripts/gen_accel_hash.py: the hashes of the files of\n'
    "// tstst's lib/pure whose definitions the natives were checked against.\n"
    'let pure_file_hashes : Array[(String, Int64)] = [\n' + '\n'.join(rows) + '\n]\n')
print('\n'.join(rows))
