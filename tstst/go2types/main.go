type fstate struct {
	c        *compiler
	fn       *ssa.Function
	name     string
	names    map[ssa.Value]string
	liveIn   map[*ssa.BasicBlock][]ssa.Value
	hasDefer bool
	defers   []*ssa.Defer
	// the program-wide id of the first of defers (G_defer's keys)
	deferBase int
	prefix   string // of value names, in a function inlined into another
	inlines  int
	parent   *fstate // the function this one is inlined into
	// values bound by the entry alias around the function's frame (the cell
	// of its deferred calls, the named results the Recover block reads);
	// block 0 skips the instructions defining them
	prebound map[ssa.Value]bool
	selects  int
	// ifs whose arms meet in place (join.go): the join of a branching block,
	// the joins whose arms are being written
	joinOf  map[*ssa.BasicBlock]*ssa.BasicBlock
	joining map[*ssa.BasicBlock]bool
	// the resumable copy (sched.go): calls that may suspend save frames,
	// continuations of the function (by block and instruction)
	r      bool
	conts  map[[2]int]*cont
	contOrder []*cont
	// parameters known to be functions (spec.go)
	known map[ssa.Value]*ssa.Function
}

func (fs *fstate) vname(v ssa.Value) string {
	return fs.prefix + valueName(v)
}

func (c *compiler) emitFunc(b *strings.Builder, f *ssa.Function) {
	c.emitFuncAs(b, f, false)
}

// emitFuncAs writes f, or with r its resumable copy (sched.go)
func (c *compiler) emitFuncAs(b *strings.Builder, f *ssa.Function, r bool) {
	defer func() {
		for _, p := range c.pending {
			b.WriteString(p)
		}
		c.pending = nil
	}()
	name := c.fname(f)
	if r {
		name = c.rname(f)
	}
	sp := specCur
	if sp != nil {
		name = sp.name
	}
	fmt.Fprintf(b, "/** %s */\n", strings.ReplaceAll(funcText(f), "*/", "* /"))
	params := []string{"H"}
	for i := range f.Params {
		params = append(params, "P"+strconv.Itoa(i))
	}
	for i := range f.FreeVars {
		params = append(params, "V"+strconv.Itoa(i))
	}
	if body, ok := intrinsicBody(f); ok {
		if r {
			body = rIntrinsic(f, body)
		}
		fmt.Fprintf(b, "export type %s<%s> = %s;\n\n", name, strings.Join(params, ", "), body)
		return
	}
	if isPkgInit(f) && c.deadInit[f.Pkg] {
		fmt.Fprintf(b, "export type %s<%s> = [H]; // its globals are not read\n\n", name, strings.Join(params, ", "))
		return
	}
	if g := forwardTarget(f); g != nil {
		target := c.fname(g)
		if r {
			target = c.calleeR(g)
		}
		fmt.Fprintf(b, "export type %s<%s> = %s<%s>;\n\n", name, strings.Join(params, ", "), target, strings.Join(params, ", "))
		return
	}
	if len(f.Blocks) == 0 && f.Pkg != nil && stubPkg(f.Pkg.Pkg.Path()) {
		// runtime hook without a body: does nothing and returns zero values
		parts := []string{"H"}
		res := f.Signature.Results()
		for i := 0; i < res.Len(); i++ {
			parts = append(parts, c.zero(res.At(i).Type()))
		}
		fmt.Fprintf(b, "export type %s<%s> = [%s];\n\n", name, strings.Join(params, ", "), strings.Join(parts, ", "))
		return
	}
	if len(f.Blocks) == 0 {
		// external function without a body
		body := c.fail(f.Pos(), "function without body: %s", f.String())
		fmt.Fprintf(b, "export type %s<%s> = %s;\n\n", name, strings.Join(params, ", "), body)
		return
	}
	fs := &fstate{c: c, fn: f, name: name, names: map[ssa.Value]string{}, r: r}
	for i, p := range f.Params {
		fs.names[p] = "P" + strconv.Itoa(i)
	}
	if sp != nil {
		fs.known = map[ssa.Value]*ssa.Function{}
		for i, kf := range sp.known {
			fs.known[f.Params[i]] = kf
		}
	}
	for i, v := range f.FreeVars {
		fs.names[v] = "V" + strconv.Itoa(i)
	}
	for _, blk := range f.Blocks {
		for _, ins := range blk.Instrs {
			if d, ok := ins.(*ssa.Defer); ok {
				fs.hasDefer = true
				fs.defers = append(fs.defers, d)
			}
		}
	}
	if base, ok := c.deferBaseOf[f]; ok {
		// (the resumable copy runs the deferred calls of f's entries)
		fs.deferBase = base
	} else {
		fs.deferBase = c.deferN
		c.deferN += len(fs.defers)
		c.deferBaseOf[f] = fs.deferBase
	}
	fs.appendValues()
	fs.foldConstants()
	fs.liftLocals()
	fs.fuseFields()
	fs.byValueLoads()
	fs.computeLiveness()
	if fs.hasDefer {
		fs.emitDeferFunc(b, params)
		return
	}
	if len(f.Blocks[0].Preds) == 0 {
		// the entry alias is block 0
		fmt.Fprintf(b, "export type %s<%s> =\n", name, strings.Join(params, ", "))
		bs := &bstate{fs: fs, heap: "H"}
		b.WriteString(selfLoop(name, params, fs.blockExpr(bs, f.Blocks[0])))
		b.WriteString(";\n")
		for _, blk := range f.Blocks[1:] {
			fs.emitBlock(b, blk)
		}
		fs.emitConts(b)
		b.WriteString("\n")
		return
	}
	// entry alias forwards to block 0
	entryArgs := []string{"H"}
	for _, v := range fs.liveIn[f.Blocks[0]] {
		entryArgs = append(entryArgs, fs.names[v])
	}
	fmt.Fprintf(b, "export type %s<%s> = %s_0<%s>;\n", name, strings.Join(params, ", "), name, strings.Join(entryArgs, ", "))
	for _, blk := range f.Blocks {
		fs.emitBlock(b, blk)
	}
	fs.emitConts(b)
	b.WriteString("\n")
}

func valueName(v ssa.Value) string {
	return "t" + strings.TrimPrefix(v.Name(), "t")
}

// operands that are local SSA values (passed between blocks)
func isLocal(v ssa.Value) bool {
	if foldedConst[v] {
		return false
	}
	switch v.(type) {
	case *ssa.Const, *ssa.Global, *ssa.Function, *ssa.Builtin:
		return false
	}
	return true
}

func (fs *fstate) computeLiveness() {
	f := fs.fn
	defs := map[*ssa.BasicBlock]map[ssa.Value]bool{}
	uses := map[*ssa.BasicBlock]map[ssa.Value]bool{}
	// Extract instructions are named after their tuple and count as defined
	// where the tuple is defined.
	extracts := map[ssa.Value][]*ssa.Extract{}
	for _, blk := range f.Blocks {
		for _, ins := range blk.Instrs {
			if e, ok := ins.(*ssa.Extract); ok {
				extracts[e.Tuple] = append(extracts[e.Tuple], e)
				fs.names[e] = fs.vname(e.Tuple) + "_" + strconv.Itoa(e.Index)
			}
		}
	}
	for _, blk := range f.Blocks {
		d := map[ssa.Value]bool{}
		u := map[ssa.Value]bool{}
		for _, ins := range blk.Instrs {
			if _, ok := ins.(*ssa.Extract); ok || fs.c.dropped[ins] {
				continue
			}
			if _, ok := ins.(*ssa.Phi); !ok {
				var ops []*ssa.Value
				for _, op := range ins.Operands(ops) {
					for _, v := range fusedOperands(*op) {
						if v != nil && isLocal(v) && !d[v] {
							u[v] = true
						}
					}
				}
			}
			if v, ok := ins.(ssa.Value); ok {
				d[v] = true
				for _, e := range extracts[v] {
					d[e] = true
				}
			}
		}
		defs[blk] = d
		uses[blk] = u
	}
	live := map[*ssa.BasicBlock]map[ssa.Value]bool{}
	for _, blk := range f.Blocks {
		live[blk] = map[ssa.Value]bool{}
	}
	changed := true
	for changed {
		changed = false
		for i := len(f.Blocks) - 1; i >= 0; i-- {
			blk := f.Blocks[i]
			in := live[blk]
			add := func(v ssa.Value) {
				if !in[v] {
					in[v] = true
					changed = true
				}
			}
			for v := range uses[blk] {
				add(v)
			}
			for _, s := range blk.Succs {
				for v := range live[s] {
					if isPhiOf(v, s) {
						continue
					}
					if !defs[blk][v] {
						add(v)
					}
				}
				// phi operands for the edge blk -> s
				idx := predIndex(s, blk)
				for _, ins := range s.Instrs {
					phi, ok := ins.(*ssa.Phi)
					if !ok {
						break
					}
					op := fusedOperand(phi.Edges[idx])
					if isLocal(op) && !defs[blk][op] {
						add(op)
					}
				}
			}
		}
	}
	fs.liveIn = map[*ssa.BasicBlock][]ssa.Value{}
	for _, blk := range f.Blocks {
		var phis, rest []ssa.Value
		for _, ins := range blk.Instrs {
			if phi, ok := ins.(*ssa.Phi); ok {
				phis = append(phis, phi)
			}
		}
		for v := range live[blk] {
			if !isPhiOf(v, blk) {
				rest = append(rest, v)
			}
		}
		sort.Slice(rest, func(i, j int) bool { return fs.order(rest[i]) < fs.order(rest[j]) })
		fs.liveIn[blk] = append(phis, rest...)
	}
}

func (fs *fstate) order(v ssa.Value) string {
	switch x := v.(type) {
	case *ssa.Parameter:
		for i, p := range fs.fn.Params {
			if p == x {
				return fmt.Sprintf("a%06d", i)
			}
		}
	case *ssa.FreeVar:
		for i, p := range fs.fn.FreeVars {
			if p == x {
				return fmt.Sprintf("b%06d", i)
			}
		}
	}
	n, _ := strconv.Atoi(strings.TrimPrefix(v.Name(), "t"))
	return fmt.Sprintf("c%06d", n)
}

func isPhiOf(v ssa.Value, blk *ssa.BasicBlock) bool {
	phi, ok := v.(*ssa.Phi)
	return ok && phi.Block() == blk
}

func predIndex(s, p *ssa.BasicBlock) int {
	for i, q := range s.Preds {
		if q == p {
			return i
		}
	}
	panic("not a predecessor")
}

// block emission state
type bstate struct {
	fs    *fstate
	lines []string
	opens int
	// false branches of the opened conditionals from the innermost one out
	// that are not 0 (keyed by the number of conditionals opened before)
	elses map[int]string
	// calls are not inlined (the call of a go statement)
	noInline bool
	heap     string
	hn       int
	tmp      int
	// conditionals the expression is nested in outside bs (the blocks it was
	// inlined into)
	depth int
	// the last call (bs.call): a return of exactly its results is the call
	last *lastCall
	// the instruction being written (blockExprFrom), for continuations
	blk *ssa.BasicBlock
	at  int
	// calls go to resumable copies, without frames (the call of a go
	// statement's thunk)
	rcall bool
}

type lastCall struct {
	expr    string
	lines   int // len(lines) after it
	heap    string
	results []string
	cont    *cont // the frame its suspension gets
}

// conditional expressions must be parenthesized before `extends`
func paren(expr string) string {
	if strings.Contains(expr, " ? ") || strings.Contains(expr, " ?\n") {
		return "(" + expr + ")"
	}
	return expr
}

func (bs *bstate) bind(expr, name string) {
	expr = bs.tupleOf(expr)
	bs.lines = append(bs.lines, fmt.Sprintf("  %s extends infer %s ?", paren(expr), name))
	bs.opens++
}

// A tuple literal with an element that may resolve to a type alias (g.hget<..>,
// a conditional) is a deferred type reference in tsc and tsgo: instantiated
// with all the type parameters it may reference, and taken for one that may
// contain type variables, so everything holding it (the heap, once stored) is
// walked on every instantiation. tupleOf binds such elements first, to keep
// the tuple's elements literals and type parameters.
func (bs *bstate) tupleOf(expr string) string {
	elems, ok := splitTupleLit(expr)
	if !ok {
		return expr
	}
	for i, e := range elems {
		if _, nested := splitTupleLit(e); nested {
			elems[i] = bs.tupleOf(e)
		} else if !simpleTypeElem(e) {
			t := bs.newTmp()
			bs.lines = append(bs.lines, fmt.Sprintf("  %s extends infer %s ?", paren(e), t))
			bs.opens++
			elems[i] = t
		}
	}
	return "[" + strings.Join(elems, ", ") + "]"
}

var simpleElem = regexp.MustCompile("^(?:[A-Za-z_$][\\w$]*|-?[0-9]+n?|\"(?:[^\"\\\\]|\\\\.)*\")$")

// an element that resolves to no type alias: a name, a number or string literal
func simpleTypeElem(e string) bool {
	return simpleElem.MatchString(e) && e != "never"
}

// the elements of a tuple literal [a, b, ...] (top-level commas), or false
func splitTupleLit(expr string) ([]string, bool) {
	if len(expr) < 2 || expr[0] != '[' || expr[len(expr)-1] != ']' {
		return nil, false
	}
	var elems []string
	depth, start := 0, 1
	var quote byte
	for i := 1; i < len(expr)-1; i++ {
		ch := expr[i]
		if quote != 0 {
			if ch == '\\' {
				i++
			} else if ch == quote {
				quote = 0
			}
			continue
		}
		switch ch {
		case '"', '`':
			quote = ch
		case '[', '<', '(', '{':
			depth++
		case ']', '>', ')', '}':
			depth--
			if depth < 0 {
				return nil, false
			}
		case ',':
			if depth == 0 {
				elems = append(elems, strings.TrimSpace(expr[start:i]))
				start = i + 1
			}
		}
	}
	if depth != 0 || quote != 0 {
		return nil, false
	}
	if last := strings.TrimSpace(expr[start : len(expr)-1]); last != "" || len(elems) > 0 {
		elems = append(elems, last)
	}
	for _, e := range elems {
		if e == "" || strings.HasPrefix(e, "...") {
			return nil, false
		}
	}
	return elems, true
}

func (bs *bstate) bindTuple(expr string, names ...string) {
	expr = paren(expr)
	parts := make([]string, len(names))
	for i, n := range names {
		parts[i] = "infer " + n
	}
	bs.lines = append(bs.lines, fmt.Sprintf("  %s extends [%s] ?", expr, strings.Join(parts, ", ")))
	bs.opens++
}

// the false branches closing the opened conditionals, innermost first
func (bs *bstate) closings() string {
	var b strings.Builder
	for i := bs.opens - 1; i >= 0; i-- {
		if e, ok := bs.elses[i]; ok {
			b.WriteString(" : " + e)
		} else {
			b.WriteString(" : 0")
		}
	}
	return b.String()
}

func (bs *bstate) newHeap() string {
	bs.hn++
	return "H" + strconv.Itoa(bs.hn)
}

func (bs *bstate) newTmp() string {
	bs.tmp++
	return "X" + strconv.Itoa(bs.tmp)
}

func (bs *bstate) lastTmp() string { return "X" + strconv.Itoa(bs.tmp) }

// heap-updating expression whose result is the new heap
func (bs *bstate) setHeap(expr string) {
	h := bs.newHeap()
	bs.bind(expr, h)
	bs.heap = h
}

// call returning [H, results...], or a panic, which becomes the result of
// the enclosing expression (so that it reaches the catching function)
func (bs *bstate) call(expr string, results ...string) {
	r := bs.newTmp()
	bs.bind(expr, r)
	h := bs.newHeap()
	parts := make([]string, 0, len(results)+1)
	for _, n := range append([]string{h}, results...) {
		parts = append(parts, "infer "+n)
	}
	bs.lines = append(bs.lines, fmt.Sprintf("  %s extends [%s] ?", r, strings.Join(parts, ", ")))
	if bs.elses == nil {
		bs.elses = map[int]string{}
	}
	bs.elses[bs.opens] = r
	bs.opens++
	bs.heap = h
	bs.last = &lastCall{expr: expr, lines: len(bs.lines), heap: h, results: results}
}

// the call just made, when what follows returns exactly its results (heap
// and values): the result is the call's, panics included, so the call is
// the term (a tail call)
func (bs *bstate) returnsLastCall(parts []string) (string, bool) {
	l := bs.last
	if l == nil || l.lines != len(bs.lines) || len(parts) != len(l.results)+1 || parts[0] != l.heap {
		return "", false
	}
	for i, r := range l.results {
		if parts[i+1] != r {
			return "", false
		}
	}
	if l.cont != nil {
		if *framesLearn {
			// (every function on a stack that waits is learned)
			return "", false
		}
		l.cont.tail++
	}
	bs.lines = bs.lines[:len(bs.lines)-2]
	bs.opens -= 2
	delete(bs.elses, bs.opens+1)
	bs.last = nil
	return paren(l.expr), true
}

func (fs *fstate) blockName(blk *ssa.BasicBlock) string {
	return fs.name + "_" + strconv.Itoa(blk.Index)
}

// Blocks with a single predecessor are not aliases of their own: their code
// is emitted where the predecessor jumps to them, so that a function costs
// one alias call per executed join point (loop header, merge after an if)
// instead of one per block.
func (fs *fstate) inlined(blk *ssa.BasicBlock) bool {
	if blk.Index == 0 || blk == fs.fn.Recover {
		return false
	}
	return len(blk.Preds) == 1 || fs.tinyReturn(blk) || fs.isJoin(blk)
}

// a block of a few instructions that returns, without calls: written at each
// jump to it (a copy per predecessor) rather than as an alias of its own,
// whose call costs more than the block
func (fs *fstate) tinyReturn(blk *ssa.BasicBlock) bool {
	if fs.hasDefer || len(blk.Instrs) == 0 {
		return false
	}
	if _, ok := blk.Instrs[len(blk.Instrs)-1].(*ssa.Return); !ok {
		return false
	}
	n := 0
	for _, ins := range blk.Instrs {
		switch x := ins.(type) {
		case *ssa.DebugRef, *ssa.Phi:
			continue
		case *ssa.Call, *ssa.Defer, *ssa.Go, *ssa.Select, *ssa.RunDefers, *ssa.Panic:
			return false
		case *ssa.FieldAddr, *ssa.ChangeType:
			// (an address its load or store takes in: no code of its own; a
			// change of type: none)
			continue
		case *ssa.Convert:
			if isInteger(x.Type()) && isInteger(x.X.Type()) {
				// (an integer's: a wrap at most)
				continue
			}
		}
		n++
	}
	return n <= 3
}

func (fs *fstate) emitBlock(b *strings.Builder, blk *ssa.BasicBlock) {
	if fs.inlined(blk) {
		return
	}
	params := []string{"H"}
	if fs.hasDefer {
		params = append(params, "DC")
	}
	for _, v := range fs.liveIn[blk] {
		if _, ok := fs.names[v]; !ok {
			fs.names[v] = fs.vname(v)
		}
		params = append(params, fs.names[v])
	}
	fmt.Fprintf(b, "type %s<%s> =\n", fs.blockName(blk), strings.Join(params, ", "))
	b.WriteString(selfLoop(fs.blockName(blk), params, fs.blockExpr(&bstate{fs: fs, heap: "H"}, blk)))
	b.WriteString(";\n")
}

// the body of an alias that only calls itself (a loop doing nothing, like
// runtime._ExternalCode): behind a conditional, since a type alias whose
// type is a reference to itself circularly references itself, which tsc and
// tsgo report (the conditional is resolved when instantiated: a loop)
//
// So is the body of one that calls itself (a loop) when its first conditional
// tests no parameter (it starts with constants: a global's address): tsc and
// tsgo resolve such a conditional where the alias is declared, and with it the
// conditionals its result makes non-generic, up to the reference to the alias
// itself, whose type is then being resolved (TS2456)
func selfLoop(name string, params []string, body string) string {
	if strings.TrimSpace(body) == name+"<"+strings.Join(params, ", ")+">" {
		return fmt.Sprintf("  [%s] extends [unknown] ? %s : never", params[0], strings.TrimSpace(body))
	}
	if !strings.Contains(body, name+"<") {
		return body
	}
	first, _, _ := strings.Cut(body, "\n")
	cond, _, ok := strings.Cut(first, " extends ")
	if !ok {
		return body
	}
	for _, p := range params {
		if regexp.MustCompile(`\b` + regexp.QuoteMeta(p) + `\b`).MatchString(cond) {
			return body
		}
	}
	return fmt.Sprintf("  [%s] extends [unknown] ?\n%s : never", params[0], body)
}

// the code of blk as one expression, continuing in the state of bs (whose
// heap and fresh-name counters it starts from)
func (fs *fstate) blockExpr(bs *bstate, blk *ssa.BasicBlock) string {
	return fs.blockExprFrom(bs, blk, 0)
}

// the code of blk from instruction start on
func (fs *fstate) blockExprFrom(bs *bstate, blk *ssa.BasicBlock, start int) string {
	for _, ins := range blk.Instrs {
		if v, ok := ins.(ssa.Value); ok {
			if _, done := fs.names[v]; !done {
				fs.names[v] = fs.vname(v)
			}
		}
	}
	var term string
	for i := start; i < len(blk.Instrs); i++ {
		ins := blk.Instrs[i]
		if v, ok := ins.(ssa.Value); ok && fs.prebound[v] || fs.c.dropped[ins] {
			continue
		}
		if splittable(ins) && i > start && *splitAt > 0 && bs.depth+bs.opens >= *splitAt {
			term = fs.splitRest(bs, blk, i)
			break
		}
		bs.blk, bs.at = blk, i
		if t := fs.instr(bs, ins); t != "" {
			term = t
		}
	}
	var b strings.Builder
	for _, l := range bs.lines {
		b.WriteString(l)
		b.WriteString("\n")
	}
	b.WriteString("  ")
	b.WriteString(term)
	b.WriteString(bs.closings())
	return b.String()
}

func isIdent(s string) bool {
	// constants written as keywords are no names: a parameter called null
	// is a syntax error for the checkers (tstc accepts it)
	switch s {
	case "null", "undefined", "true", "false", "never", "unknown", "any", "void", "object", "string", "number", "bigint", "boolean", "symbol", "keyof", "infer", "extends", "typeof", "readonly", "unique":
		return false
	}
	for i, r := range s {
		if !(r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			return false
		}
	}
	return s != ""
}

// a block can be split before ins (Extracts stay with their tuple)
func splittable(ins ssa.Instruction) bool {
	switch ins.(type) {
	case *ssa.Phi, *ssa.Extract, *ssa.DebugRef:
		return false
	}
	return true
}

// splitRest moves the code of blk from instruction i on into an alias of its
// own (written after the function) and returns the call of it: the values it
// reads that are defined before i (and those live out of blk) are its
// parameters.
func (fs *fstate) splitRest(bs *bstate, blk *ssa.BasicBlock, i int) string {
	c := fs.c
	params := []string{"H"}
	args := []string{bs.heap}
	if fs.hasDefer {
		params = append(params, "DC")
		args = append(args, "DC")
	}
	names := map[string]bool{}
	for _, p := range params {
		names[p] = true
	}
	rest := fs.restNames(blk, i, nil, names)
	params = append(params, rest...)
	args = append(args, rest...)
	c.splits++
	name := fmt.Sprintf("%s_s%d", fs.name, c.splits)
	body := fs.blockExprFrom(&bstate{fs: fs, heap: "H"}, blk, i)
	c.pending = append(c.pending, fmt.Sprintf("type %s<%s> =\n%s;\n", name, strings.Join(params, ", "), body))
	return fmt.Sprintf("%s<%s>", name, strings.Join(args, ", "))
}

// restNames: the names of the values the code of blk from instruction i on
// reads (and those live out of blk) that are defined before i (or are in
// defs, defined there too), not yet in names (which gets them)
func (fs *fstate) restNames(blk *ssa.BasicBlock, i int, defs []ssa.Value, names map[string]bool) []string {
	c := fs.c
	defined := map[ssa.Value]bool{}
	for _, v := range defs {
		defined[v] = true
	}
	var needed []ssa.Value
	seen := map[ssa.Value]bool{}
	var need func(v ssa.Value)
	need = func(v ssa.Value) {
		if v == nil || !isLocal(v) || defined[v] || seen[v] {
			return
		}
		// written where it is used: what it reads is needed
		if inlinedVal[v] {
			seen[v] = true
			var ops []*ssa.Value
			for _, op := range v.(ssa.Instruction).Operands(ops) {
				for _, v := range fusedOperands(*op) {
					need(v)
				}
			}
			return
		}
		// an extract (in a successor too) is bound where its tuple is
		if e, ok := v.(*ssa.Extract); ok && defined[e.Tuple] {
			return
		}
		seen[v] = true
		needed = append(needed, v)
	}
	rest := blk.Instrs[i:]
	for _, ins := range rest {
		if _, ok := ins.(*ssa.Extract); ok {
			continue // named after its tuple, bound where the tuple is
		}
		// (prebound values are bound by the entry alias, a parameter here)
		if v, ok := ins.(ssa.Value); ok && !fs.prebound[v] {
			defined[v] = true
		}
	}
	// extracts of tuples defined in the rest are defined there too
	for _, ins := range rest {
		if e, ok := ins.(*ssa.Extract); ok && defined[e.Tuple] {
			defined[e] = true
		}
	}
	for _, ins := range rest {
		switch ins.(type) {
		case *ssa.Extract, *ssa.DebugRef:
			continue
		}
		if c.dropped[ins] {
			continue
		}
		var ops []*ssa.Value
		for _, op := range ins.Operands(ops) {
			for _, v := range fusedOperands(*op) {
				need(v)
			}
		}
	}
	for _, s := range blk.Succs {
		for _, v := range fs.liveIn[s] {
			if !isPhiOf(v, s) {
				need(v)
			}
		}
		idx := predIndex(s, blk)
		for _, ins := range s.Instrs {
			phi, ok := ins.(*ssa.Phi)
			if !ok {
				break
			}
			need(fusedOperand(phi.Edges[idx]))
		}
	}
	sort.SliceStable(needed, func(a, b int) bool { return fs.order(needed[a]) < fs.order(needed[b]) })
	var out []string
	for _, v := range needed {
		n := fs.val(v)
		if !isIdent(n) {
			// in an inlined function, a parameter can stand for a constant
			// or for an expression of the caller's values (written in
			// place): the names that expression reads are parameters then,
			// or the split alias reads names it does not have (tstc accepts
			// that; to tsc and tsgo it is an error type, any)
			e := exprStrings.ReplaceAllString(n, `""`)
			for _, m := range exprNames.FindAllStringSubmatchIndex(e, -1) {
				id, end := e[m[2]:m[3]], m[3]
				if end < len(e) && (e[end] == '.' || e[end] == '<') {
					continue
				}
				if isIdent(id) && !names[id] {
					names[id] = true
					out = append(out, id)
				}
			}
			continue
		}
		if names[n] {
			continue
		}
		names[n] = true
		out = append(out, n)
	}
	return out
}

// the value names an expression reads: identifiers that are not a namespace
// (g.), a member after a dot or a generic alias applied to arguments
var exprNames = regexp.MustCompile(`(?:^|[^.\w$])([A-Za-z_$][\w$]*)\b`)

// string and template literals (no names in them)
var exprStrings = regexp.MustCompile("\"(?:[^\"\\\\]|\\\\.)*\"|`(?:[^`\\\\]|\\\\.)*`")

func (fs *fstate) val(v ssa.Value) string {
	c := fs.c
	switch x := v.(type) {
	case *ssa.Const:
		return c.constant(x)
	case *ssa.Global:
		return fmt.Sprintf("%dn", c.globID[x])
	case *ssa.Function:
		return fmt.Sprintf("[%dn]", c.fid(x))
	case *ssa.Builtin:
		return c.fail(token.NoPos, "builtin %s used as a value", x.Name())
	}
	// (before the names: blocks name all their values first)
	if e, ok := fs.liftedVal(v); ok {
		return e
	}
	if n, ok := fs.names[v]; ok {
		return n
	}
	n := fs.vname(v)
	fs.names[v] = n
	return n
}

func (fs *fstate) jump(bs *bstate, from, to *ssa.BasicBlock) string {
	if fs.joining[to] {
		// (an arm of an if written in place ends: join.go)
		return fs.joinTuple(bs, from, to)
	}
	if fs.inlined(to) {
		sub := &bstate{fs: fs, heap: bs.heap, hn: bs.hn, tmp: bs.tmp, depth: bs.depth + bs.opens + 1}
		// phis take the value of the edge from this block
		idx := predIndex(to, from)
		for _, ins := range to.Instrs {
			phi, ok := ins.(*ssa.Phi)
			if !ok {
				break
			}
			sub.bind(fs.val(phi.Edges[idx]), fs.val(phi))
		}
		return "\n" + fs.blockExpr(sub, to)
	}
	args := []string{bs.heap}
	if fs.hasDefer {
		args = append(args, "DC")
	}
	idx := predIndex(to, from)
	for _, v := range fs.liveIn[to] {
		if phi, ok := v.(*ssa.Phi); ok && phi.Block() == to {
			args = append(args, fs.val(phi.Edges[idx]))
		} else {
			args = append(args, fs.val(v))
		}
	}
	return fmt.Sprintf("%s<%s>", fs.blockName(to), strings.Join(args, ", "))
}

// instr emits code for one instruction; returns the block's final expression for terminators.
func (fs *fstate) instr(bs *bstate, ins ssa.Instruction) string {
	c := fs.c
	switch x := ins.(type) {
	case *ssa.DebugRef, *ssa.Phi:
		return ""
	case *ssa.Jump:
		return fs.jump(bs, x.Block(), x.Block().Succs[0])
	case *ssa.If:
		if m := fs.joinAt(x.Block()); m != nil {
			return fs.joinIf(bs, x, m)
		}
		return fmt.Sprintf("%s extends true ? %s : %s", fs.val(x.Cond),
			fs.jump(bs, x.Block(), x.Block().Succs[0]), fs.jump(bs, x.Block(), x.Block().Succs[1]))
	case *ssa.Return:
		parts := []string{bs.heap}
		for _, r := range x.Results {
			parts = append(parts, fs.val(r))
		}
		if call, ok := bs.returnsLastCall(parts); ok {
			return call
		}
		// values written in place are bound first: a tuple literal with an
		// alias in it is a deferred type reference to the real checkers,
		// instantiated with every type parameter in scope at each return
		for i := 1; i < len(parts); i++ {
			if strings.ContainsAny(parts[i], "<?") {
				t := bs.newTmp()
				bs.bind(parts[i], t)
				parts[i] = t
			}
		}
		ret := "[" + strings.Join(parts, ", ") + "]"
		return ret
	case *ssa.Panic:
		return fmt.Sprintf("g.gpanic<%s, %s>", bs.heap, fs.val(x.X))
	case *ssa.RunDefers:
		if fs.hasDefer {
			if fs.r && fs.parent == nil {
				bs.callS(fmt.Sprintf("G_defersR<%s, DC>", bs.heap), nil, nil)
			} else {
				bs.call(fmt.Sprintf("G_defers<%s, DC>", bs.heap))
			}
		}
		return ""
	case *ssa.Defer:
		idx := 0
		for i, d := range fs.defers {
			if d == x {
				idx = i
			}
		}
		parts := []string{intLit(int64(fs.deferBase + idx))}
		_, isClosure := x.Call.Value.(*ssa.MakeClosure)
		_, isBuiltin := x.Call.Value.(*ssa.Builtin)
		if !isBuiltin && (x.Call.IsInvoke() || x.Call.StaticCallee() == nil || isClosure) {
			parts = append(parts, fs.val(x.Call.Value))
		}
		for _, a := range x.Call.Args {
			parts = append(parts, fs.val(a))
		}
		// the frame's deferred calls are in the heap cell DC: a list
		// [entry, rest] (null when empty), the last deferred first
		rest := bs.newTmp()
		bs.bind(fmt.Sprintf("g.hget<%s, DC>", bs.heap), rest)
		bs.setHeap(fmt.Sprintf("g.hset<%s, DC, %s>", bs.heap, bs.tupleOf(fmt.Sprintf("[[%s], %s]", strings.Join(parts, ", "), rest))))
		return ""
	case *ssa.Go:
		fs.goStmt(bs, x)
		return ""
	case *ssa.Store:
		if c.prefillStore(fs, x) {
			return ""
		}
		if e, check, ok := fs.fusedStore(bs, x); ok {
			if check {
				bs.setHeapChecked(e)
			} else {
				bs.setHeap(e)
			}
			return ""
		}
		if mayBeNil(x.Addr) {
			bs.setHeapChecked(c.storeExpr(bs.heap, fs.val(x.Addr), fs.val(x.Val), x.Val.Type()))
		} else {
			bs.setHeap(c.storeExpr(bs.heap, fs.val(x.Addr), fs.val(x.Val), x.Val.Type()))
		}
		return ""
	case *ssa.MapUpdate:
		bs.setHeapChecked(fmt.Sprintf("g.mupdate<%s, %s, %s, %s>", bs.heap, fs.val(x.Map), fs.val(x.Key), fs.val(x.Value)))
		return ""
	case *ssa.Send:
		elem := x.Chan.Type().Underlying().(*types.Chan).Elem()
		if e, susp := fs.chanCallR("tststChanSend", bs.heap, fs.val(x.Chan), c.box(fs.val(x.X), elem)); susp {
			bs.callS(e, nil, nil)
		} else {
			bs.call(e)
		}
		return ""
	case *ssa.Select:
		fs.selectStmt(bs, x)
		return ""
	case *ssa.Call:
		fs.callCommon(bs, &x.Call, x)
		return ""
	}
	v, ok := ins.(ssa.Value)
	if !ok {
		return c.fail(ins.Pos(), "unsupported instruction %T", ins)
	}
	name := fs.names[v]
	switch x := ins.(type) {
	case *ssa.Alloc:
		pat, ok := c.foldPattern[x]
		count := int64(1)
		if !ok {
			elem := x.Type().(*types.Pointer).Elem()
			pat = c.zeroCellsTuple(elem)
			// an array: its element's cells, as many times as it has elements
			if run, n := c.zeroRun(elem); n > 1 {
				pat, count = "["+strings.Join(run, ", ")+"]", n
			}
		}
		if a, ok := c.staticAlloc(x, pat, count); ok {
			bs.bind(intLit(a), name)
			break
		}
		bs.call(fmt.Sprintf("g.halloc<%s, %s, %s>", bs.heap, pat, intLit(count)), name)
	case *ssa.BinOp:
		if (x.Op == token.QUO || x.Op == token.REM) && isInteger(x.X.Type()) {
			// the division may fail (by zero); then its result wraps
			if k, ok := x.Y.(*ssa.Const); ok && k.Value != nil && constant.Sign(k.Value) != 0 {
				bs.bind(fs.binop(x), name)
				break
			}
			e := fs.binop(x)
			if inner, ok := strings.CutPrefix(e, "g.iwrap<"); ok {
				i := strings.LastIndex(inner, ", ")
				bs.bindChecked(inner[:i], name+"_q")
				bs.bind(fmt.Sprintf("g.iwrap<%s%s", name+"_q", inner[i:]), name)
			} else {
				bs.bindChecked(e, name)
			}
			break
		}
		fs.bindPure(bs, x, fs.binop(x), name)
	case *ssa.UnOp:
		switch x.Op {
		case token.MUL:
			if fv, ok := x.X.(*ssa.FreeVar); ok && c.freeByValue(fv) != nil {
				// captured by value: the variable's only value
				bs.bind(fs.val(fv), name)
			} else if e, check := fs.fusedLoad(bs, x); e != "" {
				if check {
					bs.bindChecked(e, name)
				} else {
					bs.bind(e, name)
				}
			} else if mayBeNil(x.X) {
				bs.bindChecked(c.loadExpr(bs.heap, fs.val(x.X), x.Type()), name)
			} else {
				bs.bind(c.loadExpr(bs.heap, fs.val(x.X), x.Type()), name)
			}
		case token.SUB:
			if isFloat(x.Type()) {
				fs.bindPure(bs, x, fmt.Sprintf("g.fneg<%s>", fs.val(x.X)), name)
			} else {
				fs.bindPure(bs, x, wrap(fmt.Sprintf("g.ineg<%s>", fs.val(x.X)), x.Type()), name)
			}
		case token.XOR:
			fs.bindPure(bs, x, wrap(fmt.Sprintf("g.inot<%s>", fs.val(x.X)), x.Type()), name)
		case token.NOT:
			fs.bindPure(bs, x, fmt.Sprintf("g.bnot<%s>", fs.val(x.X)), name)
		case token.ARROW:
			elem := x.X.Type().Underlying().(*types.Chan).Elem()
			post := func(bs *bstate) {
				if x.CommaOk {
					bs.bind(c.unbox(name+"_r", elem), name+"_0")
					bs.bind(name+"_ok", name+"_1")
				} else {
					bs.bind(c.unbox(name+"_r", elem), name)
				}
			}
			if e, susp := fs.chanCallR("tststChanRecv", bs.heap, fs.val(x.X)); susp {
				bs.callS(e, []string{name + "_r", name + "_ok"}, post)
			} else {
				bs.call(e, name+"_r", name+"_ok")
				post(bs)
			}
		default:
			bs.bind(c.fail(x.Pos(), "unsupported unary operator %s", x.Op), name)
		}
	case *ssa.ChangeType:
		fs.bindPure(bs, x, fs.val(x.X), name)
	case *ssa.ChangeInterface:
		fs.bindPure(bs, x, fs.val(x.X), name)
	case *ssa.Convert:
		fs.convert(bs, x, name)
	case *ssa.MultiConvert:
		bs.bind(c.fail(x.Pos(), "MultiConvert"), name)
	case *ssa.SliceToArrayPointer:
		bs.bind(fmt.Sprintf("g.sdata<%s>", fs.val(x.X)), name)
	case *ssa.MakeInterface:
		fs.bindPure(bs, x, fmt.Sprintf("[%dn, %s]", c.typeID(x.X.Type()), fs.val(x.X)), name)
	case *ssa.TypeAssert:
		fs.typeAssert(bs, x, name)
	case *ssa.Extract:
		// named in computeLiveness
	case *ssa.Field:
		fs.bindPure(bs, x, fmt.Sprintf("g.tget<%s, %s>", fs.val(x.X), intLit(int64(x.Field))), name)
	case *ssa.FieldAddr:
		st := x.X.Type().Underlying().(*types.Pointer).Elem().Underlying().(*types.Struct)
		if mayBeNil(x.X) {
			bs.bindChecked(fmt.Sprintf("g.padd<%s, %s>", fs.val(x.X), intLit(c.fieldOffset(st, x.Field))), name)
		} else if c.fieldOffset(st, x.Field) == 0 {
			// the first field of what is not nil: the same address
			bs.bind(fs.val(x.X), name)
		} else {
			bs.bind(fmt.Sprintf("g.padd<%s, %s>", fs.val(x.X), intLit(c.fieldOffset(st, x.Field))), name)
		}
	case *ssa.Index:
		if isString(x.X.Type()) {
			bs.bindChecked(fmt.Sprintf("g.sat<%s, %s>", fs.val(x.X), fs.val(x.Index)), name)
		} else {
			bs.bindChecked(fmt.Sprintf("g.vget<%s, %s>", fs.val(x.X), fs.val(x.Index)), name)
		}
	case *ssa.IndexAddr:
		switch u := x.X.Type().Underlying().(type) {
		case *types.Slice:
			bs.bindChecked(fmt.Sprintf("g.sidx<%s, %s, %s>", fs.val(x.X), fs.val(x.Index), intLit(c.cells(u.Elem()))), name)
		case *types.Pointer:
			arr := u.Elem().Underlying().(*types.Array)
			stride := c.cells(arr.Elem())
			idx := fs.val(x.Index)
			if stride != 1 {
				idx = fmt.Sprintf("g.imul<%s, %s>", idx, intLit(stride))
			}
			if mayBeNil(x.X) {
				bs.bindChecked(fmt.Sprintf("g.padd<%s, %s>", fs.val(x.X), idx), name)
			} else {
				bs.bind(fmt.Sprintf("g.padd<%s, %s>", fs.val(x.X), idx), name)
			}
		default:
			bs.bind(c.fail(x.Pos(), "IndexAddr on %s", x.X.Type()), name)
		}
	case *ssa.Lookup:
		if isString(x.X.Type()) {
			bs.bindChecked(fmt.Sprintf("g.sat<%s, %s>", fs.val(x.X), fs.val(x.Index)), name)
		} else {
			elem := x.X.Type().Underlying().(*types.Map).Elem()
			if x.CommaOk {
				bs.bindTuple(fmt.Sprintf("g.mlookup2<%s, %s, %s, %s>", bs.heap, fs.val(x.X), fs.val(x.Index), c.zero(elem)), name+"_0", name+"_1")
			} else {
				bs.bind(fmt.Sprintf("g.mlookup<%s, %s, %s, %s>", bs.heap, fs.val(x.X), fs.val(x.Index), c.zero(elem)), name)
			}
		}
	case *ssa.MakeMap:
		bs.call(fmt.Sprintf("g.halloc<%s, g.mnew, 1n>", bs.heap), name)
	case *ssa.MakeSlice:
		elem := x.Type().Underlying().(*types.Slice).Elem()
		bs.call(fmt.Sprintf("g.salloc<%s, %s, %s, %s>", bs.heap, fs.val(x.Len), fs.val(x.Cap), c.zeroCellsTuple(elem)), name)
	case *ssa.MakeChan:
		// channels are only created (and closed) by single-threaded code paths
		bs.call(c.chanCall("tststMakechan", bs.heap, fs.val(x.Size)), name)
	case *ssa.Slice:
		fs.slice(bs, x, name)
	case *ssa.MakeClosure:
		parts := []string{fmt.Sprintf("%dn", c.fid(x.Fn.(*ssa.Function)))}
		c.fname(x.Fn.(*ssa.Function))
		for i, bnd := range x.Bindings {
			if st := c.freeByValue(x.Fn.(*ssa.Function).FreeVars[i]); st != nil {
				// (the cell's value now: what was stored, the binding being live here)
				parts = append(parts, c.loadExpr(bs.heap, fs.val(bnd), bnd.Type().Underlying().(*types.Pointer).Elem()))
				continue
			}
			parts = append(parts, fs.val(bnd))
		}
		bs.bind("["+strings.Join(parts, ", ")+"]", name)
	case *ssa.Range:
		switch x.X.Type().Underlying().(type) {
		case *types.Map:
			bs.call(fmt.Sprintf("g.mrange<%s, %s>", bs.heap, fs.val(x.X)), name)
		default:
			if isString(x.X.Type()) {
				bs.call(fmt.Sprintf("g.srange<%s, %s>", bs.heap, fs.val(x.X)), name)
			} else {
				bs.bind(c.fail(x.Pos(), "range over %s", x.X.Type()), name)
			}
		}
	case *ssa.Next:
		if x.IsString {
			bs.call(fmt.Sprintf("g.snext<%s, %s>", bs.heap, fs.val(x.Iter)), name+"_0", name+"_1", name+"_2")
		} else {
			bs.call(fmt.Sprintf("g.mnext<%s, %s>", bs.heap, fs.val(x.Iter)), name+"_0", name+"_1", name+"_2")
		}
	default:
		bs.bind(c.fail(ins.Pos(), "unsupported instruction %T", ins), name)
	}
	return ""
}

func wrap(expr string, t types.Type) string {
	if k := wrapCode(t); k != 0 {
		return fmt.Sprintf("g.iwrap<%s, %dn>", expr, k)
	}
	return expr
}

func (fs *fstate) binop(x *ssa.BinOp) string {
	c := fs.c
	a, b := fs.val(x.X), fs.val(x.Y)
	t := x.X.Type()
	switch {
	case isString(t):
		switch x.Op {
		case token.ADD:
			return fmt.Sprintf("g.scat<%s, %s>", a, b)
		case token.EQL:
			return fmt.Sprintf("g.seq<%s, %s>", a, b)
		case token.NEQ:
			return fmt.Sprintf("g.bnot<g.seq<%s, %s>>", a, b)
		case token.LSS:
			return fmt.Sprintf("g.slt<%s, %s>", a, b)
		case token.GTR:
			return fmt.Sprintf("g.slt<%s, %s>", b, a)
		case token.LEQ:
			return fmt.Sprintf("g.bnot<g.slt<%s, %s>>", b, a)
		case token.GEQ:
			return fmt.Sprintf("g.bnot<g.slt<%s, %s>>", a, b)
		}
	case isFloat(t):
		switch x.Op {
		case token.ADD:
			return fmt.Sprintf("g.fadd<%s, %s>", a, b)
		case token.SUB:
			return fmt.Sprintf("g.fsub<%s, %s>", a, b)
		case token.MUL:
			return fmt.Sprintf("g.fmul<%s, %s>", a, b)
		case token.QUO:
			return fmt.Sprintf("g.fdiv<%s, %s>", a, b)
		case token.EQL:
			return fmt.Sprintf("g.feq<%s, %s>", a, b)
		case token.NEQ:
			return fmt.Sprintf("g.fne<%s, %s>", a, b)
		case token.LSS:
			return fmt.Sprintf("g.flt<%s, %s>", a, b)
		case token.GTR:
			return fmt.Sprintf("g.flt<%s, %s>", b, a)
		case token.LEQ:
			return fmt.Sprintf("g.fle<%s, %s>", a, b)
		case token.GEQ:
			return fmt.Sprintf("g.fle<%s, %s>", b, a)
		}
	case isInteger(t):
		u := isUnsigned(t)
		rt := x.Type()
		switch x.Op {
		case token.ADD:
			return wrap(fmt.Sprintf("g.iadd<%s, %s>", a, b), rt)
		case token.SUB:
			return wrap(fmt.Sprintf("g.isub<%s, %s>", a, b), rt)
		case token.MUL:
			return wrap(fmt.Sprintf("g.imul<%s, %s>", a, b), rt)
		case token.QUO:
			if u {
				return wrap(fmt.Sprintf("g.udiv<%s, %s>", a, b), rt)
			}
			return wrap(fmt.Sprintf("g.idiv<%s, %s>", a, b), rt)
		case token.REM:
			if u {
				return wrap(fmt.Sprintf("g.urem<%s, %s>", a, b), rt)
			}
			return wrap(fmt.Sprintf("g.irem<%s, %s>", a, b), rt)
		case token.AND:
			return fmt.Sprintf("g.iand<%s, %s>", a, b)
		case token.OR:
			return fmt.Sprintf("g.ior<%s, %s>", a, b)
		case token.XOR:
			return wrap(fmt.Sprintf("g.ixor<%s, %s>", a, b), rt)
		case token.AND_NOT:
			return fmt.Sprintf("g.iandnot<%s, %s>", a, b)
		case token.SHL:
			if isUnsigned(x.Y.Type()) {
				return wrap(fmt.Sprintf("g.ishl<%s, %s>", a, b), rt)
			}
			return wrap(fmt.Sprintf("g.ishl<%s, %s>", a, b), rt)
		case token.SHR:
			if u {
				return wrap(fmt.Sprintf("g.iushr<%s, %s>", a, b), rt)
			}
			return fmt.Sprintf("g.ishr<%s, %s>", a, b)
		case token.EQL:
			return fmt.Sprintf("g.ieq<%s, %s>", a, b)
		case token.NEQ:
			return fmt.Sprintf("g.ine<%s, %s>", a, b)
		case token.LSS:
			if u {
				return fmt.Sprintf("g.iult<%s, %s>", a, b)
			}
			return fmt.Sprintf("g.ilt<%s, %s>", a, b)
		case token.LEQ:
			if u {
				return fmt.Sprintf("g.iule<%s, %s>", a, b)
			}
			return fmt.Sprintf("g.ile<%s, %s>", a, b)
		case token.GTR:
			if u {
				return fmt.Sprintf("g.iugt<%s, %s>", a, b)
			}
			return fmt.Sprintf("g.igt<%s, %s>", a, b)
		case token.GEQ:
			if u {
				return fmt.Sprintf("g.iuge<%s, %s>", a, b)
			}
			return fmt.Sprintf("g.ige<%s, %s>", a, b)
		}
	case isBool(t):
		switch x.Op {
		case token.EQL:
			return fmt.Sprintf("g.geq<%s, %s>", a, b)
		case token.NEQ:
			return fmt.Sprintf("g.gne<%s, %s>", a, b)
		}
	default:
		switch x.Op {
		case token.EQL:
			return eqExpr(a, b, t)
		case token.NEQ:
			if e := eqExpr(a, b, t); !strings.HasPrefix(e, "g.geq<") {
				return fmt.Sprintf("g.bnot<%s>", e)
			}
			return fmt.Sprintf("g.gne<%s, %s>", a, b)
		}
	}
	return c.fail(x.Pos(), "unsupported binary operator %s on %s", x.Op, t)
}

// a == b for values of type t: floats compare as numbers (-0 == 0, NaN !=
// NaN), also inside structs, arrays and interfaces (G_ieq); the rest compare
// as values
func eqExpr(a, b string, t types.Type) string {
	if a == "null" || b == "null" || !mayHoldFloat(t, map[types.Type]bool{}) {
		return fmt.Sprintf("g.geq<%s, %s>", a, b)
	}
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return fmt.Sprintf("g.feq<%s, %s>", a, b)
	case *types.Interface:
		return fmt.Sprintf("G_ieq<%s, %s>", a, b)
	case *types.Struct:
		var parts []string
		for i := 0; i < u.NumFields(); i++ {
			if u.Field(i).Name() == "_" {
				continue
			}
			ft := u.Field(i).Type()
			parts = append(parts, eqExpr(fmt.Sprintf("g.tget<%s, %dn>", a, i), fmt.Sprintf("g.tget<%s, %dn>", b, i), ft))
		}
		return andAll(parts)
	case *types.Array:
		var parts []string
		for i := int64(0); i < u.Len(); i++ {
			parts = append(parts, eqExpr(fmt.Sprintf("g.tget<%s, %dn>", a, i), fmt.Sprintf("g.tget<%s, %dn>", b, i), u.Elem()))
		}
		return andAll(parts)
	}
	return fmt.Sprintf("g.geq<%s, %s>", a, b)
}

func andAll(parts []string) string {
	if len(parts) == 0 {
		return "true"
	}
	e := parts[len(parts)-1]
	for i := len(parts) - 2; i >= 0; i-- {
		e = fmt.Sprintf("(%s extends true ? %s : false)", parts[i], e)
	}
	return e
}

// whether a value of type t can hold a float (an interface may)
func mayHoldFloat(t types.Type, seen map[types.Type]bool) bool {
	if seen[t] {
		return false
	}
	seen[t] = true
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return u.Info()&types.IsFloat != 0
	case *types.Interface:
		return true
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			if mayHoldFloat(u.Field(i).Type(), seen) {
				return true
			}
		}
	case *types.Array:
		return mayHoldFloat(u.Elem(), seen)
	}
	return false
}

func (fs *fstate) convert(bs *bstate, x *ssa.Convert, name string) {
	c := fs.c
	from, to := x.X.Type(), x.Type()
	v := fs.val(x.X)
	fu, tu := from.Underlying(), to.Underlying()
	switch {
	case isInteger(from) && isInteger(to):
		if wrapCode(to) != 0 {
			bs.bind(wrap(v, to), name)
		} else {
			bs.bind(v, name)
		}
	case isInteger(from) && isFloat(to):
		if isUnsigned(from) {
			bs.bind(fmt.Sprintf("g.u2f<%s>", v), name)
		} else {
			bs.bind(fmt.Sprintf("g.i2f<%s>", v), name)
		}
	case isFloat(from) && isInteger(to):
		if isUnsigned(to) {
			bs.bind(wrap(fmt.Sprintf("g.f2u<%s>", v), to), name)
		} else {
			bs.bind(wrap(fmt.Sprintf("g.f2i<%s>", v), to), name)
		}
	case isFloat(from) && isFloat(to):
		if tb, ok := tu.(*types.Basic); ok && tb.Kind() == types.Float32 {
			bs.bind(fmt.Sprintf("g.fround32<%s>", v), name)
		} else {
			bs.bind(v, name)
		}
	case isInteger(from) && isString(to):
		bs.bind(fmt.Sprintf("g.runestr<%s>", v), name)
	case isString(from) && isString(to):
		bs.bind(v, name)
	case isString(from):
		if s, ok := tu.(*types.Slice); ok {
			if b, ok := s.Elem().Underlying().(*types.Basic); ok && b.Kind() == types.Int32 {
				bs.call(fmt.Sprintf("g.s2runesl<%s, %s>", bs.heap, v), name)
				return
			}
			bs.call(fmt.Sprintf("g.s2bytes<%s, %s>", bs.heap, v), name)
			return
		}
		bs.bind(c.fail(x.Pos(), "conversion %s -> %s", from, to), name)
	case isString(to):
		if s, ok := fu.(*types.Slice); ok {
			if b, ok := s.Elem().Underlying().(*types.Basic); ok && b.Kind() == types.Int32 {
				bs.bind(fmt.Sprintf("g.runes2sl<%s, %s>", bs.heap, v), name)
				return
			}
			bs.bind(fmt.Sprintf("g.bytes2s<%s, %s>", bs.heap, v), name)
			return
		}
		bs.bind(c.fail(x.Pos(), "conversion %s -> %s", from, to), name)
	default:
		if _, ok := fu.(*types.Basic); ok {
			if fb := fu.(*types.Basic); fb.Kind() == types.UnsafePointer {
				bs.bind(v, name)
				return
			}
		}
		if tb, ok := tu.(*types.Basic); ok && tb.Kind() == types.UnsafePointer {
			bs.bind(v, name)
			return
		}
		bs.bind(c.fail(x.Pos(), "conversion %s -> %s", from, to), name)
	}
}

func (fs *fstate) typeAssert(bs *bstate, x *ssa.TypeAssert, name string) {
	c := fs.c
	v := fs.val(x.X)
	if types.IsInterface(x.AssertedType) {
		impl := c.implAlias(x.AssertedType)
		if x.CommaOk {
			bs.bindTuple(fmt.Sprintf("%s extends null ? [null, false] : %s<g.tget<%s, 0n>> extends true ? [%s, true] : [null, false]", v, impl, v, v), name+"_0", name+"_1")
		} else {
			bs.bindChecked(fmt.Sprintf("%s extends null ? g.rterr<\"interface conversion: interface is nil\"> : %s<g.tget<%s, 0n>> extends true ? %s : g.rterr<%s>", v, impl, v, v, tsString("interface conversion: missing method for "+x.AssertedType.String())), name)
		}
		return
	}
	id := c.typeID(x.AssertedType)
	if x.CommaOk {
		bs.bindTuple(fmt.Sprintf("g.ta2<%s, %dn, %s>", v, id, c.zero(x.AssertedType)), name+"_0", name+"_1")
	} else {
		bs.bindChecked(fmt.Sprintf("g.ta1<%s, %dn>", v, id), name)
	}
}

func (fs *fstate) slice(bs *bstate, x *ssa.Slice, name string) {
	c := fs.c
	opt := func(v ssa.Value) string {
		if v == nil {
			return "null"
		}
		return fs.val(v)
	}
	switch u := x.X.Type().Underlying().(type) {
	case *types.Slice:
		bs.bind(fmt.Sprintf("g.reslice<%s, %s, %s, %s, %s>", fs.val(x.X), opt(x.Low), opt(x.High), opt(x.Max), intLit(c.cells(u.Elem()))), name)
	case *types.Pointer:
		arr := u.Elem().Underlying().(*types.Array)
		bs.bind(fmt.Sprintf("g.aslice<%s, %s, %s, %s, %s, %s>", fs.val(x.X), intLit(arr.Len()), opt(x.Low), opt(x.High), opt(x.Max), intLit(c.cells(arr.Elem()))), name)
	case *types.Basic:
		lo := "0n"
		if x.Low != nil {
			lo = fs.val(x.Low)
		}
		hi := fmt.Sprintf("g.slen<%s>", fs.val(x.X))
		if x.High != nil {
			hi = fs.val(x.High)
		}
		bs.bindChecked(fmt.Sprintf("g.sslice<%s, %s, %s>", fs.val(x.X), lo, hi), name)
	default:
		bs.bind(c.fail(x.Pos(), "slice of %s", x.X.Type()), name)
	}
}

// results: names to bind; ins may be nil (go statement)
func (fs *fstate) callCommon(bs *bstate, common *ssa.CallCommon, ins *ssa.Call) {
	c := fs.c
	var resNames []string
	if ins != nil {
		name := fs.names[ins]
		switch n := ins.Type().(type) {
		case *types.Tuple:
			for i := 0; i < n.Len(); i++ {
				resNames = append(resNames, name+"_"+strconv.Itoa(i))
			}
		default:
			if ins.Type() != nil {
				resNames = []string{name}
			}
		}
	}
	if b, ok := common.Value.(*ssa.Builtin); ok {
		fs.builtin(bs, b, common.Args, resNames, ins)
		return
	}
	args := []string{bs.heap}
	var callee string
	// in a resumable copy (or a go statement's thunk), a call that may
	// suspend goes to resumable copies (and saves a frame: callS)
	rcallee, susp := "", false
	if fs.r && fs.parent == nil || bs.rcall {
		rcallee, susp = fs.suspCallee(common)
	}
	emit := func(expr string) {
		if susp && !bs.rcall {
			bs.callS(expr, resNames, nil)
		} else {
			bs.call(expr, resNames...)
		}
	}
	if fn := common.StaticCallee(); fn != nil && fn.Name() == "tststGCanSuspend" && fn.Pkg != nil && fn.Pkg.Pkg.Path() == "runtime" {
		bs.call(fmt.Sprintf("[%s, %v]", bs.heap, fs.r && fs.parent == nil), resNames...)
		return
	}
	if common.IsInvoke() {
		callee = c.invokerFor(common)
		if susp {
			callee = rcallee
		}
		args = append(args, fs.val(common.Value))
	} else if fn := common.StaticCallee(); fn != nil {
		if fn.String() == "runtime.Caller" && ins != nil {
			if k, ok := common.Args[0].(*ssa.Const); ok && k.Int64() == 0 {
				// runtime.Caller(0): where this call is (the call stack is not known)
				pos := c.prog.Fset.Position(ins.Pos())
				bs.call(fmt.Sprintf("[%s, 1n, %s, %dn, true]", bs.heap, tsString(sourcePath(pos.Filename)), pos.Line), resNames...)
				return
			}
		}
		callee = c.fname(fn)
		if susp {
			callee = rcallee
		}
		if _, ok := common.Value.(*ssa.Function); ok && fn != fs.fn && !bs.noInline && !susp && c.inlinable(fn) && !fs.inlining(fn) &&
			!(fs.r && fs.parent == nil && !c.inlineIntoR(fn)) {
			bs.call(fs.inline(bs, fn, common.Args), resNames...)
			return
		}
		if !susp {
			if sp := fs.specFor(fn, common.Args); sp != "" {
				callee = sp
			}
		}
		if mc, ok := common.Value.(*ssa.MakeClosure); ok {
			for _, a := range common.Args {
				args = append(args, fs.val(a))
			}
			clo := fs.val(mc)
			for i := range mc.Bindings {
				args = append(args, fmt.Sprintf("g.tget<%s, %dn>", clo, i+1))
			}
			emit(fmt.Sprintf("%s<%s>", callee, strings.Join(args, ", ")))
			return
		}
	} else if kf := fs.knownFn(common.Value); kf != nil && !susp {
		// (a parameter known to be kf: spec.go)
		callee = c.fname(kf)
		if sp := fs.specFor(kf, common.Args); sp != "" {
			callee = sp
		}
		for _, a := range common.Args {
			args = append(args, fs.val(a))
		}
		clo := fs.val(common.Value)
		for i := range kf.FreeVars {
			args = append(args, fmt.Sprintf("g.tget<%s, %dn>", clo, i+1))
		}
		emit(fmt.Sprintf("%s<%s>", callee, strings.Join(args, ", ")))
		return
	} else {
		n := len(common.Args)
		if susp {
			callee = rcallee
		} else {
			c.callers[n] = true
			callee = "Call" + strconv.Itoa(n)
		}
		args = append(args, fs.val(common.Value))
	}
	for _, a := range common.Args {
		args = append(args, fs.val(a))
	}
	emit(fmt.Sprintf("%s<%s>", callee, strings.Join(args, ", ")))
}

// Small leaf functions (no calls but builtins, no loops or merges, no
// defers) are inlined at static call sites: their code becomes an
// expression of the call's result [H, results...].
var chanFuncs = []string{"tststGo", "tststMain", "tststYield", "tststRuntimeErr", "tststMakechan", "tststChanSend", "tststChanRecv", "tststChanTryRecv", "tststChanTrySend",
	"tststChanWaiting", "tststChanSendWaiting", "tststSelectPark", "tststChanClose", "tststChanLen", "tststChanCap"}

// a call of a function of the runtime's channel implementation
func (c *compiler) chanCall(name string, args ...string) string {
	f := c.chanFn[name]
	if f == nil {
		return c.fail(token.NoPos, "no %s (extra/runtime)", name)
	}
	return fmt.Sprintf("%s<%s>", c.fname(f), strings.Join(args, ", "))
}

// channel elements are boxed in interfaces
func (c *compiler) box(v string, t types.Type) string {
	if types.IsInterface(t) {
		return v
	}
	return fmt.Sprintf("[%dn, %s]", c.typeID(t), v)
}

func (c *compiler) unbox(v string, t types.Type) string {
	if types.IsInterface(t) {
		return v
	}
	return fmt.Sprintf("(%s extends null ? %s : g.tget<%s, 1n>)", v, c.zero(t), v)
}

// A closure's free variable that is a local's cell (an Alloc) is captured
// by value when the local is stored once, right before the closure is made
// (alloc, store, make closure in one block, in that order: each closure gets
// a fresh cell), nothing else stores to it or takes it, and the closure only
// loads it: the closure then holds the stored value instead of the cell, and
// its loads are that value. The store, or nil when captured by reference.
func (c *compiler) freeByValue(fv *ssa.FreeVar) *ssa.Store {
	if st, done := c.byValue[fv]; done {
		return st
	}
	st := func() *ssa.Store {
		f := fv.Parent()
		idx := -1
		for i, v := range f.FreeVars {
			if v == fv {
				idx = i
			}
		}
		for _, r := range *fv.Referrers() {
			switch x := r.(type) {
			case *ssa.UnOp:
				if x.Op != token.MUL {
					return nil
				}
			case *ssa.DebugRef:
			default:
				return nil
			}
		}
		parent := f.Parent()
		if parent == nil || idx < 0 {
			return nil
		}
		// the closure's only making
		var mc *ssa.MakeClosure
		for _, b := range parent.Blocks {
			for _, ins := range b.Instrs {
				if m, ok := ins.(*ssa.MakeClosure); ok && m.Fn == f {
					if mc != nil {
						return nil
					}
					mc = m
				}
			}
		}
		if mc == nil {
			return nil
		}
		alloc, ok := mc.Bindings[idx].(*ssa.Alloc)
		if !ok || alloc.Block() != mc.Block() {
			return nil
		}
		var store *ssa.Store
		for _, r := range *alloc.Referrers() {
			switch x := r.(type) {
			case *ssa.Store:
				if x.Addr != alloc || store != nil {
					return nil
				}
				store = x
			case *ssa.UnOp:
				if x.Op != token.MUL {
					return nil
				}
			case *ssa.MakeClosure:
				if x != mc {
					return nil
				}
			case *ssa.DebugRef:
			default:
				return nil
			}
		}
		if store == nil || store.Block() != mc.Block() {
			return nil
		}
		pos := func(ins ssa.Instruction) int {
			for i, x := range mc.Block().Instrs {
				if x == ins {
					return i
				}
			}
			return -1
		}
		if !(pos(alloc) < pos(store) && pos(store) < pos(mc)) {
			return nil
		}
		return store
	}()
	c.byValue[fv] = st
	return st
}

func (c *compiler) inlinable(f *ssa.Function) bool {
	if ok, done := c.inlineOK[f]; done {
		return ok
	}
	ok := func() bool {
		if len(f.Blocks) == 0 || f.Recover != nil || len(f.FreeVars) > 0 {
			return false
		}
		if _, ok := intrinsicBody(f); ok {
			return false
		}
		// (what emitFunc emits instead of the body: a redirect to another
		// package's function, an init skipped)
		if forwardTarget(f) != nil || isPkgInit(f) && c.deadInit[f.Pkg] {
			return false
		}
		// leaf functions of up to 40 instructions; and very small ones with
		// one call (getters, forwarders: the call costs more than the body).
		// Its blocks are all written in place: entered from one block, or
		// tiny returns, or joins of ifs (join.go)
		tmp := &fstate{c: c, fn: f}
		for _, blk := range f.Blocks {
			tmp.joinAt(blk)
		}
		n, calls := 0, 0
		for i, blk := range f.Blocks {
			if i == 0 && len(blk.Preds) != 0 || i > 0 && !tmp.inlined(blk) {
				return false
			}
			for _, ins := range blk.Instrs {
				n++
				switch x := ins.(type) {
				case *ssa.Call:
					if _, ok := x.Call.Value.(*ssa.Builtin); !ok {
						// (a static call or a method call on an interface)
						if _, ok := x.Call.Value.(*ssa.Function); !ok && !x.Call.IsInvoke() {
							return false
						}
						calls++
					}
				case *ssa.Defer, *ssa.Go, *ssa.Select, *ssa.RunDefers:
					return false
				}
			}
		}
		if calls > 0 {
			return calls == 1 && n <= 12
		}
		return n <= 40
	}()
	c.inlineOK[f] = ok
	return ok
}

// whether f is being inlined already (or is the function inlining), or the
// inlining is nested deep: calls in an inlined body stay calls then
func (fs *fstate) inlining(f *ssa.Function) bool {
	depth := 0
	for x := fs; x != nil; x = x.parent {
		if x.fn == f {
			return true
		}
		depth++
	}
	return depth > 3
}

func (fs *fstate) inline(bs *bstate, f *ssa.Function, args []ssa.Value) string {
	fs.inlines++
	sub := &fstate{c: fs.c, fn: f, name: fs.c.fname(f), names: map[ssa.Value]string{},
		prefix: fmt.Sprintf("%si%d_", fs.prefix, fs.inlines), parent: fs}
	for i, p := range f.Params {
		sub.names[p] = fs.val(args[i])
		if kf := fs.knownFn(args[i]); kf != nil && fs.c.isFuncValue(kf) {
			if sub.known == nil {
				sub.known = map[ssa.Value]*ssa.Function{}
			}
			sub.known[p] = kf
		}
	}
	// (as the function's own code: its folded constants are named in sub)
	sub.appendValues()
	sub.foldConstants()
	sub.liftLocals()
	sub.fuseFields()
	sub.computeLiveness()
	return sub.blockExpr(&bstate{fs: sub, heap: bs.heap, hn: bs.hn, tmp: bs.tmp, depth: bs.depth + bs.opens + 1}, f.Blocks[0])
}

// select: an alias per statement tries the cases in order; when none can
// proceed and the select blocks, it parks as a receiver on its receive
// channels and tries again. Its result is the Select tuple
// [H, index, recvOK, values received by the receive cases...].
func (fs *fstate) selectStmt(bs *bstate, x *ssa.Select) {
	c := fs.c
	fs.selects++
	alias := fmt.Sprintf("%s_sel%d", fs.name, fs.selects)
	var params, args, zeros []string
	for i, st := range x.States {
		params = append(params, fmt.Sprintf("C%d", i))
		args = append(args, fs.val(st.Chan))
		if st.Dir == types.SendOnly {
			params = append(params, fmt.Sprintf("S%d", i))
			args = append(args, c.box(fs.val(st.Send), st.Chan.Type().Underlying().(*types.Chan).Elem()))
		} else {
			zeros = append(zeros, c.zero(st.Chan.Type().Underlying().(*types.Chan).Elem()))
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "type %s<%s> =\n", alias, strings.Join(append([]string{"H"}, params...), ", "))
	k := 0
	closes := 0
	for i, st := range x.States {
		if st.Dir == types.SendOnly {
			fmt.Fprintf(&b, "  %s extends [infer H, infer ok] ? ok extends true ? [H, %dn, false, %s] :\n",
				c.chanCall("tststChanTrySend", "H", fmt.Sprintf("C%d", i), fmt.Sprintf("S%d", i)), i, strings.Join(zeros, ", "))
		} else {
			vals := append([]string{}, zeros...)
			vals[k] = c.unbox("v", st.Chan.Type().Underlying().(*types.Chan).Elem())
			fmt.Fprintf(&b, "  %s extends [infer H, infer v, infer ok, infer ready] ? ready extends true ? [H, %dn, ok, %s] :\n",
				c.chanCall("tststChanTryRecv", "H", fmt.Sprintf("C%d", i)), i, strings.Join(vals, ", "))
			k++
		}
		closes++
	}
	// (in a resumable copy, the wait may suspend: its continuation tries
	// again; the call of the alias too)
	susp := false
	if !x.Blocking {
		// the default case lets other goroutines run first: goroutines switch
		// only where they wait, and a loop polling with select would otherwise
		// keep the others from ever running
		ret := fmt.Sprintf("[H, -1n, false, %s]", strings.Join(zeros, ", "))
		y, s := fs.chanCallR("tststYield", "H")
		if s {
			susp = true
			frame := c.handCont(alias+"_k", fs.fn, nil, func(frame string) string {
				return fmt.Sprintf("X extends [infer H] ? %s : G_susp<X, %s>", ret, frame)
			})
			fmt.Fprintf(&b, "  %s extends infer XP ? XP extends [infer H] ? %s : G_susp<XP, %s> : 0", y, ret, frame)
		} else {
			fmt.Fprintf(&b, "  %s extends [infer H] ? %s : 0", y, ret)
		}
	} else {
		// park as a receiver on the receive channels and a sender on the
		// send channels, then try again
		var reg, unreg string
		n := 0
		for i, st := range x.States {
			f := "tststChanWaiting"
			if st.Dir == types.SendOnly {
				f = "tststChanSendWaiting"
			}
			reg += fmt.Sprintf("%s extends [infer H] ? ", c.chanCall(f, "H", fmt.Sprintf("C%d", i), "1n"))
			unreg += fmt.Sprintf("%s extends [infer H] ? ", c.chanCall(f, "H", fmt.Sprintf("C%d", i), "-1n"))
			n++
		}
		again := fmt.Sprintf("%s%s<%s>%s", unreg, alias, strings.Join(append([]string{"H"}, params...), ", "), strings.Repeat(" : 0", n))
		p, s := fs.chanCallR("tststSelectPark", "H")
		if s {
			susp = true
			frame := c.handCont(alias+"_k", fs.fn, params, func(frame string) string {
				return fmt.Sprintf("X extends [infer H] ? %s : G_susp<X, %s>", again, frame)
			})
			fmt.Fprintf(&b, "  %s%s extends infer XP ? XP extends [infer H] ? %s : G_susp<XP, %s> : 0%s", reg, p, again, frame, strings.Repeat(" : 0", n))
		} else {
			fmt.Fprintf(&b, "  %s%s extends [infer H] ? %s : 0%s", reg, p, again, strings.Repeat(" : 0", n))
		}
	}
	for i := 0; i < closes; i++ {
		b.WriteString(" : 0")
	}
	b.WriteString(";\n")
	fs.c.helpers = append(fs.c.helpers, b.String())
	name := fs.names[x]
	names := []string{name + "_0", name + "_1"}
	for i := 2; i < 2+len(zeros); i++ {
		names = append(names, name+"_"+strconv.Itoa(i))
	}
	call := fmt.Sprintf("%s<%s>", alias, strings.Join(append([]string{bs.heap}, args...), ", "))
	if susp {
		bs.callS(call, names, nil)
	} else {
		bs.call(call, names...)
	}
}

func (fs *fstate) builtin(bs *bstate, b *ssa.Builtin, args []ssa.Value, res []string, ins *ssa.Call) {
	c := fs.c
	one := func(expr string) {
		if len(res) == 1 {
			bs.bind(expr, res[0])
		}
	}
	switch b.Name() {
	case "len", "cap":
		t := args[0].Type().Underlying()
		if p, ok := t.(*types.Pointer); ok {
			t = p.Elem().Underlying()
		}
		v := fs.val(args[0])
		switch u := t.(type) {
		case *types.Basic:
			one(fmt.Sprintf("g.slen<%s>", v))
		case *types.Slice:
			if b.Name() == "len" {
				one(fmt.Sprintf("g.tget<%s, 1n>", v))
			} else {
				one(fmt.Sprintf("g.tget<%s, 2n>", v))
			}
		case *types.Map:
			one(fmt.Sprintf("g.mlen_<%s, %s>", bs.heap, v))
		case *types.Array:
			one(intLit(u.Len()))
		case *types.Chan:
			if b.Name() == "len" {
				bs.call(c.chanCall("tststChanLen", bs.heap, v), res...)
			} else {
				bs.call(c.chanCall("tststChanCap", bs.heap, v), res...)
			}
		default:
			one(c.fail(ins.Pos(), "len of %s", t))
		}
	case "append":
		st := args[0].Type().Underlying().(*types.Slice)
		elem := st.Elem()
		noscan := "true"
		if hasPointers(elem) {
			noscan = "false"
		}
		if c.cells(elem) == 0 {
			// elements without cells (struct{}): only the length changes
			sv, tv := fs.val(args[0]), fs.val(args[1])
			n := fmt.Sprintf("g.iadd<g.tget<%s, 1n>, g.tget<%s, 1n>>", sv, tv)
			bs.call(fmt.Sprintf("[%s, [g.tget<%s, 0n> extends null ? g.hget<%s, 0n> : g.tget<%s, 0n>, %s, g.igt<%s, g.tget<%s, 2n>> extends true ? %s : g.tget<%s, 2n>]]",
				bs.heap, sv, bs.heap, sv, n, n, sv, n, sv), res...)
			break
		}
		if vals, ok := fs.varargsOf(ins); ok {
			items := make([]string, len(vals))
			for i, v := range vals {
				items[i] = fs.val(v)
			}
			bs.call(fmt.Sprintf("g.sappendv<%s, %s, [%s], %s, %s, %s, %s>", bs.heap, fs.val(args[0]), strings.Join(items, ", "),
				c.zeroCellsTuple(elem), intLit(c.cells(elem)), intLit(c.elemSize(elem)), noscan), res...)
			break
		}
		bs.call(fmt.Sprintf("g.sappend<%s, %s, %s, %s, %s, %s, %s>", bs.heap, fs.val(args[0]), fs.val(args[1]),
			c.zeroCellsTuple(elem), intLit(c.cells(elem)), intLit(c.elemSize(elem)), noscan), res...)
	case "copy":
		et := args[0].Type().Underlying().(*types.Slice).Elem()
		bs.call(fmt.Sprintf("g.scopy<%s, %s, %s, %s>", bs.heap, fs.val(args[0]), fs.val(args[1]), intLit(c.cells(et))), res...)
	case "delete":
		bs.setHeap(fmt.Sprintf("g.mdelete<%s, %s, %s>", bs.heap, fs.val(args[0]), fs.val(args[1])))
	case "print", "println":
		var parts []string
		for i, a := range args {
			if i > 0 && b.Name() == "println" {
				parts = append(parts, `" "`)
			}
			parts = append(parts, fs.printArg(a))
		}
		if b.Name() == "println" {
			parts = append(parts, `"\n"`)
		}
		for _, p := range parts {
			bs.setHeap(fmt.Sprintf("rt.gprint<%s, %s>", bs.heap, p))
		}
	case "min", "max":
		t := args[0].Type()
		pre := "i"
		if isFloat(t) {
			pre = "f"
		} else if isString(t) {
			pre = "s"
		}
		cur := fs.val(args[0])
		for _, a := range args[1:] {
			cur = fmt.Sprintf("rt.%s%s<%s, %s>", pre, b.Name(), cur, fs.val(a))
		}
		one(cur)
	case "recover":
		bs.call(fmt.Sprintf("g.grecover<%s>", bs.heap), res...)
	case "close":
		bs.call(c.chanCall("tststChanClose", bs.heap, fs.val(args[0])))
	case "Sizeof":
		one(intLit(c.sizes.Sizeof(args[0].Type())))
	case "Alignof":
		one(intLit(c.sizes.Alignof(args[0].Type())))
	case "String":
		one(fmt.Sprintf("g.ptrstr<%s, %s, %s>", bs.heap, fs.val(args[0]), fs.val(args[1])))
	case "SliceData":
		one(fmt.Sprintf("g.sdata<%s>", fs.val(args[0])))
	case "StringData":
		// strings are values: materialize the bytes in fresh cells
		bs.call(fmt.Sprintf("g.s2bytes<%s, %s>", bs.heap, fs.val(args[0])), res[0]+"_sl")
		one(fmt.Sprintf("g.tget<%s, 0n>", res[0]+"_sl"))
	case "Add":
		// unsafe.Add(ptr, len): offsets count cells (a byte or a scalar field
		// takes one)
		one(fmt.Sprintf("g.padd<%s, %s>", fs.val(args[0]), fs.val(args[1])))
	case "Slice":
		// unsafe.Slice(ptr, len)
		one(fmt.Sprintf("[%s, %s, %s]", fs.val(args[0]), fs.val(args[1]), fs.val(args[1])))
	case "ssa:wrapnilchk":
		if len(res) == 1 {
			bs.bindChecked(fmt.Sprintf("g.nilchk<%s>", fs.val(args[0])), res[0])
		}
	case "clear":
		t := args[0].Type().Underlying()
		if _, ok := t.(*types.Map); ok {
			bs.setHeap(fmt.Sprintf("%s extends null ? %s : g.hset<%s, %s, g.mnew>", fs.val(args[0]), bs.heap, bs.heap, fs.val(args[0])))
		} else if st, ok := t.(*types.Slice); ok {
			bs.setHeap(fmt.Sprintf("g.sclear<%s, %s, %s>", bs.heap, fs.val(args[0]), c.zeroCellsTuple(st.Elem())))
		} else {
			bs.setHeap(c.fail(ins.Pos(), "clear of %s", t))
		}
	default:
		if len(res) > 0 {
			one(c.fail(token.NoPos, "builtin %s", b.Name()))
		} else {
			bs.setHeap(c.fail(token.NoPos, "builtin %s", b.Name()))
		}
	}
}

func (fs *fstate) printArg(a ssa.Value) string {
	t := a.Type()
	v := fs.val(a)
	switch {
	case isString(t):
		return v
	case isInteger(t):
		if isUnsigned(t) {
			return fmt.Sprintf("g.uitoa<%s>", v)
		}
		return fmt.Sprintf("g.itoa<%s>", v)
	case isFloat(t):
		return fmt.Sprintf("g.ftoa<%s>", v)
	case isBool(t):
		return fmt.Sprintf("(%s extends true ? \"true\" : \"false\")", v)
	}
	return `"?"`
}

// Panics are values {tstst_panic: value, heap: heap} that calls pass
// through (see bstate.call) up to a function with defers. Such a function
// keeps its deferred calls in a heap cell DC and runs its body; when the body
// panics, it runs the deferred calls with the panic in cell 3, where recover
// takes it. If one does, the function returns what its Recover block
// computes from the named results (allocated before the body, so both parts
// see them); otherwise the panic goes on.
func (fs *fstate) emitDeferFunc(b *strings.Builder, params []string) {
	f := fs.fn
	c := fs.c
	fs.prebound = map[ssa.Value]bool{}
	var pre []ssa.Value
	if f.Recover != nil {
		pre = fs.liveIn[f.Recover]
	}
	bs := &bstate{fs: fs, heap: "H"}
	bs.call(fmt.Sprintf("g.halloc<%s, null, 1n>", bs.heap), "DC")
	for _, v := range pre {
		a, ok := v.(*ssa.Alloc)
		if !ok || a.Block() != f.Blocks[0] {
			c.fail(f.Pos(), "unsupported value live into the Recover block")
			continue
		}
		fs.names[v] = fs.vname(v)
		fs.instr(bs, a)
		fs.prebound[v] = true
	}
	var preNames []string
	for _, v := range pre {
		preNames = append(preNames, fs.names[v])
	}
	bodyParams := append(append([]string{"H"}, params[1:]...), "DC")
	bodyParams = append(bodyParams, preNames...)
	bodyArgs := append(append([]string{bs.heap}, params[1:]...), "DC")
	bodyArgs = append(bodyArgs, preNames...)
	r := bs.newTmp()
	bs.bind(fmt.Sprintf("%s_body<%s>", fs.name, strings.Join(bodyArgs, ", ")), r)
	recover := "[H2"
	if f.Recover != nil {
		args := []string{"H2"}
		if fs.hasDefer {
			args = append(args, "DC")
		}
		args = append(args, preNames...)
		recover = fmt.Sprintf("%s<%s>", fs.blockName(f.Recover), strings.Join(args, ", "))
	} else {
		for i := 0; i < f.Signature.Results().Len(); i++ {
			recover += ", " + c.zero(f.Signature.Results().At(i).Type())
		}
		recover += "]"
	}
	term := func(r, ret string) string {
		return fmt.Sprintf(
			"%s extends { tstst_panic: infer V; heap: infer HP } ? g.gunwind<HP, V> extends infer HU ? G_rundefers<HU, DC> extends infer H2 ? g.hget<H2, 3n> extends null ? %s : { tstst_panic: g.tget<g.hget<H2, 3n>, 0n>; heap: g.hset<H2, 3n, null> } : 0 : 0 : %s",
			r, recover, ret)
	}
	fmt.Fprintf(b, "export type %s<%s> =\n", fs.name, strings.Join(params, ", "))
	if fs.r {
		// a suspension of the body, or of a deferred call run while
		// panicking (G_rundefersR), gets the frame of what follows it here
		kparams := append([]string{"DC"}, preNames...)
		pid := c.newCont(fs.name+"_kp", fs.fn)
		pframe := fmt.Sprintf("[%dn, %s]", pid, strings.Join(kparams, ", "))
		after := func(rd string) string {
			return fmt.Sprintf("%s extends [infer H2] ? g.hget<H2, 3n> extends null ? %s : { tstst_panic: g.tget<g.hget<H2, 3n>, 0n>; heap: g.hset<H2, 3n, null> } : G_susp<%s, %s>",
				rd, recover, rd, pframe)
		}
		termR := func(r, ret string) string {
			return fmt.Sprintf("%s extends { tstst_panic: infer V; heap: infer HP } ? g.gunwind<HP, V> extends infer HU ? G_rundefersR<HU, DC> extends infer RD ? %s : 0 : 0 : %s",
				r, after("RD"), ret)
		}
		id := c.newCont(fs.name+"_kd", fs.fn)
		frame := fmt.Sprintf("[%dn, %s]", id, strings.Join(kparams, ", "))
		b.WriteString(fs.closeExpr(bs, termR(r, fmt.Sprintf("G_susp<%s, %s>", r, frame))))
		b.WriteString(";\n")
		ps := strings.Join(append([]string{"X"}, kparams...), ", ")
		fmt.Fprintf(b, "type %s_kd<%s> = %s;\n", fs.name, ps, termR("X", fmt.Sprintf("G_susp<X, %s>", frame)))
		fmt.Fprintf(b, "type %s_kp<%s> = %s;\n", fs.name, ps, after("X"))
		c.contAliases = append(c.contAliases, contAlias{fs.name + "_kd", id, len(kparams)}, contAlias{fs.name + "_kp", pid, len(kparams)})
		c.rDefers = true
	} else {
		b.WriteString(fs.closeExpr(bs, term(r, r)))
		b.WriteString(";\n")
	}
	if c.rtCatch {
		// a runtime error in the body is a panic (G_rtpanic) the deferred calls see
		b.WriteString("/** @catch G_rtpanic */\n")
	}
	fmt.Fprintf(b, "type %s_body<%s> =\n", fs.name, strings.Join(bodyParams, ", "))
	if len(f.Blocks[0].Preds) == 0 {
		b.WriteString(fs.blockExpr(&bstate{fs: fs, heap: "H"}, f.Blocks[0]))
		b.WriteString(";\n")
		for _, blk := range f.Blocks[1:] {
			fs.emitBlock(b, blk)
		}
	} else {
		args := []string{"H", "DC"}
		for _, v := range fs.liveIn[f.Blocks[0]] {
			args = append(args, fs.names[v])
		}
		fmt.Fprintf(b, "  %s<%s>;\n", fs.blockName(f.Blocks[0]), strings.Join(args, ", "))
		for _, blk := range f.Blocks {
			fs.emitBlock(b, blk)
		}
	}
	fs.emitDeferRunner(b)
	fs.emitConts(b)
	b.WriteString("\n")
}

// the expression term after the lines bound so far in bs
func (fs *fstate) closeExpr(bs *bstate, term string) string {
	var b strings.Builder
	for _, l := range bs.lines {
		b.WriteString(l)
		b.WriteString("\n")
	}
	b.WriteString("  ")
	b.WriteString(term)
	b.WriteString(bs.closings())
	return b.String()
}

func (fs *fstate) emitDeferRunner(b *strings.Builder) {
	// the deferred calls are entries of G_defer, keyed by their program-wide
	// id (one runner for every function, emitDeferRunners)
	c := fs.c
	for i, d := range fs.defers {
		var callee string
		args := []string{"H"}
		k := 1
		common := &d.Call
		if bi, ok := common.Value.(*ssa.Builtin); ok {
			// the builtin's code, with its arguments taken from the entry
			saved := map[ssa.Value]string{}
			for j, a := range common.Args {
				if n, ok := fs.names[a]; ok {
					saved[a] = n
				}
				fs.names[a] = fmt.Sprintf("g.tget<E, %dn>", j+1)
			}
			sub := &bstate{fs: fs, heap: "H", noInline: true}
			fs.builtin(sub, bi, common.Args, nil, nil)
			e := fmt.Sprintf("  \"%d\": (%s);\n", fs.deferBase+i, fs.closeExpr(sub, "["+sub.heap+"]"))
			if fs.r {
				c.deferEntriesR = append(c.deferEntriesR, e)
			} else {
				c.deferEntries = append(c.deferEntries, e)
			}
			for _, a := range common.Args {
				delete(fs.names, a)
				if n, ok := saved[a]; ok {
					fs.names[a] = n
				}
			}
			continue
		}
		// (a resumable copy's deferred calls go to resumable copies: G_deferR)
		rcallee, susp := "", false
		if fs.r {
			rcallee, susp = fs.suspCallee(common)
		}
		if common.IsInvoke() {
			callee = fs.c.invokerFor(common)
			if susp {
				callee = rcallee
			}
			args = append(args, "g.tget<E, 1n>")
			k = 2
		} else if fn := common.StaticCallee(); fn != nil {
			if _, isClosure := common.Value.(*ssa.MakeClosure); isClosure {
				n := len(common.Args)
				if fs.r && fs.c.funcValSusp(common) {
					fs.c.callersS[n] = true
					callee = "CallS" + strconv.Itoa(n)
				} else {
					fs.c.callers[n] = true
					callee = "Call" + strconv.Itoa(n)
				}
				args = append(args, "g.tget<E, 1n>")
				k = 2
			} else {
				callee = fs.c.fname(fn)
				if susp {
					callee = rcallee
				}
			}
		} else {
			n := len(common.Args)
			if susp {
				callee = rcallee
			} else {
				fs.c.callers[n] = true
				callee = "Call" + strconv.Itoa(n)
			}
			args = append(args, "g.tget<E, 1n>")
			k = 2
		}
		for j := range common.Args {
			args = append(args, fmt.Sprintf("g.tget<E, %dn>", j+k))
		}
		e := fmt.Sprintf("  \"%d\": %s<%s>;\n", fs.deferBase+i, callee, strings.Join(args, ", "))
		if fs.r {
			c.deferEntriesR = append(c.deferEntriesR, e)
		} else {
			c.deferEntries = append(c.deferEntries, e)
		}
	}
}

// The runners of deferred calls, for every function: G_defers runs them in
// LIFO order at a normal return, each taken off the list in the cell DC
// first, a panic in one going on as the function's result ([H] or a panic);
// G_rundefers while panicking (the panic in cell 3: one in a deferred call
// replaces it), returning the heap; G_defer is one deferred call.
func (c *compiler) emitDeferRunners(b *strings.Builder) {
	if len(c.deferEntries) == 0 {
		return
	}
	b.WriteString("type G_defers<H, DC> = g.hget<H, DC> extends [infer E, infer R] ? G_defer<g.hset<H, DC, R>, E> extends infer X ? X extends [infer H2, ...infer _] ? G_defers<H2, DC> : X : 0 : [H];\n")
	b.WriteString("type G_rundefers<H, DC> = g.hget<H, DC> extends [infer E, infer R] ? G_defer<g.hset<H, DC, R>, E> extends infer X ? X extends [infer H2, ...infer _] ? G_rundefers<H2, DC> : X extends { tstst_panic: infer V; heap: infer HP } ? G_rundefers<g.gunwind<HP, V>, DC> : 0 : 0 : H;\n")
	b.WriteString("type G_defer<H, E> = " + tableOpen("g.tget<E, 0n>") + "\n")
	for _, e := range c.deferEntries {
		b.WriteString(e)
	}
	b.WriteString(tableClose("never") + ";\n\n")
	if !c.rDefers {
		return
	}
	// the runners of resumable copies: a suspension of a deferred call gets
	// the frame of the runner's rest (G_rundefersR returns [H])
	kd := c.handCont("G_kdefers", nil, []string{"DC"}, func(frame string) string {
		return fmt.Sprintf("X extends [infer H2, ...infer _] ? G_defersR<H2, DC> : G_susp<X, %s>", frame)
	})
	krd := c.handCont("G_krundefers", nil, []string{"DC"}, func(frame string) string {
		return fmt.Sprintf("X extends [infer H2, ...infer _] ? G_rundefersR<H2, DC> : X extends { tstst_panic: infer V; heap: infer HP } ? G_rundefersR<g.gunwind<HP, V>, DC> : G_susp<X, %s>", frame)
	})
	fmt.Fprintf(b, "type G_defersR<H, DC> = g.hget<H, DC> extends [infer E, infer R] ? G_deferR<g.hset<H, DC, R>, E> extends infer X ? X extends [infer H2, ...infer _] ? G_defersR<H2, DC> : G_susp<X, %s> : 0 : [H];\n", kd)
	fmt.Fprintf(b, "type G_rundefersR<H, DC> = g.hget<H, DC> extends [infer E, infer R] ? G_deferR<g.hset<H, DC, R>, E> extends infer X ? X extends [infer H2, ...infer _] ? G_rundefersR<H2, DC> : X extends { tstst_panic: infer V; heap: infer HP } ? G_rundefersR<g.gunwind<HP, V>, DC> : G_susp<X, %s> : 0 : [H];\n", krd)
	b.WriteString("type G_deferR<H, E> = " + tableOpen("g.tget<E, 0n>") + "\n")
	for _, e := range c.deferEntriesR {
		b.WriteString(e)
	}
	b.WriteString(tableClose("never") + ";\n\n")
}

