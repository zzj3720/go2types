// Memory layout: every value occupies cells; structs and arrays are flattened.

func (c *compiler) cells(t types.Type) int64 {
	switch u := t.Underlying().(type) {
	case *types.Struct:
		var n int64
		for i := 0; i < u.NumFields(); i++ {
			n += c.cells(u.Field(i).Type())
		}
		return n
	case *types.Array:
		return u.Len() * c.cells(u.Elem())
	}
	return 1
}

func (c *compiler) fieldOffset(st *types.Struct, field int) int64 {
	var off int64
	for i := 0; i < field; i++ {
		off += c.cells(st.Field(i).Type())
	}
	return off
}

// flattened zero cells of a type
func (c *compiler) zeroCells(t types.Type) []string {
	switch u := t.Underlying().(type) {
	case *types.Struct:
		var out []string
		for i := 0; i < u.NumFields(); i++ {
			out = append(out, c.zeroCells(u.Field(i).Type())...)
		}
		return out
	case *types.Array:
		elem := c.zeroCells(u.Elem())
		var out []string
		for i := int64(0); i < u.Len(); i++ {
			out = append(out, elem...)
		}
		return out
	}
	return []string{c.zero(t)}
}

func (c *compiler) zeroCellsTuple(t types.Type) string {
	z := c.zeroCells(t)
	if len(z) == 1 && c.isScalarCell(t) {
		return z[0]
	}
	return "[" + strings.Join(z, ", ") + "]"
}

// a single cell whose zero value is not itself a tuple pattern
func (c *compiler) isScalarCell(t types.Type) bool {
	switch t.Underlying().(type) {
	case *types.Struct, *types.Array, *types.Slice:
		return false
	}
	return true
}

func (c *compiler) loadExpr(h, p string, t types.Type) string {
	if c.cells(t) == 1 {
		if _, ok := t.Underlying().(*types.Struct); !ok {
			if _, ok := t.Underlying().(*types.Array); !ok {
				return fmt.Sprintf("g.hget<%s, %s>", h, p)
			}
		}
	}
	return fmt.Sprintf("%s<%s, %s>", c.loader(t), h, p)
}

func (c *compiler) storeExpr(h, p, v string, t types.Type) string {
	if c.cells(t) == 1 {
		if _, ok := t.Underlying().(*types.Struct); !ok {
			if _, ok := t.Underlying().(*types.Array); !ok {
				return fmt.Sprintf("g.hset<%s, %s, %s>", h, p, v)
			}
		}
	}
	return fmt.Sprintf("%s<%s, %s, %s>", c.storer(t), h, p, v)
}

// layout descriptor of a type: "s" scalar cell, "(...)" struct, "[N...]" array
func (c *compiler) layout(t types.Type) string {
	switch u := t.Underlying().(type) {
	case *types.Struct:
		var b strings.Builder
		b.WriteByte('(')
		for i := 0; i < u.NumFields(); i++ {
			b.WriteString(c.layout(u.Field(i).Type()))
		}
		b.WriteByte(')')
		return b.String()
	case *types.Array:
		return "[" + strconv.FormatInt(u.Len(), 10) + c.layout(u.Elem()) + "]"
	}
	return "s"
}

func (c *compiler) loader(t types.Type) string {
	if v := c.loaders.At(t); v != nil {
		return v.(string)
	}
	name := c.newName("LD", c.layout(t))
	c.loaders.Set(t, name)
	c.helpers = append(c.helpers, fmt.Sprintf("type %s<H, P> = g.hloadt<H, P, %q>;\n", name, c.layout(t)))
	return name
}

func (c *compiler) storer(t types.Type) string {
	if v := c.storers.At(t); v != nil {
		return v.(string)
	}
	name := c.newName("ST", c.layout(t))
	c.storers.Set(t, name)
	c.helpers = append(c.helpers, fmt.Sprintf("type %s<H, P, V> = g.hstoret<H, P, V, %q>;\n", name, c.layout(t)))
	return name
}

// the content of a string variable with a //go:embed directive (one file);
// the bundled lib files come in the program's input instead. The directive
// comes from the parsed files and the file's content from the file system or
// the pack (scanEmbeds, readEmbed): a go2types on tstst has no file system.
func (c *compiler) embedded(g *ssa.Global) (string, bool) {
	t, ok := g.Type().(*types.Pointer).Elem().(*types.Basic)
	if !ok || t.Kind() != types.String || g.Pkg == nil || strings.HasSuffix(g.Pkg.Pkg.Path(), "/internal/bundled") {
		return "", false
	}
	path, ok := embedPaths[g.Pos()]
	if !ok {
		return "", false
	}
	return readEmbed(path)
}

// longest zero pattern of an array written as it is (reflect's TypeZero):
// the checkers walk a pattern cell by cell
const maxRunCells = 16

// zero cells of a type as a repeated pattern (arrays are not expanded)
func (c *compiler) zeroRun(t types.Type) ([]string, int64) {
	if a, ok := t.Underlying().(*types.Array); ok {
		p, n := c.zeroRun(a.Elem())
		return p, n * a.Len()
	}
	return c.zeroCells(t), 1
}
