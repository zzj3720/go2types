// ---------------------------------------------------------------------------
// Reachability (rapid type analysis that stops at intrinsics)

func methodKey(m *types.Func) string {
	return types.Id(m.Pkg(), m.Name())
}

func (c *compiler) reach(roots []*ssa.Function) {
	var queue []*ssa.Function
	invoked := map[string]bool{}
	var typesSeen []types.Type
	parent := map[*ssa.Function]*ssa.Function{}
	var cur *ssa.Function
	addFunc := func(f *ssa.Function) {
		if f == nil || c.reachable[f] {
			return
		}
		c.reachable[f] = true
		c.reachOrder = append(c.reachOrder, f)
		parent[f] = cur
		queue = append(queue, f)
		if g := forwardTarget(f); g != nil {
			if !c.reachable[g] {
				c.reachOrder = append(c.reachOrder, g)
			}
			c.reachable[g] = true
			parent[g] = f
			queue = append(queue, g)
		}
	}
	defer func() {
		// explain how runtime internals became reachable
		shown := 0
		for _, f := range c.reachOrder {
			if f.Pkg == nil || shown >= 5 {
				continue
			}
			p := f.Pkg.Pkg.Path()
			match := false
			for _, w := range strings.Split(*why, ",") {
				if w != "" && (p == w || strings.HasPrefix(p, w+"/")) {
					match = true
				}
			}
			if !match {
				continue
			}
			if parent[f] != nil && parent[f].Pkg != nil && parent[f].Pkg.Pkg.Path() == p {
				continue
			}
			var chain []string
			for g := f; g != nil && len(chain) < 12; g = parent[g] {
				chain = append(chain, g.String())
			}
			fmt.Fprintf(stderr, "go2types: reached: %s\n", strings.Join(chain, " <- "))
			shown++
		}
	}()
	methodsOf := func(t types.Type, key string) {
		ms := c.prog.MethodSets.MethodSet(t)
		for i := 0; i < ms.Len(); i++ {
			sel := ms.At(i)
			if key != "" && methodKey(sel.Obj().(*types.Func)) != key {
				continue
			}
			if !invoked[methodKey(sel.Obj().(*types.Func))] {
				continue
			}
			addFunc(c.prog.MethodValue(sel))
		}
	}
	var addType func(t types.Type)
	addType = func(t types.Type) {
		if types.IsInterface(t) || c.runtimeTypes.At(t) != nil {
			return
		}
		c.runtimeTypes.Set(t, true)
		typesSeen = append(typesSeen, t)
		methodsOf(t, "")
		// what reflection can reach from a value of type t: its fields,
		// elements, keys and (for named types) a pointer to it
		for _, r := range reflectNeighbors(t) {
			addType(r)
		}
	}
	invoke := func(m *types.Func) {
		k := methodKey(m)
		if invoked[k] {
			return
		}
		invoked[k] = true
		for _, t := range typesSeen {
			methodsOf(t, k)
		}
	}
	for _, r := range roots {
		addFunc(r)
	}
	for len(queue) > 0 {
		f := queue[len(queue)-1]
		queue = queue[:len(queue)-1]
		cur = f
		if _, ok := intrinsicBody(f); ok {
			continue
		}
		for _, blk := range f.Blocks {
			for _, ins := range blk.Instrs {
				var ops []*ssa.Value
				for _, op := range ins.Operands(ops) {
					if fn, ok := (*op).(*ssa.Function); ok {
						addFunc(fn)
					}
				}
				switch x := ins.(type) {
				case *ssa.MakeInterface:
					addType(x.X.Type())
				case ssa.CallInstruction:
					if cc := x.Common(); cc.IsInvoke() {
						invoke(cc.Method)
					}
				}
			}
		}
	}
}

