// go2types compiles a Go program into TypeScript type-level code that runs on
// the tstst runtime.
//
// Every Go function becomes a family of type aliases, one per SSA basic block.
// The heap H is threaded through every alias; blocks receive their live values
// as type parameters and jump to each other with tail calls.
//
// Usage: go2types -o out/prog.ts [-lib ../lib] ./path/to/main/package
package main

import (
	"flag"
	"fmt"
	"go/constant"
	"go/token"
	"go/types"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/ssa"
	"golang.org/x/tools/go/types/typeutil"
)

var (
	outPath = flag.String("o", "out/prog.ts", "output file")
	libDir  = flag.String("lib", "", "directory containing go.ts and gort.ts, normally lib/pure (import path written into the output)")
	verbose = flag.Bool("v", false, "verbose")
	natives = flag.String("natives", "", "directory with replacement packages (default: <go2types>/natives)")
	dir     = flag.String("C", "", "directory to load packages from")
	testBin = flag.Bool("test", false, "compile the package's test binary (go test's generated main); with several packages, one program with all their test binaries (its input starts with the package's path and a newline)")
	exports = flag.String("export", "", "library mode: Name=Func,... exports these functions of the (non-main) package as type aliases Name<args> = results")
	deadInits = flag.String("dead-inits", "yes", "skip the inits of packages that only fill globals nothing reachable reads: yes, no, or lib (library mode only); a checker spends most of rterrors in unicode's tables otherwise")
	splitAt = flag.Int("split", 400, "nesting depth of conditionals after which the rest of a block goes into an alias of its own (0: never): checkers recurse per nesting level (tsc's parser), and resolving a conditional nested in the true branches of d others costs tsc, tsgo and tsrs 2^d (getConditionalFlowTypeOfType); tsc_run.sh uses 8")
	why     = flag.String("why", "runtime,internal/runtime,internal/reflectlite,reflect", "explain how functions of these packages became reachable")
)

func main() {
	parseFlags()
	if flag.NArg() != 1 && !(*testBin && flag.NArg() > 1) {
		fmt.Fprintln(stderr, "usage: go2types -o out.ts <main package>")
		os.Exit(2)
	}
	prog, spkgs, firstPath := load()
	// one package after another in a fixed order: which instance of a generic
	// function is created first (and so the name it prints, with or without
	// aliases) depends on the order (prog.Build goes by map order, in parallel)
	all := prog.AllPackages()
	sort.Slice(all, func(i, j int) bool { return pathQual(all[i].Pkg) < pathQual(all[j].Pkg) })
	for _, p := range all {
		p.Build()
	}
	var mainPkg *ssa.Package
	var testMains []*ssa.Package
	for _, p := range spkgs {
		if p == nil {
			continue
		}
		switch {
		case *testBin:
			if p.Pkg.Name() == "main" && strings.HasSuffix(p.Pkg.Path(), ".test") {
				testMains = append(testMains, p)
				mainPkg = p
			}
		case *exports != "":
			if p.Pkg.Path() == firstPath {
				mainPkg = p
			}
		case p.Pkg.Name() == "main":
			mainPkg = p
		}
	}
	if mainPkg == nil {
		fatal("no main package")
	}
	roots := []*ssa.Function{mainPkg.Func("init")}
	var libExports [][2]string
	if *testBin && flag.NArg() > 1 {
		// several packages' test binaries: init and main of each, by path
		sort.Slice(testMains, func(i, j int) bool { return testMains[i].Pkg.Path() < testMains[j].Pkg.Path() })
		roots = nil
		for _, p := range testMains {
			roots = append(roots, p.Func("init"), p.Func("main"))
		}
	} else if *exports == "" {
		roots = append(roots, mainPkg.Func("main"))
	} else {
		for _, e := range strings.Split(*exports, ",") {
			name, fn, ok := strings.Cut(e, "=")
			f := mainPkg.Func(fn)
			if !ok || f == nil {
				fatal("-export: no function %q", e)
			}
			roots = append(roots, f)
			libExports = append(libExports, [2]string{name, fn})
		}
	}

	c := newCompiler(prog)
	// (the roots of the program's entry; the scheduler's functions follow)
	c.mainRoots = len(roots)
	c.manyMains = *testBin && flag.NArg() > 1
	if rp := prog.ImportedPackage("runtime"); rp != nil {
		for _, n := range chanFuncs {
			if f := rp.Func(n); f != nil {
				c.chanFn[n] = f
				roots = append(roots, f)
			}
		}
	}
	c.reach(roots)
	if *deadInits == "yes" || *deadInits == "lib" && *exports != "" {
		c.findDeadInits()
	}
	c.mainPkg = mainPkg
	c.collect()
	c.libExports = libExports
	c.computeFramed()
	if *blockReport != "" || *blockRefined != "" {
		c.blocks = c.analyzeBlocking()
	}
	var refined *rAnalysis
	if *blockRefined != "" {
		refined = c.analyzeRefined()
	}
	out := c.emitProgram(roots)
	if *blockReport != "" {
		c.writeBlockReport(c.blocks, len(out))
	}
	if refined != nil {
		c.writeRefinedReport(refined, len(out), c.blocks.size)
	}
	// functions with the same code: one (dedup.go)
	out = dedupFuncs(out)

	lib := *libDir
	if lib == "" {
		lib = "../lib/pure"
	}
	header := fmt.Sprintf("// Generated by go2types from %s. Do not edit.\n"+
		"import type * as g from %q;\n"+
		"import type * as rt from %q;\n\n", strings.Join(flag.Args(), " "), lib+"/go", lib+"/gort")
	if *verbose {
		fmt.Fprintf(stderr, "go2types: %d functions, %d types, %d globals, %d bytes\n",
			len(c.funcs), c.typeIDs.Len(), len(c.globals), len(header)+len(out))
	}
	writeOutput(header + out)
}

// typeMap is a typeutil.Map that iterates in insertion order: typeutil.Map's
// order is random, so type ids changed from run to run.
type typeMap struct {
	m    typeutil.Map
	keys []types.Type
}

func (tm *typeMap) At(t types.Type) any { return tm.m.At(t) }
func (tm *typeMap) Len() int            { return tm.m.Len() }

func (tm *typeMap) Set(t types.Type, v any) {
	if tm.m.Set(t, v) == nil {
		tm.keys = append(tm.keys, t)
	}
}

// Iterate visits the entries present when it starts.
func (tm *typeMap) Iterate(f func(t types.Type, v any)) {
	for _, t := range tm.keys {
		f(t, tm.m.At(t))
	}
}

func fatal(format string, args ...any) {
	fmt.Fprintf(stderr, "go2types: "+format+"\n", args...)
	os.Exit(1)
}

type compiler struct {
	prog    *ssa.Program
	mainPkg *ssa.Package

	reachable     map[*ssa.Function]bool
	reachOrder    []*ssa.Function            // reachable, in the order reach found them
	runtimeTypes  typeMap                    // types stored in interfaces
	runtimeSorted []types.Type               // runtimeTypes by id
	wrappers      map[string][]*ssa.Function // by text: see sameWrapper
	usedIDs       map[int]bool               // function and type ids
	usedNames     map[string]bool            // names of invokers, impls, loaders, storers

	funcs   []*ssa.Function
	funcID  map[*ssa.Function]int
	globals []*ssa.Global
	globID  map[*ssa.Global]int

	typeIDs   typeMap // types.Type -> int
	rtCatch   bool    // G_rtpanic is defined: bodies of functions with defers catch runtime errors
	ifaceImpl typeMap // interface type -> alias name of implements table

	invokers map[string]*invoker // dispatch aliases for interface method calls
	callers  map[int]bool        // dynamic call dispatchers by arity
	inlineOK map[*ssa.Function]bool
	byValue  map[*ssa.FreeVar]*ssa.Store // free variables captured by value (freeByValue)
	chanFn   map[string]*ssa.Function // runtime's channel implementation (extra/runtime)
	// library mode: (export name, function name)
	libExports [][2]string

	sizes   types.Sizes
	sb      strings.Builder
	errs    []string
	loaders typeMap
	storers typeMap
	helpers []string
	// continuation aliases of split blocks (-split), written after the
	// function being emitted
	pending []string
	splits  int
	// packages whose init is skipped, and the instructions of initialization
	// that only build values for globals nothing reads (-dead-inits)
	deadInit map[*ssa.Package]bool
	dropped  map[ssa.Instruction]bool
	// initial cells of allocations with constant stores folded in (fold.go)
	foldPattern map[*ssa.Alloc]string
	// the deferred calls of all functions: G_defer's entries
	deferN        int
	deferEntries  []string
	deferEntriesR []string // of resumable copies (G_deferR)
	rDefers       bool
	// allocations of package initialization in the initial heap (static.go):
	// the next address, their runs; the cyclic blocks of functions
	staticNext int64
	staticBase int64
	staticRun  map[*ssa.Alloc]string
	staticPlan []*ssa.Alloc
	cyclic     map[*ssa.Function]map[int]bool
	staticAddr map[*ssa.Alloc]int64
	// a global's one store, made once by initialization: its initial value
	globalInit   map[*ssa.Global]string
	globalStores map[*ssa.Global]int
	// -block-report: the functions that can wait for another goroutine
	blocks *blockInfo
	// resumable goroutines (sched.go): functions with frames, continuations
	framed      map[*ssa.Function]bool
	suspCache   map[string]bool
	callersS    map[int]bool // dispatchers of resumable copies by arity
	contAliases []contAlias
	contFn      map[int]int    // continuation id -> its function's id
	fnames      map[int]string // names of go statements' calls (G_fname)
	goThunks    []goThunk
	mainThunks  []goThunk // the main goroutines' (one per test binary of -test with several packages)
	mainRoots   int       // how many of emitProgram's roots are the entry's
	manyMains   bool      // -test with several packages: Main's input names the package
	deferBaseOf map[*ssa.Function]int
}

type invoker struct {
	r      bool // of resumable copies
	name   string
	iface  *types.Interface
	method *types.Func
	nargs  int
	nres   int
}

func newCompiler(prog *ssa.Program) *compiler {
	return &compiler{
		prog:      prog,
		reachable: map[*ssa.Function]bool{},
		funcID:    map[*ssa.Function]int{},
		usedIDs:   map[int]bool{},
		usedNames: map[string]bool{},
		globID:    map[*ssa.Global]int{},
		invokers:  map[string]*invoker{},
		callers:   map[int]bool{},
		inlineOK:  map[*ssa.Function]bool{},
		byValue:   map[*ssa.FreeVar]*ssa.Store{},
		chanFn:    map[string]*ssa.Function{},
		foldPattern: map[*ssa.Alloc]string{},
		suspCache:   map[string]bool{},
		callersS:    map[int]bool{},
		contFn:      map[int]int{},
		fnames:      map[int]string{},
		deferBaseOf: map[*ssa.Function]int{},
		cyclic:      map[*ssa.Function]map[int]bool{},
		staticAddr:  map[*ssa.Alloc]int64{},
		staticRun:   map[*ssa.Alloc]string{},
		globalInit:  map[*ssa.Global]string{},
		sizes:     types.SizesFor("gc", "amd64"),
	}
}

// collect assigns ids to reachable functions, globals and runtime types.
func (c *compiler) collect() {
	// by name; functions with the same name in the order they were found
	fns := append([]*ssa.Function(nil), c.reachOrder...)
	keys := map[*ssa.Function]string{}
	for _, f := range fns {
		keys[f] = c.fnKey(f)
	}
	sort.SliceStable(fns, func(i, j int) bool { return keys[fns[i]] < keys[fns[j]] })
	for _, f := range fns {
		if g := c.sameWrapper(f); g != nil {
			continue
		}
		c.funcID[f] = c.newID(funcText(f))
		c.funcs = append(c.funcs, f)
	}
	// globals of all packages (stdout and input occupy addresses 1 and 2)
	var globs []*ssa.Global
	seenGlob := map[*ssa.Global]bool{}
	for _, f := range c.funcs {
		if _, ok := intrinsicBody(f); ok {
			continue
		}
		for _, blk := range f.Blocks {
			for _, ins := range blk.Instrs {
				var ops []*ssa.Value
				for _, op := range ins.Operands(ops) {
					if g, ok := (*op).(*ssa.Global); ok && !seenGlob[g] {
						seenGlob[g] = true
						globs = append(globs, g)
					}
				}
			}
		}
	}
	sort.Slice(globs, func(i, j int) bool { return globKey(globs[i]) < globKey(globs[j]) })
	addr := int64(4) // cell 0: allocation pointer, 1: stdout, 2: input, 3: the panic being recovered
	for _, g := range globs {
		c.globID[g] = int(addr)
		c.globals = append(c.globals, g)
		addr += c.cells(g.Type().(*types.Pointer).Elem())
	}
	c.staticNext = addr
	c.staticBase = addr
	// type ids in a deterministic order (typeutil.Map iterates in a random
	// one): by the type's text, then where a named type is declared
	var ts []types.Type
	c.runtimeTypes.Iterate(func(t types.Type, _ any) { ts = append(ts, t) })
	tkeys := map[types.Type]string{}
	for _, t := range ts {
		tkeys[t] = c.typeKey(t)
	}
	sort.SliceStable(ts, func(i, j int) bool { return tkeys[ts[i]] < tkeys[ts[j]] })
	for _, t := range ts {
		c.typeID(t)
	}
}

// Ids and names derive from what they stand for (a hash), not from a count:
// a change of the program changes few of them, and the output's text only
// where it changed (for the caches of compilers of the output).

func hash64(s string) uint64 {
	h := uint64(14695981039346656037)
	for i := 0; i < len(s); i++ {
		h ^= uint64(s[i])
		h *= 1099511628211
	}
	return h
}

// an id for key: 31 bits of its hash (the next free one on a collision)
func (c *compiler) newID(key string) int {
	id := int(hash64(key) >> 33)
	for id == 0 || c.usedIDs[id] {
		id++
	}
	c.usedIDs[id] = true
	return id
}

// a name base_<hash of key>
func (c *compiler) newName(base, key string) string {
	name := base + "_" + strconv.FormatUint(hash64(key)>>32, 36)
	for c.usedNames[name] {
		name += "x"
	}
	c.usedNames[name] = true
	return name
}

func (c *compiler) typeKey(t types.Type) string {
	k := c.typeTextLoc(t)
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	if n, ok := t.(*types.Named); ok && n.Obj().Pos().IsValid() {
		k += "\x00" + c.posText(n.Obj().Pos())
	}
	return k
}

// the runtime types by id
func (c *compiler) runtimeTypeList() []types.Type {
	if c.runtimeSorted == nil || len(c.runtimeSorted) != c.runtimeTypes.Len() {
		var ts []types.Type
		c.runtimeTypes.Iterate(func(t types.Type, _ any) { ts = append(ts, t) })
		sort.Slice(ts, func(i, j int) bool { return c.typeID(ts[i]) < c.typeID(ts[j]) })
		c.runtimeSorted = ts
	}
	return c.runtimeSorted
}

// go/ssa makes the wrappers $bound and $thunk once per package that needs
// them: equal ones are one function here (else their order, and so the ids,
// would differ from run to run)
func (c *compiler) sameWrapper(f *ssa.Function) *ssa.Function {
	name := f.Name()
	if f.Object() == nil || !strings.HasSuffix(name, "$bound") && !strings.HasSuffix(name, "$thunk") {
		return nil
	}
	if c.wrappers == nil {
		c.wrappers = map[string][]*ssa.Function{}
	}
	k := funcText(f)
	for _, g := range c.wrappers[k] {
		if g.Object() == f.Object() && g.Name() == name && types.Identical(g.Signature, f.Signature) &&
			sameVarTypes(g.FreeVars, f.FreeVars) && sameParamTypes(g.Params, f.Params) {
			c.funcID[f] = c.funcID[g]
			return g
		}
	}
	c.wrappers[k] = append(c.wrappers[k], f)
	return nil
}

func sameVarTypes(a, b []*ssa.FreeVar) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if !types.Identical(a[i].Type(), b[i].Type()) {
			return false
		}
	}
	return true
}

func sameParamTypes(a, b []*ssa.Parameter) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if !types.Identical(a[i].Type(), b[i].Type()) {
			return false
		}
	}
	return true
}

// the order of functions: by name, then where they are (the id is from the
// name: an edit moving the others in a file changes no id)
func (c *compiler) fnKey(f *ssa.Function) string {
	return typePrinter{q: pathQual, loc: c.posText}.funcText(f) + "\x00" + c.posText(f.Pos())
}

func (c *compiler) posText(p token.Pos) string {
	if !p.IsValid() {
		return ""
	}
	pos := c.prog.Fset.Position(p)
	return pos.Filename + ":" + strconv.Itoa(pos.Line) + ":" + strconv.Itoa(pos.Column)
}

// a global's text for the order of globals (RelString, with its package's
// variant: pathQual)
func globKey(g *ssa.Global) string {
	if g.Pkg != nil {
		if id, ok := variantIDs[g.Pkg.Pkg]; ok {
			return id + "." + g.Name()
		}
	}
	return g.RelString(nil)
}

func pathQual(p *types.Package) string {
	if id, ok := variantIDs[p]; ok {
		return id
	}
	return p.Path()
}

// with several packages' test binaries, the packages compiled for a test
// (go list's "q [p.test]") beside q itself: their ids (load), in the text of
// their types and functions, which would otherwise be q's
var variantIDs = map[*types.Package]string{}

// f.RelString(nil) with the types' text from typeText (go/ssa names a
// generic instance after the type arguments' spelling in the package that
// needed it first)
func funcText(f *ssa.Function) string {
	return typePrinter{q: pathQual}.funcText(f)
}

// funcText as if no package were compiled for a test (pathQual): the names
// of framesList
func plainFuncText(f *ssa.Function) string {
	return typePrinter{q: (*types.Package).Path}.funcText(f)
}

func (tp typePrinter) funcText(f *ssa.Function) string {
	if p := f.Parent(); p != nil {
		return tp.funcText(p) + strings.TrimPrefix(f.Name(), p.Name())
	}
	name := f.Name()
	if targs := f.TypeArgs(); len(targs) > 0 && f.Origin() != nil {
		var as []string
		for _, a := range targs {
			as = append(as, tp.text(a))
		}
		name = f.Origin().Name() + "[" + strings.Join(as, ",") + "]"
	}
	var recv types.Type
	if r := f.Signature.Recv(); r != nil {
		recv = r.Type()
	} else if strings.HasSuffix(name, "$bound") && len(f.FreeVars) == 1 {
		recv = f.FreeVars[0].Type()
	} else if strings.HasSuffix(name, "$thunk") && len(f.Params) > 0 {
		recv = f.Params[0].Type()
	}
	if recv != nil {
		return "(" + tp.text(recv) + ")." + name
	}
	if f.Pkg != nil {
		return tp.q(f.Pkg.Pkg) + "." + name
	}
	if o := f.Object(); o != nil && o.Pkg() != nil {
		return tp.q(o.Pkg()) + "." + name
	}
	return f.RelString(nil)
}

// types.TypeString with aliases resolved (byte, rune and declared ones): the
// same text for identical types however they are spelled
func typeText(t types.Type, q types.Qualifier) string {
	var b strings.Builder
	typePrinter{q: q}.writeType(&b, t)
	return b.String()
}

// typeText with where types declared in functions are (types of the same
// name, distinct): for ordering, not for ids (they would change with edits
// moving the declaration)
func (c *compiler) typeTextLoc(t types.Type) string {
	var b strings.Builder
	typePrinter{q: pathQual, loc: c.posText}.writeType(&b, t)
	return b.String()
}

type typePrinter struct {
	q   types.Qualifier
	loc func(token.Pos) string // nil: without
}

func (tp typePrinter) text(t types.Type) string {
	var b strings.Builder
	tp.writeType(&b, t)
	return b.String()
}

func (tp typePrinter) writeType(b *strings.Builder, t types.Type) {
	q := tp.q
	switch x := t.(type) {
	case *types.Alias:
		tp.writeType(b, types.Unalias(x))
	case *types.Basic:
		if x.Kind() == types.UnsafePointer {
			b.WriteString("unsafe.Pointer")
		} else {
			b.WriteString(types.Typ[x.Kind()].Name())
		}
	case *types.Pointer:
		b.WriteByte('*')
		tp.writeType(b, x.Elem())
	case *types.Slice:
		b.WriteString("[]")
		tp.writeType(b, x.Elem())
	case *types.Array:
		fmt.Fprintf(b, "[%d]", x.Len())
		tp.writeType(b, x.Elem())
	case *types.Map:
		b.WriteString("map[")
		tp.writeType(b, x.Key())
		b.WriteByte(']')
		tp.writeType(b, x.Elem())
	case *types.Chan:
		switch x.Dir() {
		case types.SendOnly:
			b.WriteString("chan<- ")
		case types.RecvOnly:
			b.WriteString("<-chan ")
		default:
			b.WriteString("chan ")
		}
		if e, ok := types.Unalias(x.Elem()).(*types.Chan); ok && x.Dir() == types.SendRecv && e.Dir() == types.RecvOnly {
			b.WriteByte('(')
			tp.writeType(b, e)
			b.WriteByte(')')
		} else {
			tp.writeType(b, x.Elem())
		}
	case *types.Signature:
		b.WriteString("func")
		tp.writeSig(b, x)
	case *types.Struct:
		b.WriteString("struct{")
		for i := 0; i < x.NumFields(); i++ {
			if i > 0 {
				b.WriteString("; ")
			}
			f := x.Field(i)
			if !f.Embedded() {
				b.WriteString(f.Name())
				b.WriteByte(' ')
			}
			tp.writeType(b, f.Type())
			if tag := x.Tag(i); tag != "" {
				b.WriteByte(' ')
				b.WriteString(strconv.Quote(tag))
			}
		}
		b.WriteByte('}')
	case *types.Interface:
		b.WriteString("interface{")
		first := true
		for i := 0; i < x.NumEmbeddeds(); i++ {
			if !first {
				b.WriteString("; ")
			}
			first = false
			tp.writeType(b, x.EmbeddedType(i))
		}
		for i := 0; i < x.NumExplicitMethods(); i++ {
			if !first {
				b.WriteString("; ")
			}
			first = false
			m := x.ExplicitMethod(i)
			b.WriteString(m.Name())
			tp.writeSig(b, m.Type().(*types.Signature))
		}
		b.WriteByte('}')
	case *types.Named:
		o := x.Obj()
		if o.Pkg() != nil && q != nil {
			if s := q(o.Pkg()); s != "" {
				b.WriteString(s)
				b.WriteByte('.')
			}
		}
		b.WriteString(o.Name())
		if tp.loc != nil && o.Pkg() != nil && o.Parent() != nil && o.Parent() != o.Pkg().Scope() {
			b.WriteString("@" + tp.loc(o.Pos()))
		}
		if ta := x.TypeArgs(); ta.Len() > 0 {
			b.WriteByte('[')
			for i := 0; i < ta.Len(); i++ {
				if i > 0 {
					b.WriteByte(',')
				}
				tp.writeType(b, ta.At(i))
			}
			b.WriteByte(']')
		}
	case *types.Tuple:
		tp.writeTuple(b, x, false)
	case *types.Union:
		for i := 0; i < x.Len(); i++ {
			if i > 0 {
				b.WriteString(" | ")
			}
			if x.Term(i).Tilde() {
				b.WriteByte('~')
			}
			tp.writeType(b, x.Term(i).Type())
		}
	default:
		b.WriteString(types.TypeString(t, q))
	}
}

func (tp typePrinter) writeTuple(b *strings.Builder, t *types.Tuple, variadic bool) {
	b.WriteByte('(')
	for i := 0; i < t.Len(); i++ {
		if i > 0 {
			b.WriteString(", ")
		}
		v := t.At(i)
		if v.Name() != "" {
			b.WriteString(v.Name())
			b.WriteByte(' ')
		}
		if variadic && i == t.Len()-1 {
			b.WriteString("...")
			if s, ok := types.Unalias(v.Type()).(*types.Slice); ok {
				tp.writeType(b, s.Elem())
				continue
			}
		}
		tp.writeType(b, v.Type())
	}
	b.WriteByte(')')
}

func (tp typePrinter) writeSig(b *strings.Builder, s *types.Signature) {
	tp.writeTuple(b, s.Params(), s.Variadic())
	r := s.Results()
	if r.Len() == 0 {
		return
	}
	b.WriteByte(' ')
	if r.Len() == 1 && r.At(0).Name() == "" {
		tp.writeType(b, r.At(0).Type())
		return
	}
	tp.writeTuple(b, r, false)
}

func (c *compiler) typeID(t types.Type) int {
	if v := c.typeIDs.At(t); v != nil {
		return v.(int)
	}
	id := c.newID("type " + typeText(t, pathQual))
	c.typeIDs.Set(t, id)
	return id
}

func (c *compiler) fail(pos token.Pos, format string, args ...any) string {
	msg := fmt.Sprintf(format, args...)
	if pos.IsValid() {
		msg = c.prog.Fset.Position(pos).String() + ": " + msg
	}
	c.errs = append(c.errs, msg)
	return fmt.Sprintf("g.panic<%s>", tsString("unsupported: "+msg))
}

