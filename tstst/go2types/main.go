// the path a program sees for a source file: tsc's files are below /tsc
func sourcePath(name string) string {
	if *dir != "" {
		if abs, err := filepath.Abs(*dir); err == nil {
			if rel, err := filepath.Rel(abs, name); err == nil && !strings.HasPrefix(rel, "..") {
				return "/tsc/" + filepath.ToSlash(rel)
			}
		}
	}
	return filepath.ToSlash(name)
}

// A table of ids: the property its key names, or the default. The table is
// an object type with the ids' text as property names, looked up as
//   X extends infer N$ extends bigint ? ({ "1": A; "2": B } extends infer Tbl$ ?
//     `${N$}` extends infer Key$ extends keyof Tbl$ ? Tbl$[Key$] : D : never) : D
// (an index signature for the default, `{ 1: A; [k: string]: D }[K]`, is
// not TypeScript: tsc and tsgo require each property to be assignable to an
// index signature's type; and a placeholder's type must be known to be a
// string, number, bigint, ...: the id x, a bigint, is bound as one). tstc
// compiles the lookup to the indexed object, found by the integer itself.
// tableOpen(x) starts the table of the key x, tableClose(d) ends it.
func tableOpen(x string) string {
	return x + " extends infer N$ extends bigint ? ({"
}

func tableClose(def string) string {
	return fmt.Sprintf("} extends infer Tbl$ ? `${N$}` extends infer Key$ extends keyof Tbl$ ? Tbl$[Key$] : %s : never) : %s", def, def)
}

func tsString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		ch := s[i]
		switch {
		case ch == '"':
			b.WriteString(`\"`)
		case ch == '\\':
			b.WriteString(`\\`)
		case ch >= 0x20 && ch < 0x7f:
			b.WriteByte(ch)
		default:
			fmt.Fprintf(&b, `\x%02x`, ch)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func intLit(v int64) string { return strconv.FormatInt(v, 10) + "n" }

// floats are their IEEE 754 bits (TypeScript number literal types have no
// NaN, infinities or -0)
func floatLit(f float64) string { return intLit(int64(math.Float64bits(f))) }

func isUnsigned(t types.Type) bool {
	if b, ok := t.Underlying().(*types.Basic); ok {
		return b.Info()&types.IsUnsigned != 0
	}
	return false
}

// width code for iwrap: bits for signed, -bits for unsigned, 0 for no wrapping
func wrapCode(t types.Type) int {
	b, ok := t.Underlying().(*types.Basic)
	if !ok {
		return 0
	}
	switch b.Kind() {
	case types.Int8:
		return 8
	case types.Int16:
		return 16
	case types.Int32:
		return 32
	case types.Uint8:
		return -8
	case types.Uint16:
		return -16
	case types.Uint32:
		return -32
	}
	return 0
}

func (c *compiler) constant(cv *ssa.Const) string {
	t := cv.Type()
	if cv.Value == nil {
		return c.zero(t)
	}
	switch cv.Value.Kind() {
	case constant.Bool:
		if constant.BoolVal(cv.Value) {
			return "true"
		}
		return "false"
	case constant.String:
		return tsString(constant.StringVal(cv.Value))
	case constant.Int:
		if isFloat(t) {
			return c.floatConst(cv)
		}
		if v, ok := constant.Int64Val(cv.Value); ok {
			return intLit(v)
		}
		if v, ok := constant.Uint64Val(cv.Value); ok {
			return intLit(int64(v))
		}
		return c.fail(cv.Pos(), "integer constant out of range")
	case constant.Float:
		if isFloat(t) {
			return c.floatConst(cv)
		}
		// float constant converted to an integer type
		f, _ := constant.Float64Val(cv.Value)
		return intLit(int64(f))
	}
	return c.fail(cv.Pos(), "unsupported constant %v", cv)
}

// a float constant; float32 values are kept as the float64 they widen to
func (c *compiler) floatConst(cv *ssa.Const) string {
	f, _ := constant.Float64Val(cv.Value)
	if b, ok := cv.Type().Underlying().(*types.Basic); ok && b.Kind() == types.Float32 {
		f32, _ := constant.Float32Val(cv.Value)
		f = float64(f32)
	}
	return floatLit(f)
}

