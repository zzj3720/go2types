// zero value of a type as a type expression
func (c *compiler) zero(t types.Type) string {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return "false"
		case u.Info()&types.IsString != 0:
			return `""`
		case u.Info()&types.IsFloat != 0:
			return "0n"
		case u.Info()&types.IsInteger != 0:
			return "0n"
		case u.Kind() == types.UnsafePointer, u.Kind() == types.UntypedNil:
			return "null"
		}
		return "null"
	case *types.Pointer, *types.Map, *types.Chan, *types.Signature, *types.Interface:
		return "null"
	case *types.Slice:
		return "[null, 0n, 0n]"
	case *types.Struct:
		parts := make([]string, u.NumFields())
		for i := range parts {
			parts[i] = c.zero(u.Field(i).Type())
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case *types.Array:
		return fmt.Sprintf("g.vnew<%s, %s>", intLit(u.Len()), c.zero(u.Elem()))
	}
	return "null"
}

func (c *compiler) elemSize(t types.Type) int64 {
	return c.sizes.Sizeof(t)
}

func hasPointers(t types.Type) bool {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return u.Kind() == types.String || u.Kind() == types.UnsafePointer
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			if hasPointers(u.Field(i).Type()) {
				return true
			}
		}
		return false
	case *types.Array:
		return u.Len() > 0 && hasPointers(u.Elem())
	}
	return true
}

