func intrinsicKey(f *ssa.Function) string {
	name := f.String()
	if i := strings.IndexByte(name, '['); i >= 0 && !strings.HasPrefix(name, "(") {
		name = name[:i]
	}
	return name
}

// packages whose body-less functions (runtime hooks) become no-ops
func stubPkg(path string) bool {
	switch path {
	case "time", "internal/synctest", "internal/syscall/unix", "internal/godebug", "internal/poll", "os", "syscall", "runtime", "runtime/debug",
		"sync", "internal/sync", "internal/runtime/atomic", "unique", "weak", "os/signal":
		return true
	}
	return false
}

// packages whose initialization is skipped: the Go runtime is not translated
func skipInit(path string) bool {
	switch path {
	case "runtime", "internal/cpu", "internal/bytealg",
		"internal/godebug", "internal/bisect", "internal/abi", "internal/goarch",
		"internal/chacha8rand", "internal/godebugs", "internal/goos", "internal/race":
		return true
	}
	return strings.HasPrefix(path, "internal/runtime/") || strings.HasPrefix(path, "runtime/") ||
		strings.HasPrefix(path, "github.com/klauspost/cpuid") ||
		// x/tools' table of the standard library's symbols (go2types does not use it)
		path == "golang.org/x/tools/internal/stdlib"
}

// readsNoGlobal: f and the functions it calls (all known statically) refer
// to no global
func (c *compiler) readsNoGlobal(f *ssa.Function, seen map[*ssa.Function]bool) bool {
	if seen[f] {
		return true
	}
	seen[f] = true
	if g := forwardTarget(f); g != nil {
		return c.readsNoGlobal(g, seen)
	}
	if _, ok := intrinsicBody(f); ok || len(f.Blocks) == 0 {
		return intrinsicFor(f) != "" || ok
	}
	var ops []*ssa.Value
	for _, blk := range f.Blocks {
		for _, ins := range blk.Instrs {
			if cl, ok := ins.(ssa.CallInstruction); ok {
				com := cl.Common()
				if _, isB := com.Value.(*ssa.Builtin); !isB {
					callee := com.StaticCallee()
					if callee == nil || !c.readsNoGlobal(callee, seen) {
						return false
					}
				}
			}
			for _, op := range ins.Operands(ops[:0]) {
				switch x := (*op).(type) {
				case *ssa.Global:
					return false
				case *ssa.Function:
					if !c.readsNoGlobal(x, seen) {
						return false
					}
				}
			}
		}
	}
	return true
}

// the package initializer (not an init#N of the source)
func isPkgInit(f *ssa.Function) bool {
	return f.Pkg != nil && f.Name() == "init" && f.Signature.Recv() == nil && f.Parent() == nil
}

// part of package initialization: the initializer, init#N functions and
// closures in them
func inInit(f *ssa.Function) bool {
	for f.Parent() != nil {
		f = f.Parent()
	}
	return f.Pkg != nil && f.Signature.Recv() == nil && (f.Name() == "init" || strings.HasPrefix(f.Name(), "init#"))
}

// findDeadInits finds the packages whose initialization only fills the
// package's own globals (calling only its own initialization functions and
// the dead inits of other packages) when no reachable function outside initialization
// reads any of them: running it changes nothing a program can see. (The
// unicode tables are most of the initialization of lib/pure/softfloat.ts.)
func (c *compiler) findDeadInits() {
	read := map[*ssa.Global]bool{}
	var ops []*ssa.Value
	for f := range c.reachable {
		if inInit(f) {
			continue
		}
		for _, blk := range f.Blocks {
			for _, ins := range blk.Instrs {
				for _, op := range ins.Operands(ops[:0]) {
					if g, ok := (*op).(*ssa.Global); ok {
						read[g] = true
					}
				}
			}
		}
	}
	// the initialization functions of each package
	parts := map[*ssa.Package][]*ssa.Function{}
	for f := range c.reachable {
		if inInit(f) && f.Pkg != nil {
			parts[f.Pkg] = append(parts[f.Pkg], f)
		}
	}
	c.deadInit = map[*ssa.Package]bool{}
	for p := range parts {
		c.deadInit[p] = true
	}
	for changed := true; changed; {
		changed = false
		for p, fs := range parts {
			if !c.deadInit[p] {
				continue
			}
			ok := true
		check:
			for _, f := range fs {
				for _, blk := range f.Blocks {
					for _, ins := range blk.Instrs {
						switch ins.(type) {
						case *ssa.Go, *ssa.Defer, *ssa.Panic, *ssa.Send, *ssa.Select:
							ok = false
							break check
						}
						for _, op := range ins.Operands(ops[:0]) {
							switch x := (*op).(type) {
							case *ssa.Global:
								if x.Pkg != p || read[x] {
									ok = false
									break check
								}
							case *ssa.Function:
								// (other functions of p could do anything)
								if !(inInit(x) && x.Pkg == p) && !(isPkgInit(x) && c.deadInit[x.Pkg]) {
									ok = false
									break check
								}
							}
						}
						if call, ok2 := ins.(*ssa.Call); ok2 && call.Call.IsInvoke() {
							ok = false
							break check
						}
					}
				}
			}
			if !ok {
				c.deadInit[p] = false
				changed = true
			}
		}
	}
	for p, dead := range c.deadInit {
		if !dead {
			delete(c.deadInit, p)
		}
	}
	c.findDeadStores(read)
	if *verbose {
		var names []string
		for p := range c.deadInit {
			names = append(names, p.Pkg.Path())
		}
		sort.Strings(names)
		fmt.Fprintf(stderr, "go2types: inits skipped (globals not read): %s\n", strings.Join(names, " "))
	}
}

// findDeadStores marks the instructions of package initialization that only
// build values stored into globals nothing reads (as tables like strconv's
// isPrint16 that a program does not use): stores into such a global or into
// memory only they reach, and the allocations, addresses and conversions
// feeding them alone. read holds the globals reachable code outside
// initialization reads.
func (c *compiler) findDeadStores(read map[*ssa.Global]bool) {
	var inits []*ssa.Function
	for f := range c.reachable {
		if inInit(f) {
			inits = append(inits, f)
		}
	}
	// globals initialization reads (anything but the address of a store)
	used := map[*ssa.Global]bool{}
	for g := range read {
		used[g] = true
	}
	var ops []*ssa.Value
	for _, f := range inits {
		for _, blk := range f.Blocks {
			for _, ins := range blk.Instrs {
				st, isStore := ins.(*ssa.Store)
				for _, op := range ins.Operands(ops[:0]) {
					if g, ok := (*op).(*ssa.Global); ok && !(isStore && st.Addr == g) {
						used[g] = true
					}
				}
			}
		}
	}
	// optimistically every candidate, then those that are not
	cand := map[ssa.Instruction]bool{}
	for _, f := range inits {
		for _, blk := range f.Blocks {
			for _, ins := range blk.Instrs {
				switch ins.(type) {
				case *ssa.Store, *ssa.Alloc, *ssa.IndexAddr, *ssa.FieldAddr, *ssa.Slice, *ssa.ChangeType,
					*ssa.MakeInterface, *ssa.MakeMap, *ssa.MapUpdate, *ssa.DebugRef:
					cand[ins] = true
				}
			}
		}
	}
	valueOK := func(v ssa.Value) bool {
		ins, ok := v.(ssa.Instruction)
		if !ok || !cand[ins] {
			return false
		}
		for _, r := range *v.Referrers() {
			if !cand[r] {
				return false
			}
		}
		return true
	}
	// the memory a derived value is of: dropped too, or an unread global's
	baseOK := func(ins ssa.Instruction) bool {
		var x ssa.Value
		switch v := ins.(type) {
		case *ssa.IndexAddr:
			x = v.X
		case *ssa.FieldAddr:
			x = v.X
		case *ssa.Slice:
			x = v.X
		case *ssa.ChangeType:
			x = v.X
		case *ssa.MakeInterface:
			x = v.X
		default:
			return false
		}
		if g, ok := x.(*ssa.Global); ok {
			return !used[g]
		}
		if xi, ok := x.(ssa.Instruction); ok {
			return cand[xi]
		}
		return false
	}
	for changed := true; changed; {
		changed = false
		for ins := range cand {
			ok := true
			switch x := ins.(type) {
			case *ssa.Store:
				if g, isG := x.Addr.(*ssa.Global); isG {
					ok = !used[g]
				} else {
					ok = valueOK(x.Addr)
				}
			case *ssa.MapUpdate:
				ok = valueOK(x.Map)
			case *ssa.DebugRef:
			case *ssa.Alloc, *ssa.MakeMap:
				ok = valueOK(ins.(ssa.Value))
			default:
				// an address or view of memory: of memory dropped too
				ok = valueOK(ins.(ssa.Value)) && baseOK(ins)
			}
			if !ok {
				delete(cand, ins)
				changed = true
			}
		}
	}
	c.dropped = map[ssa.Instruction]bool{}
	n := 0
	for ins := range cand {
		if _, ok := ins.(*ssa.DebugRef); !ok {
			c.dropped[ins] = true
			n++
		}
	}
	if *verbose {
		fmt.Fprintf(stderr, "go2types: %d instructions of initialization only build globals nothing reads\n", n)
	}
}

func intrinsicBody(f *ssa.Function) (string, bool) {
	if body, ok := schedIntrinsic(f); ok {
		return body, true
	}
	switch f.Name() {
	case "tststOutput":
		return "[rt.gprint<H, P0>]", true
	case "tststInput":
		return "[H, rt.ginput<H>]", true
	case "tststEmit":
		return "[g.gemit<H, P0>]", true
	case "tststFork":
		return "g.gfork<H, P0>", true
	case "tststWait":
		return "g.gwait<H>", true
	case "tststExit":
		return "g.gexit<H, P0>", true
	case "tststNowMs":
		return "g.gnowms<H>", true
	case "tststCrashTag":
		return "[g.gcrashtag<H, P0>]", true
	}
	if f.Pkg != nil && f.Name() == "init" && f.Signature.Recv() == nil && skipInit(f.Pkg.Pkg.Path()) {
		return "[H]", true
	}
	b, ok := intrinsics[intrinsicKey(f)]
	return b, ok
}

// a body-less function F (a runtime hook) whose package has a function
// tstst_F (added in extra/) is implemented by it
func forwardTarget(f *ssa.Function) *ssa.Function {
	if t, ok := redirects[f.String()]; ok && f.Pkg != nil {
		if p := f.Prog.ImportedPackage(t[0]); p != nil {
			if g := p.Func(t[1]); g != nil {
				return g
			}
		}
	}
	if len(f.Blocks) != 0 || f.Pkg == nil || f.Signature.Recv() != nil || f.Parent() != nil || f.TypeArgs() != nil {
		return nil
	}
	if _, ok := intrinsicBody(f); ok {
		return nil
	}
	if t, ok := forwards[intrinsicKey(f)]; ok {
		if p := f.Prog.ImportedPackage(t[0]); p != nil {
			return p.Func(t[1])
		}
	}
	return f.Pkg.Func("tstst_" + f.Name())
}

