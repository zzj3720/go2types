func (c *compiler) emitProgram(roots []*ssa.Function) string {
	var b strings.Builder
	// initial cells as [count, pattern] runs: stdout, input, then the globals' zero values
	buildRuns := func(input string) string {
		// [count, pattern] runs; a pattern of equal cells is one cell repeated,
		// and runs of the same pattern merge
		type run struct {
			n   int64
			pat string
		}
		var rs []run
		var add func(n int64, pat []string)
		add = func(n int64, pat []string) {
			if n == 1 && len(pat) > 1 {
				// one copy: maximal runs of equal cells
				for i := 0; i < len(pat); {
					j := i
					for j < len(pat) && pat[j] == pat[i] {
						j++
					}
					if j-i == len(pat) {
						break
					}
					add(int64(j-i), pat[i:i+1])
					i = j
					if i == len(pat) {
						return
					}
				}
			}
			if len(pat) > 1 {
				same := true
				for _, p := range pat[1:] {
					same = same && p == pat[0]
				}
				if same {
					n *= int64(len(pat))
					pat = pat[:1]
				}
			}
			p := strings.Join(pat, ", ")
			if len(rs) > 0 && rs[len(rs)-1].pat == p {
				rs[len(rs)-1].n += n
				return
			}
			rs = append(rs, run{n, p})
		}
		add(1, []string{`""`})
		rs = append(rs, run{1, input})
		add(1, []string{"null"})
		for _, gl := range c.globals {
			if v, ok := c.globalInit[gl]; ok {
				// (its one store, made by the initialization: static.go)
				add(1, []string{v})
				continue
			}
			if content, ok := c.embedded(gl); ok {
				rs = append(rs, run{1, tsString(content)})
				continue
			}
			pattern, count := c.zeroRun(gl.Type().(*types.Pointer).Elem())
			add(count, pattern)
		}
		var r strings.Builder
		r.WriteString("g.hinit<[")
		for k, x := range rs {
			if k > 0 {
				r.WriteString(", ")
			}
			fmt.Fprintf(&r, "[%s, [%s]]", intLit(x.n), x.pat)
		}
		r.WriteString(staticRunsMark + "]>")
		return r.String()
	}
	// (the initial heap is written last: what initialization stores once in
	// globals goes into it, static.go)
	var runInputs []string
	runs := func(input string) string {
		runInputs = append(runInputs, input)
		return fmt.Sprintf("\x00runs%d\x00", len(runInputs)-1)
	}
	b.WriteString("// interface values compare their floats as numbers\n" +
		"type G_ieq<A, B> = A extends [infer T, infer X] ? B extends [infer U, infer Y] ? g.geq<T, U> extends true ?\n" +
		"  TypeKind<T> extends 14n ? g.feq<X, Y> : TypeKind<T> extends 13n ? g.feq<X, Y> : g.geq<X, Y> : false : false : g.geq<A, B>;\n\n")
	if c.libExports != nil {
		// library: the heap after init, and a type per exported function
		b.WriteString("// The heap after the package's initialization.\n")
		fmt.Fprintf(&b, "export type LibHeap = %s<%s> extends [infer H] ? H : never;\n", c.fname(roots[0]), runs(`""`))
		// functions that read no global run on a heap without them: a checker
		// then need not run the initialization (which tables can make long)
		b.WriteString("// The heap for the functions that read no global.\n")
		b.WriteString("type BareHeap = g.hinit<[[1n, [\"\"]], [1n, [\"\"]], [1n, [null]]]>;\n")
		for i, e := range c.libExports {
			f := roots[i+1]
			var ps []string
			for k := range f.Params {
				ps = append(ps, "P"+strconv.Itoa(k))
			}
			heap := "LibHeap"
			if c.readsNoGlobal(f, map[*ssa.Function]bool{}) {
				heap = "BareHeap"
			}
			args := append([]string{heap}, ps...)
			res := "R[0]"
			if f.Signature.Results().Len() != 1 {
				res = "R"
			}
			fmt.Fprintf(&b, "/** %s */\nexport type %s<%s> = %s<%s> extends [infer _H, ...infer R] ? %s : never;\n",
				f.String(), e[0], strings.Join(ps, ", "), c.fname(f), strings.Join(args, ", "), res)
		}
		b.WriteString("\n")
	} else {
		// Input goes in its cell (2, after stdout's) inside G_run, behind a
		// check on it: a checker resolving Main's own declaration (not an
		// instantiation) then defers the run there. With Input in the initial
		// heap it would run the whole program on a heap holding the type
		// parameter, and everything carrying that heap would be generic:
		// walked on every instantiation and relation. (G_run: emitSched)
		if !c.manyMains {
			fmt.Fprintf(&b, "export type Main<Input extends string = \"\"> = G_run<%s, Input>;\n", runs(`""`))
		} else {
			// several test binaries: the input's first line names the package
			fmt.Fprintf(&b, "export type Main<Input extends string = \"\"> = Input extends `${infer P}\\n${infer In}` ? G_run<%s, In, G_mainid<P>> : never;\n", runs(`""`))
		}
	}
	rterr := false
	if rp := c.prog.ImportedPackage("runtime"); rp != nil {
		if obj := rp.Pkg.Scope().Lookup("tststRuntimeError"); obj != nil && c.typeIDs.At(obj.Type()) != nil {
			b.WriteString("// the value of a runtime error\n")
			fmt.Fprintf(&b, "export type G_rterr<M> = [%dn, M];\n", c.typeID(obj.Type()))
			rterr = true
			// A native runtime's failures (where lib/pure fails: rterr, panic)
			// are runtime errors. The bodies of functions with defers catch
			// them (tstc: @catch) as this panic, with the heap as the failure
			// left it; other failures go on.
			b.WriteString("// the panic of a failure with message M (tstc: @catch), with heap H\n" +
				"export type G_rtpanic<M, H> = G_rtkind<M> extends true ? { tstst_panic: G_rterr<G_rtmsg<M>>; heap: H } : g.panic<M>;\n" +
				"type G_rtkind<M> =\n" +
				"  M extends `invalid memory address or nil pointer dereference${string}` ? true\n" +
				"  : M extends `index out of range${string}` ? true\n" +
				"  : M extends `slice bounds out of range${string}` ? true\n" +
				"  : M extends `integer divide by zero${string}` ? true\n" +
				"  : M extends `interface conversion${string}` ? true\n" +
				"  : M extends `assignment to entry in nil map${string}` ? true\n" +
				"  : M extends `makeslice:${string}` ? true\n" +
				"  : M extends `negative shift amount${string}` ? true\n" +
				"  : false;\n" +
				"// as Go's runtime.Error messages\n" +
				"type G_rtmsg<M> =\n" +
				"  M extends `interface conversion${string}` ? M\n" +
				"  : M extends `assignment to entry${string}` ? M\n" +
				"  : M extends string ? `runtime error: ${M}` : never;\n")
			c.rtCatch = true
		}
	}
	b.WriteString("// a runtime error E (lib/pure rterr.ts) as a panic, with the heap H\n")
	if rterr {
		b.WriteString("type G_rtp<H, E> = { tstst_panic: G_rterr<g.rtmsg<E>>; heap: H };\n\n")
	} else {
		b.WriteString("type G_rtp<H, E> = g.panic<g.rtmsg<E>>;\n\n")
	}
	if c.libExports != nil {
		c.emitSched(&b, nil)
	} else {
		c.emitSched(&b, roots[:c.mainRoots])
	}
	for _, f := range c.funcs {
		n := b.Len()
		c.emitFunc(&b, f)
		if c.framed[f] {
			c.emitFuncAs(&b, f, true)
		}
		if c.blocks != nil {
			c.blocks.size[f] = b.Len() - n
		}
	}
	c.emitSpecs(&b)
	c.emitDeferRunners(&b)
	// dispatchers
	keys := make([]string, 0, len(c.invokers))
	for k := range c.invokers {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		c.emitInvoker(&b, c.invokers[k])
	}
	for _, f := range c.funcs {
		if intrinsicKey(f) == "reflect.funcCall" {
			c.emitReflectCall(&b)
			break
		}
	}
	var arities []int
	for n := range c.callers {
		arities = append(arities, n)
	}
	sort.Ints(arities)
	for _, n := range arities {
		c.emitCaller(&b, n, false)
	}
	arities = arities[:0]
	for n := range c.callersS {
		arities = append(arities, n)
	}
	sort.Ints(arities)
	for _, n := range arities {
		c.emitCaller(&b, n, true)
	}
	c.emitConts(&b)
	c.emitTypeTables(&b)
	for i := 0; i < len(c.helpers); i++ {
		b.WriteString(c.helpers[i])
	}
	type impl struct {
		t    types.Type
		name string
	}
	var impls []impl
	c.ifaceImpl.Iterate(func(t types.Type, v any) { impls = append(impls, impl{t, v.(string)}) })
	sort.Slice(impls, func(i, j int) bool { return impls[i].name < impls[j].name })
	for _, im := range impls {
		c.emitImpl(&b, im.t.Underlying().(*types.Interface), im.name)
	}
	out := b.String()
	for i, in := range runInputs {
		out = strings.ReplaceAll(out, fmt.Sprintf("\x00runs%d\x00", i), buildRuns(in))
	}
	// the initial heap's allocations, after the globals (static.go)
	out = strings.ReplaceAll(out, staticRunsMark, c.staticRunsText())
	b.Reset()
	b.WriteString(out)
	if len(c.errs) > 0 {
		// full list next to the output, for triage
		writeSideFile(*outPath+".unsupported.txt", strings.Join(c.errs, "\n")+"\n")
		fmt.Fprintf(stderr, "go2types: %d unsupported constructs (compiled as panics):\n", len(c.errs))
		seen := map[string]bool{}
		n := 0
		for _, e := range c.errs {
			if seen[e] {
				continue
			}
			seen[e] = true
			if n < 50 {
				fmt.Fprintln(stderr, "  "+e)
			}
			n++
		}
	}
	return b.String()
}

func (c *compiler) fname(f *ssa.Function) string {
	id, ok := c.funcID[f]
	if !ok && c.sameWrapper(f) != nil {
		id, ok = c.funcID[f], true
	}
	if !ok {
		id = c.newID(funcText(f))
		c.funcID[f] = id
		c.funcs = append(c.funcs, f)
	}
	return "F" + strconv.FormatInt(int64(id), 36)
}

// the id of a function (its value's first element)
func (c *compiler) fid(f *ssa.Function) int {
	c.fname(f)
	return c.funcID[f]
}

func (c *compiler) emitInvoker(b *strings.Builder, inv *invoker) {
	// inv<H, R, A...> = { [typeId]: Fn<H, tget<R, 1n>, A...> }[tget<R, 0n>]
	params := []string{"H", "R"}
	for i := 0; i < inv.nargs; i++ {
		params = append(params, "A"+strconv.Itoa(i))
	}
	// (a method call on a nil interface is a runtime error)
	fmt.Fprintf(b, "type %s<%s> = g.nilchk<R> extends infer R0 ? g.rtok<R0> extends true ? %s\n", inv.name, strings.Join(params, ", "), tableOpen("g.tget<R0, 0n>"))
	var entries []string
	for _, t := range c.runtimeTypeList() {
		if types.IsInterface(t) {
			continue
		}
		if !types.Implements(t, inv.iface) {
			continue
		}
		ms := c.prog.MethodSets.MethodSet(t)
		sel := ms.Lookup(inv.method.Pkg(), inv.method.Name())
		if sel == nil {
			continue
		}
		fn := c.prog.MethodValue(sel)
		if fn == nil {
			continue
		}
		args := []string{"H", "g.tget<R, 1n>"}
		for i := 0; i < inv.nargs; i++ {
			args = append(args, "A"+strconv.Itoa(i))
		}
		callee := c.fname(fn)
		if inv.r {
			callee = c.calleeR(fn)
		}
		entries = append(entries, fmt.Sprintf("  \"%d\": %s<%s>;", c.typeID(t), callee, strings.Join(args, ", ")))
	}
	sort.Strings(entries)
	b.WriteString(strings.Join(entries, "\n"))
	fmt.Fprintf(b, "\n%s : G_rtp<H, R0> : 0;\n", tableClose("g.panic<"+tsString("no method "+inv.method.Name())+">"))
}

func (c *compiler) emitCaller(b *strings.Builder, n int, r bool) {
	// CallN<H, F, A...> = { [fid]: Fn<H, A..., bindings...> }[F[0]]; CallSN
	// calls resumable copies (and go statements' thunks)
	params := []string{"H", "F"}
	for i := 0; i < n; i++ {
		params = append(params, "A"+strconv.Itoa(i))
	}
	kind := ""
	if r {
		kind = "S"
	}
	fmt.Fprintf(b, "type Call%s%d<%s> = g.nilchk<F> extends infer F0 ? g.rtok<F0> extends true ? %s\n", kind, n, strings.Join(params, ", "), tableOpen("g.tget<F0, 0n>"))
	for _, f := range c.funcs {
		if !c.isFuncValue(f) {
			continue
		}
		if len(f.Params) != n {
			continue
		}
		args := []string{"H"}
		for i := 0; i < n; i++ {
			args = append(args, "A"+strconv.Itoa(i))
		}
		for i := range f.FreeVars {
			args = append(args, fmt.Sprintf("g.tget<F, %dn>", i+1))
		}
		callee := c.fname(f)
		if r {
			callee = c.calleeR(f)
		}
		fmt.Fprintf(b, "  \"%d\": %s<%s>;\n", c.fid(f), callee, strings.Join(args, ", "))
	}
	if r && n == 0 {
		for _, t := range c.goThunks {
			args := []string{"H"}
			for i := 0; i < t.n; i++ {
				args = append(args, fmt.Sprintf("g.tget<F, %dn>", i+1))
			}
			fmt.Fprintf(b, "  \"%d\": %s<%s>;\n", t.id, t.name, strings.Join(args, ", "))
		}
		for _, t := range c.mainThunks {
			fmt.Fprintf(b, "  \"%d\": %s<H>;\n", t.id, t.name)
		}
	}
	b.WriteString(tableClose("g.panic<\"call of nil function\">") + " : G_rtp<H, F0> : 0;\n")
}

// G_rcall<H, F, N, Args>: reflect's call of the func value F (an interface
// value) with the first N of Args (interface values): [H, results boxed as
// interface values (null past the last)], or a panic
func (c *compiler) emitReflectCall(b *strings.Builder) {
	b.WriteString("type G_rarg<T, A> = TypeKind<T> extends 20n ? A : A extends null ? null : g.tget<A, 1n>;\n")
	b.WriteString("type G_rbox<T, R> = TypeKind<T> extends 20n ? R : [T, R];\n")
	b.WriteString("type G_rret<R, FT> = R extends { tstst_panic: infer V; heap: infer HP } ? R :\n" +
		"  R extends [infer H, infer X0, infer X1, infer X2] ? [H, G_rbox<g.tget<TypeOut<FT>, 0n>, X0>, G_rbox<g.tget<TypeOut<FT>, 1n>, X1>, G_rbox<g.tget<TypeOut<FT>, 2n>, X2>] :\n" +
		"  R extends [infer H, infer X0, infer X1] ? [H, G_rbox<g.tget<TypeOut<FT>, 0n>, X0>, G_rbox<g.tget<TypeOut<FT>, 1n>, X1>, null] :\n" +
		"  R extends [infer H, infer X0] ? [H, G_rbox<g.tget<TypeOut<FT>, 0n>, X0>, null, null] :\n" +
		"  R extends [infer H] ? [H, null, null, null] : 0;\n")
	b.WriteString("type G_rcall<H, F, N, A> = g.tget<F, 0n> extends infer FT ? g.tget<F, 1n> extends infer FV ? G_rret<\n")
	for n := 0; n <= 6; n++ {
		c.callers[n] = true
		args := []string{"H", "FV"}
		for i := 0; i < n; i++ {
			args = append(args, fmt.Sprintf("G_rarg<g.tget<TypeIn<FT>, %dn>, g.tget<A, %dn>>", i, i))
		}
		fmt.Fprintf(b, "  N extends %dn ? Call%d<%s> :\n", n, n, strings.Join(args, ", "))
	}
	b.WriteString("  g.panic<\"reflect: too many arguments\">, FT> : 0 : 0;\n\n")
}

// functions that may be called through a func value
func (c *compiler) isFuncValue(f *ssa.Function) bool {
	return len(f.Blocks) > 0 || intrinsicFor(f) != ""
}

func (c *compiler) emitImpl(b *strings.Builder, it *types.Interface, name string) {
	fmt.Fprintf(b, "type %s<Id> = %s\n", name, tableOpen("Id"))
	var entries []string
	for _, t := range c.runtimeTypeList() {
		if types.IsInterface(t) {
			continue
		}
		if types.Implements(t, it) {
			entries = append(entries, fmt.Sprintf("  \"%d\": true;", c.typeID(t)))
		}
	}
	sort.Strings(entries)
	b.WriteString(strings.Join(entries, "\n"))
	b.WriteString("\n" + tableClose("false") + ";\n")
}

func (c *compiler) implAlias(t types.Type) string {
	if v := c.ifaceImpl.At(t); v != nil {
		return v.(string)
	}
	name := c.newName("Impl", typeText(t, pathQual))
	c.ifaceImpl.Set(t, name)
	return name
}

func (c *compiler) invokerFor(common *ssa.CallCommon) string {
	return c.invoker(common, false)
}

// the dispatcher of resumable copies
func (c *compiler) invokerForR(common *ssa.CallCommon) string {
	return c.invoker(common, true)
}

func (c *compiler) invoker(common *ssa.CallCommon, r bool) string {
	it := common.Value.Type().Underlying().(*types.Interface)
	m := common.Method
	key := m.FullName() + "|" + typeText(it, pathQual)
	base := "Inv_"
	if r {
		key += "|R"
		base = "InvR_"
	}
	if inv, ok := c.invokers[key]; ok {
		return inv.name
	}
	sig := m.Type().(*types.Signature)
	inv := &invoker{
		r:      r,
		name:   c.newName(base+sanitize(m.Name()), key),
		iface:  it,
		method: m,
		nargs:  sig.Params().Len(),
		nres:   sig.Results().Len(),
	}
	c.invokers[key] = inv
	return inv.name
}

func sanitize(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	return b.String()
}

