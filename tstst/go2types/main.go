// Runtime type information (used by the reflectlite replacement)

func kindOf(t types.Type) int {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch u.Kind() {
		case types.Bool:
			return 1
		case types.Int:
			return 2
		case types.Int8:
			return 3
		case types.Int16:
			return 4
		case types.Int32:
			return 5
		case types.Int64:
			return 6
		case types.Uint:
			return 7
		case types.Uint8:
			return 8
		case types.Uint16:
			return 9
		case types.Uint32:
			return 10
		case types.Uint64:
			return 11
		case types.Uintptr:
			return 12
		case types.Float32:
			return 13
		case types.Float64:
			return 14
		case types.Complex64:
			return 15
		case types.Complex128:
			return 16
		case types.String:
			return 24
		case types.UnsafePointer:
			return 26
		}
	case *types.Array:
		return 17
	case *types.Chan:
		return 18
	case *types.Signature:
		return 19
	case *types.Interface:
		return 20
	case *types.Map:
		return 21
	case *types.Pointer:
		return 22
	case *types.Slice:
		return 23
	case *types.Struct:
		return 25
	}
	return 0
}

// types reflection can reach from a value of type t
func reflectNeighbors(t types.Type) []types.Type {
	var out []types.Type
	switch u := t.Underlying().(type) {
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			out = append(out, u.Field(i).Type())
		}
	case *types.Map:
		// encoding/json sorts and deduplicates keys with []K, []V and map[K]struct{}
		out = append(out, u.Key(), u.Elem(), types.NewSlice(u.Key()), types.NewSlice(u.Elem()),
			types.NewMap(u.Key(), types.NewStruct(nil, nil)))
	case *types.Array:
		out = append(out, u.Elem())
	case *types.Slice:
		out = append(out, u.Elem())
	case *types.Pointer:
		out = append(out, u.Elem())
	case *types.Signature:
		for i := 0; i < u.Params().Len(); i++ {
			out = append(out, u.Params().At(i).Type())
		}
		for i := 0; i < u.Results().Len(); i++ {
			out = append(out, u.Results().At(i).Type())
		}
	}
	if _, ok := t.(*types.Named); ok {
		if _, isPtr := t.Underlying().(*types.Pointer); !isPtr {
			out = append(out, types.NewPointer(t))
		}
	}
	return out
}

func elemOf(t types.Type) types.Type {
	switch u := t.Underlying().(type) {
	case *types.Array:
		return u.Elem()
	case *types.Chan:
		return u.Elem()
	case *types.Map:
		return u.Elem()
	case *types.Pointer:
		return u.Elem()
	case *types.Slice:
		return u.Elem()
	}
	return nil
}

func (c *compiler) emitTypeTables(b *strings.Builder) {
	// every dynamic type of an interface gets an id; then the types
	// reachable from those, until stable
	for {
		n := c.typeIDs.Len()
		var ts []types.Type
		c.typeIDs.Iterate(func(t types.Type, _ any) { ts = append(ts, t) })
		sort.Slice(ts, func(i, j int) bool { return c.typeID(ts[i]) < c.typeID(ts[j]) })
		for _, t := range ts {
			if e := elemOf(t); e != nil {
				c.typeID(e)
			}
			for _, r := range reflectNeighbors(t) {
				c.typeID(r)
			}
		}
		if c.typeIDs.Len() == n {
			break
		}
	}
	type entry struct {
		id int
		t  types.Type
	}
	var all []entry
	c.typeIDs.Iterate(func(t types.Type, v any) { all = append(all, entry{v.(int), t}) })
	sort.Slice(all, func(i, j int) bool { return all[i].id < all[j].id })
	b.WriteString("type TypeKind<Id> = " + tableOpen("Id") + "\n")
	for _, e := range all {
		fmt.Fprintf(b, "  \"%d\": %dn;\n", e.id, kindOf(e.t))
	}
	b.WriteString(tableClose("0n") + ";\n")
	b.WriteString("type TypeElem<Id> = " + tableOpen("Id") + "\n")
	for _, e := range all {
		if el := elemOf(e.t); el != nil {
			fmt.Fprintf(b, "  \"%d\": %dn;\n", e.id, c.typeID(el))
		}
	}
	b.WriteString(tableClose("0n") + ";\n")
	b.WriteString("type TypeString<Id> = " + tableOpen("Id") + "\n")
	for _, e := range all {
		fmt.Fprintf(b, "  \"%d\": %s;\n", e.id, tsString(typeText(e.t, func(p *types.Package) string { return p.Name() })))
	}
	b.WriteString(tableClose("\"\"") + ";\n")
	b.WriteString("type TypeStride<Id> = " + tableOpen("Id") + "\n")
	for _, e := range all {
		if sl, ok := e.t.Underlying().(*types.Slice); ok {
			fmt.Fprintf(b, "  \"%d\": %dn;\n", e.id, c.cells(sl.Elem()))
		}
	}
	b.WriteString(tableClose("1n") + ";\n")
	b.WriteString("type TypeLayout<Id> = " + tableOpen("Id") + "\n")
	for _, e := range all {
		fmt.Fprintf(b, "  \"%d\": %q;\n", e.id, c.layout(e.t))
	}
	b.WriteString(tableClose("\"s\"") + ";\n")
	b.WriteString("type TypeComparable<Id> = " + tableOpen("Id") + "\n")
	for _, e := range all {
		fmt.Fprintf(b, "  \"%d\": %v;\n", e.id, types.Comparable(e.t))
	}
	b.WriteString(tableClose("false") + ";\n")
	// for package reflect
	table := func(name, def string, f func(t types.Type) (string, bool)) {
		fmt.Fprintf(b, "type %s<Id> = %s\n", name, tableOpen("Id"))
		for _, e := range all {
			if v, ok := f(e.t); ok {
				fmt.Fprintf(b, "  \"%d\": %s;\n", e.id, v)
			}
		}
		b.WriteString(tableClose(def) + ";\n")
	}
	table("TypeKey", "0n", func(t types.Type) (string, bool) {
		if m, ok := t.Underlying().(*types.Map); ok {
			return intLit(int64(c.typeID(m.Key()))), true
		}
		return "", false
	})
	table("TypeLen", "0n", func(t types.Type) (string, bool) {
		if a, ok := t.Underlying().(*types.Array); ok {
			return intLit(a.Len()), true
		}
		return "", false
	})
	table("TypeCells", "1n", func(t types.Type) (string, bool) {
		if n := c.cells(t); n != 1 {
			return intLit(n), true
		}
		return "", false
	})
	// the zero value of a type as TypeZeroN copies of the cells TypeZero
	// (arrays of many cells as copies of their element's, as allocations are)
	table("TypeZero", "null", func(t types.Type) (string, bool) {
		if pattern, count := c.zeroRun(t); count > 1 && int64(len(pattern))*count > maxRunCells {
			return "[" + strings.Join(pattern, ", ") + "]", true
		}
		return c.zeroCellsTuple(t), true
	})
	table("TypeZeroN", "1n", func(t types.Type) (string, bool) {
		if pattern, count := c.zeroRun(t); count > 1 && int64(len(pattern))*count > maxRunCells {
			return intLit(count), true
		}
		return "", false
	})
	table("TypeZeroValue", "null", func(t types.Type) (string, bool) { return c.zero(t), true })
	table("TypeName", "\"\"", func(t types.Type) (string, bool) {
		switch n := t.(type) {
		case *types.Named:
			// instances name their type arguments as Go's runtime does:
			// SyncMap[string,*example.com/pkg.T]
			name := n.Obj().Name()
			if targs := n.TypeArgs(); targs.Len() > 0 {
				var as []string
				for i := 0; i < targs.Len(); i++ {
					as = append(as, types.TypeString(targs.At(i), func(p *types.Package) string { return p.Path() }))
				}
				name += "[" + strings.Join(as, ",") + "]"
			}
			return tsString(name), true
		case *types.Basic:
			return tsString(n.Name()), true
		}
		return "", false
	})
	table("TypePkgPath", "\"\"", func(t types.Type) (string, bool) {
		if n, ok := t.(*types.Named); ok && n.Obj().Pkg() != nil {
			return tsString(n.Obj().Pkg().Path()), true
		}
		return "", false
	})
	table("TypePtrTo", "0n", func(t types.Type) (string, bool) {
		if id := c.typeIDs.At(types.NewPointer(t)); id != nil {
			return intLit(int64(id.(int))), true
		}
		return "", false
	})
	table("TypeSliceOf", "0n", func(t types.Type) (string, bool) {
		if id := c.typeIDs.At(types.NewSlice(t)); id != nil {
			return intLit(int64(id.(int))), true
		}
		return "", false
	})
	table("TypeSetOf", "0n", func(t types.Type) (string, bool) {
		if id := c.typeIDs.At(types.NewMap(t, types.NewStruct(nil, nil))); id != nil {
			return intLit(int64(id.(int))), true
		}
		return "", false
	})
	table("TypeNumMethod", "0n", func(t types.Type) (string, bool) {
		n := 0
		ms := c.prog.MethodSets.MethodSet(t)
		for i := 0; i < ms.Len(); i++ {
			if ms.At(i).Obj().Exported() {
				n++
			}
		}
		if types.IsInterface(t) {
			n = 0
			it := t.Underlying().(*types.Interface)
			for i := 0; i < it.NumMethods(); i++ {
				if it.Method(i).Exported() {
					n++
				}
			}
		}
		return intLit(int64(n)), n != 0
	})
	// func types: parameter and result type ids, variadic
	funcTable := func(name string, part func(*types.Signature) *types.Tuple) {
		table(name, "[]", func(t types.Type) (string, bool) {
			sig, ok := t.Underlying().(*types.Signature)
			if !ok {
				return "", false
			}
			var ids []string
			for i := 0; i < part(sig).Len(); i++ {
				ids = append(ids, intLit(int64(c.typeID(part(sig).At(i).Type()))))
			}
			return "[" + strings.Join(ids, ", ") + "]", true
		})
	}
	funcTable("TypeIn", (*types.Signature).Params)
	funcTable("TypeOut", (*types.Signature).Results)
	table("TypeNumIn", "0n", func(t types.Type) (string, bool) {
		sig, ok := t.Underlying().(*types.Signature)
		if !ok {
			return "", false
		}
		return intLit(int64(sig.Params().Len())), true
	})
	table("TypeNumOut", "0n", func(t types.Type) (string, bool) {
		sig, ok := t.Underlying().(*types.Signature)
		if !ok {
			return "", false
		}
		return intLit(int64(sig.Results().Len())), true
	})
	// sizes and alignments in bytes (linux/amd64), as encoding/binary and others
	// count them; addresses count cells (fields' offsets are in cells)
	table("TypeSize", "8n", func(t types.Type) (string, bool) {
		return intLit(c.sizes.Sizeof(t)), true
	})
	table("TypeAlign", "8n", func(t types.Type) (string, bool) {
		return intLit(c.sizes.Alignof(t)), true
	})
	table("TypeVariadic", "false", func(t types.Type) (string, bool) {
		sig, ok := t.Underlying().(*types.Signature)
		return "true", ok && sig.Variadic()
	})
	table("TypeNumField", "0n", func(t types.Type) (string, bool) {
		if st, ok := t.Underlying().(*types.Struct); ok {
			return intLit(int64(st.NumFields())), true
		}
		return "", false
	})
	// fields: [name, type, offset in cells, tag, embedded, package path of unexported names]
	table("TypeFields", "[]", func(t types.Type) (string, bool) {
		st, ok := t.Underlying().(*types.Struct)
		if !ok {
			return "", false
		}
		var parts []string
		for i := 0; i < st.NumFields(); i++ {
			f := st.Field(i)
			pkg := ""
			if !f.Exported() && f.Pkg() != nil {
				pkg = f.Pkg().Path()
			}
			parts = append(parts, fmt.Sprintf("[%s, %s, %s, %s, %v, %s]", tsString(f.Name()), intLit(int64(c.typeID(f.Type()))),
				intLit(c.fieldOffset(st, i)), tsString(st.Tag(i)), f.Embedded(), tsString(pkg)))
		}
		return "[" + strings.Join(parts, ", ") + "]", true
	})
	// TypeImplements<T, I>: dispatch on the interface first
	b.WriteString("type TypeImplements<T, I> = " + tableOpen("I") + "\n")
	for _, e := range all {
		if it, ok := e.t.Underlying().(*types.Interface); ok {
			_ = it
			fmt.Fprintf(b, "  \"%d\": %s<T>;\n", e.id, c.implAlias(e.t))
		}
	}
	b.WriteString(tableClose("false") + ";\n")
}

