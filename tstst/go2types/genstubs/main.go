// genstubs completes a hand-written replacement package with panicking stubs
// for the rest of the real package's exported API, so that other packages
// still type-check against it.
//
// usage: go run ./genstubs <import path> <natives dir> <output file>
package main

import (
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

func main() {
	path, dir, out := os.Args[1], os.Args[2], os.Args[3]
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName}, path)
	if err != nil || len(pkgs) != 1 || pkgs[0].Types == nil {
		fmt.Fprintln(os.Stderr, "load failed:", err)
		os.Exit(1)
	}
	real := pkgs[0].Types

	// names declared by the hand-written files
	have := map[string]bool{}
	fset := token.NewFileSet()
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, f := range files {
		if filepath.Base(f) == filepath.Base(out) {
			continue
		}
		af, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			panic(err)
		}
		for _, d := range af.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil {
					recv := d.Recv.List[0].Type
					if st, ok := recv.(*ast.StarExpr); ok {
						recv = st.X
					}
					if ix, ok := recv.(*ast.IndexExpr); ok {
						recv = ix.X
					}
					have[recv.(*ast.Ident).Name+"."+d.Name.Name] = true
				} else {
					have[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, sp := range d.Specs {
					switch sp := sp.(type) {
					case *ast.TypeSpec:
						have[sp.Name.Name] = true
					case *ast.ValueSpec:
						for _, n := range sp.Names {
							have[n.Name] = true
						}
					}
				}
			}
		}
	}

	imports := map[string]string{}
	qual := func(p *types.Package) string {
		if p == real {
			return ""
		}
		imports[p.Path()] = p.Name()
		return p.Name()
	}
	var b strings.Builder
	scope := real.Scope()
	names := scope.Names()
	sort.Strings(names)
	// the interface used for types: methods of the real Type interface
	var typeMethods *types.Interface
	if obj := scope.Lookup("Type"); obj != nil {
		typeMethods, _ = obj.Type().Underlying().(*types.Interface)
	}
	for _, name := range names {
		obj := scope.Lookup(name)
		if !obj.Exported() || have[name] {
			continue
		}
		switch o := obj.(type) {
		case *types.Const:
			fmt.Fprintf(&b, "const %s %s = %s\n", name, types.TypeString(o.Type(), qual), constant.ToInt(o.Val()).String())
		case *types.Var:
			fmt.Fprintf(&b, "var %s %s\n", name, types.TypeString(o.Type(), qual))
		case *types.Func:
			sig := o.Type().(*types.Signature)
			fmt.Fprintf(&b, "func %s%s%s { panic(%q) }\n", name, typeParams(sig.TypeParams(), qual), sigString(sig, qual), path+"."+name+" is not supported")
		case *types.TypeName:
			if o.IsAlias() {
				fmt.Fprintf(&b, "type %s = %s\n", name, types.TypeString(o.Type().Underlying(), qual))
				continue
			}
			switch u := o.Type().Underlying().(type) {
			case *types.Struct:
				fmt.Fprintf(&b, "type %s%s struct {\n", name, typeParams(o.Type().(*types.Named).TypeParams(), qual))
				for i := 0; i < u.NumFields(); i++ {
					f := u.Field(i)
					if f.Exported() {
						if f.Embedded() {
							fmt.Fprintf(&b, "\t%s\n", types.TypeString(f.Type(), qual))
						} else {
							fmt.Fprintf(&b, "\t%s %s\n", f.Name(), types.TypeString(f.Type(), qual))
						}
					}
				}
				b.WriteString("}\n")
			case *types.Interface:
				fmt.Fprintf(&b, "type %s interface {\n", name)
				for i := 0; i < u.NumMethods(); i++ {
					m := u.Method(i)
					if m.Exported() {
						fmt.Fprintf(&b, "\t%s%s\n", m.Name(), sigString(m.Type().(*types.Signature), qual))
					}
				}
				b.WriteString("}\n")
			default:
				fmt.Fprintf(&b, "type %s %s\n", name, types.TypeString(u, qual))
			}
		}
	}
	// stub methods on hand-written and generated named types
	for _, name := range names {
		tn, ok := scope.Lookup(name).(*types.TypeName)
		if !ok || !tn.Exported() || tn.IsAlias() {
			continue
		}
		named, ok := tn.Type().(*types.Named)
		if !ok {
			continue
		}
		for i := 0; i < named.NumMethods(); i++ {
			m := named.Method(i)
			if !m.Exported() || have[name+"."+m.Name()] {
				continue
			}
			sig := m.Type().(*types.Signature)
			recv := name
			if _, ptr := sig.Recv().Type().(*types.Pointer); ptr {
				recv = "*" + name
			}
			fmt.Fprintf(&b, "func (%s) %s%s { panic(%q) }\n", recv, m.Name(), sigString(sig, qual), path+"."+name+"."+m.Name()+" is not supported")
		}
	}
	// the hand-written rtype implements the full Type interface
	if typeMethods != nil && have["rtype"] {
		for i := 0; i < typeMethods.NumMethods(); i++ {
			m := typeMethods.Method(i)
			if !m.Exported() || have["rtype."+m.Name()] {
				continue
			}
			fmt.Fprintf(&b, "func (rtype) %s%s { panic(%q) }\n", m.Name(), sigString(m.Type().(*types.Signature), qual), path+".Type."+m.Name()+" is not supported")
		}
	}
	var head strings.Builder
	fmt.Fprintf(&head, "// Code generated by genstubs from %s. DO NOT EDIT.\n\npackage %s\n\n", path, real.Name())
	var ips []string
	for p := range imports {
		ips = append(ips, p)
	}
	sort.Strings(ips)
	if len(ips) > 0 {
		head.WriteString("import (\n")
		for _, p := range ips {
			fmt.Fprintf(&head, "\t%q\n", p)
		}
		head.WriteString(")\n\n")
	}
	if err := os.WriteFile(out, []byte(head.String()+b.String()), 0o644); err != nil {
		panic(err)
	}
}

func typeParams(tp *types.TypeParamList, qual types.Qualifier) string {
	if tp == nil || tp.Len() == 0 {
		return ""
	}
	parts := make([]string, tp.Len())
	for i := 0; i < tp.Len(); i++ {
		p := tp.At(i)
		parts[i] = p.Obj().Name() + " " + types.TypeString(p.Constraint(), qual)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func sigString(sig *types.Signature, qual types.Qualifier) string {
	params := tupleString(sig.Params(), sig.Variadic(), qual)
	res := sig.Results()
	switch res.Len() {
	case 0:
		return "(" + params + ")"
	case 1:
		return "(" + params + ") " + types.TypeString(res.At(0).Type(), qual)
	}
	parts := make([]string, res.Len())
	for i := 0; i < res.Len(); i++ {
		parts[i] = types.TypeString(res.At(i).Type(), qual)
	}
	return "(" + params + ") (" + strings.Join(parts, ", ") + ")"
}

func tupleString(t *types.Tuple, variadic bool, qual types.Qualifier) string {
	parts := make([]string, t.Len())
	for i := 0; i < t.Len(); i++ {
		ty := t.At(i).Type()
		if variadic && i == t.Len()-1 {
			parts[i] = fmt.Sprintf("p%d ...%s", i, types.TypeString(ty.(*types.Slice).Elem(), qual))
		} else {
			parts[i] = fmt.Sprintf("p%d %s", i, types.TypeString(ty, qual))
		}
	}
	return strings.Join(parts, ", ")
}
