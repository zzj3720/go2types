#!/bin/sh
# Regenerates go2types/frames.go: the functions that are on a goroutine's
# stack when it really has to suspend (go2types/sched.go), in the corpus's
# programs. Each is compiled with go2types -frames-learn (every function that
# can wait has frames) and run; the runtime writes the functions it needed
# frames of. usage: frames.sh [package or example...]
#   default: the examples goroutines, timers and gc, the Go tests of every
#   package of tests/go_test_packages.txt and the fourslash tests (learned
#   with frames only for the language service's packages, FOURSLASH_LEARN:
#   the program is too large otherwise). TSTC, TSTC_RT, TSTC_FLAGS as for
#   gotest.py. FRAMES_KEEP=1 adds to the current list instead of replacing it.
cd "$(dirname "$0")/.."
export TSTC=${TSTC:-$PWD/../tstc/tstc} TSTC_RT=${TSTC_RT:-$PWD/../tstc/rt}
export TSTC_FLAGS=${TSTC_FLAGS:--O f --llvm ${LLVM_BIN:-/opt/homebrew/opt/llvm@22/bin} -j 3}
FOURSLASH_LEARN=${FOURSLASH_LEARN:-internal/ls,internal/project,internal/lsp,internal/core,internal/compiler,sync,internal/collections,internal/fourslash}
ITEMS="$*"
[ -n "$ITEMS" ] || ITEMS="goroutines timers gc $(cat tests/go_test_packages.txt) internal/fourslash/tests"
OUT=$PWD/go2types/out/frames
mkdir -p $OUT
LIST=$OUT/learned.txt
: > $LIST
if [ -n "$FRAMES_KEEP" ]; then
  sed -n 's/^\t"\(.*\)",$/\1/p' go2types/frames.go | sed 's/\\"/"/g' >> $LIST
fi
for it in $ITEMS; do
  case $it in
  */*)
    run=""
    # (FOURSLASH_EVERY=n: every nth fourslash test)
    if [ $it = internal/fourslash/tests ] && [ -n "$FOURSLASH_EVERY" ]; then
      run="-run $(grep -h '^func Test' ../TypeScript/tsc/$it/*.go | sed 's/^func \(Test[A-Za-z0-9_]*\).*/\1/' | sort | awk -v n=$FOURSLASH_EVERY 'NR % n == 1' | paste -sd, -)"
    fi
    n0=$(sort -u $LIST | grep -cv '^$')
    rm -rf go2types/out/gotest/tstc-cache
    lf=$LEARN_FLAGS
    [ $it = internal/fourslash/tests ] && [ -z "$lf" ] && lf=-frames-learn-only=$FOURSLASH_LEARN
    FRAMES_OUT=$LIST G2T_FLAGS="-frames-learn $lf" python3 scripts/gotest.py $it -j 3 -t 600 -q ${RUN:-$run} < /dev/null 2>&1 | tail -3
    echo "$it: $(($(sort -u $LIST | grep -cv '^$') - n0)) more functions" 
    ;;
  *)
    (cd go2types && go run . -frames-learn -o $OUT/$it.ts -lib ../../lib/pure ./testdata/$it 2> $OUT/$it.err &&
      $TSTC build $OUT/$it.ts -o $OUT/$it --rt $TSTC_RT $TSTC_FLAGS 2>> $OUT/$it.err &&
      rm -f $OUT/$it.*.ll $OUT/$it.*.ll.o &&
      $OUT/$it run --bytes > $OUT/$it.got 2>> $OUT/$it.err) || { echo "$it: failed"; tail -5 $OUT/$it.err; }
    perl -0ne 'print "$1\n" while /\x01frames:([^\x02]*)\x02/g' $OUT/$it.got >> $LIST
    echo "$it: $(perl -0ne 'print "$1\n" while /\x01frames:([^\x02]*)\x02/g' $OUT/$it.got | sort -u | wc -l | tr -d ' ') functions"
    rm -f $OUT/$it $OUT/$it.ts
    ;;
  esac
done
{
  printf '// Code generated by scripts/frames.sh; DO NOT EDIT.\n\npackage main\n\n'
  printf '// The functions with frames (sched.go): those on a goroutine'"'"'s stack when it\n'
  printf '// really has to suspend, in the corpus'"'"'s programs (go2types -frames-learn).\n'
  printf 'var framesList = []string{\n'
  sort -u $LIST | grep -v '^$' | sed 's/\\/\\\\/g; s/"/\\"/g; s/^/\t"/; s/$/",/'
  printf '}\n'
} > go2types/frames.go
echo "go2types/frames.go: $(sort -u $LIST | grep -cv '^$') functions"
# (the learning builds are large)
rm -rf go2types/out/gotest/tstc-cache $OUT/*.ts $OUT/tstc-cache
