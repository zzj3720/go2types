#!/usr/bin/env python3
"""Writes lib/pure/tables.ts: digit tables for the pure type-level runtime."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = [str(i) for i in range(10)]
out = ['// Generated by scripts/gen_pure_tables.py. Do not edit.', '']

def table2(name, f, doc):
    out.append(f'// {doc}')
    rows = []
    for a in range(10):
        cells = ', '.join(f'"{b}": "{f(a, b)}"' for b in range(10))
        rows.append(f'  "{a}": {{ {cells} }};')
    out.append(f'export type {name} = {{\n' + '\n'.join(rows) + '\n};')
    out.append('')

table2('AddT', lambda a, b: f'{(a + b) // 10}{(a + b) % 10}', 'a + b as carry digit, digit')
table2('AddT1', lambda a, b: f'{(a + b + 1) // 10}{(a + b + 1) % 10}', 'a + b + 1 as carry digit, digit')
table2('SubT', lambda a, b: f'{1 if a < b else 0}{(a - b) % 10}', 'a - b as borrow digit, digit')
table2('SubT1', lambda a, b: f'{1 if a < b + 1 else 0}{(a - b - 1) % 10}', 'a - b - 1 as borrow digit, digit')
table2('MulT', lambda a, b: f'{(a * b) // 10}{(a * b) % 10}', 'a * b as two digits')
table2('CmpT', lambda a, b: 'lt' if a < b else 'gt' if a > b else 'eq', 'comparison of digits')
# halving with a carry digit c in 0..1: (10c + d) / 2 -> quotient digit, remainder
out.append('// (10 * c + d) / 2 as quotient digit, remainder (c is 0 or 1)')
out.append('export type HalfT = {\n' + '\n'.join(
    f'  "{c}": {{ ' + ', '.join(f'"{d}": "{(10 * c + d) // 2}{(10 * c + d) % 2}"' for d in range(10)) + ' };' for c in range(2)) + '\n};')
out.append('')
for name, f in [('AndT', lambda a, b: a & b), ('OrT', lambda a, b: a | b), ('XorT', lambda a, b: a ^ b), ('AndNotT', lambda a, b: a & ~b & 1)]:
    out.append(f'export type {name} = {{ "0": {{ "0": "{f(0,0)}", "1": "{f(0,1)}" }}; "1": {{ "0": "{f(1,0)}", "1": "{f(1,1)}" }} }};')
out.append('')
# hex digits: 16 divisions by 16 give the low 64 bits of a decimal magnitude
H = '0123456789abcdef'
out.append('// 16 * d + c as digit, carry (lowest digit first; c is 0..15)')
out.append('export type M16T = {\n' + '\n'.join(
    f'  "{c}": {{ ' + ', '.join(f'"{d}": "{(16 * d + c) % 10}{(16 * d + c) // 10}"' for d in range(10)) + ' };' for c in range(16)) + '\n};')
out.append('// (10 * c + d) / 256 as quotient digit, remainder (c is 0..255)')
out.append('export type Div256T = {\n' + '\n'.join(
    f'  "{c}": {{ ' + ', '.join(f'"{d}": "{(10 * c + d) // 256}{(10 * c + d) % 256}"' for d in range(10)) + ' };' for c in range(256)) + '\n};')
out.append('// 256 * d + c as digit, carry (lowest digit first; c is 0..255)')
out.append('export type M256T = {\n' + '\n'.join(
    f'  "{c}": {{ ' + ', '.join(f'"{d}": "{(256 * d + c) % 10}{(256 * d + c) // 10}"' for d in range(10)) + ' };' for c in range(256)) + '\n};')
out.append('// byte 0..255 -> two hex digits, and back')
out.append('export type HexOfB = { ' + '; '.join(f'"{v}": "{v:02x}"' for v in range(256)) + ' };')
out.append('export type ByteOfHex = { ' + '; '.join(f'"{v:02x}": "{v}"' for v in range(256)) + ' };')
out.append('// hex digit -> its value')
out.append('export type HexVal = { ' + '; '.join(f'"{H[v]}": "{v}"' for v in range(16)) + ' };')
out.append('// (15 - d) + c as carry, hex digit: two\'s complement digit by digit, lowest first (c is 0 or 1)')
out.append('export type NegHexT = {\n' + '\n'.join(
    f'  "{c}": {{ ' + ', '.join(f'"{H[d]}": "{(15 - d + c) // 16}{H[(15 - d + c) % 16]}"' for d in range(16)) + ' };' for c in range(2)) + '\n};')
out.append('// hex digit <-> four bits')
out.append('export type HexBits = { ' + '; '.join(f'"{H[v]}": "{v:04b}"' for v in range(16)) + ' };')
out.append('export type BitsHex = { ' + '; '.join(f'"{v:04b}": "{H[v]}"' for v in range(16)) + ' };')
for name, f in [('AndH', lambda a, b: a & b), ('OrH', lambda a, b: a | b), ('XorH', lambda a, b: a ^ b), ('AndNotH', lambda a, b: a & ~b & 15)]:
    out.append(f'export type {name} = {{\n' + '\n'.join(
        f'  "{H[a]}": {{ ' + ', '.join(f'"{H[b]}": "{H[f(a, b)]}"' for b in range(16)) + ' };' for a in range(16)) + '\n};')
out.append('')
# small counters as tuples, for shift amounts and widths
out.append('// "n" -> a tuple of length n, for n <= 64')
out.append('export type Count = {\n' + '\n'.join(f'  "{n}": [' + ', '.join(['0'] * n) + '];' for n in range(65)) + '\n};')
out.append('')
# successors of small numbers: the counters of index walks over tuples
out.append('// n -> n + 1 as number literals, for n < 4096 (counters of index walks)')
out.append('export type NextT = {\n' + '\n'.join(f'  {n}: {n + 1};' for n in range(4096)) + '\n};')
out.append('')
# bytes: char of code b, and code of char
out.append('// byte b (as a decimal string) -> the one-character string with char code b')
out.append('export type ByteChar = {\n' + '\n'.join(f'  "{b}": "\\x{b:02x}";' for b in range(256)) + '\n};')
out.append('// one-character string -> its char code as a bigint literal')
out.append('export type CharByte = {\n' + '\n'.join(f'  "\\x{b:02x}": {b}n;' for b in range(256)) + '\n};')
out.append('// one-character string -> its char code as two hex digits')
out.append('export type CharHex = {\n' + '\n'.join(f'  "\\x{b:02x}": "{b:02x}";' for b in range(256)) + '\n};')
out.append('// hex digit -> index of its child in a map trie node (0 is the value slot)')
out.append('export type HexSlot = { ' + '; '.join(f'"{d:x}": "{d + 1}"' for d in range(16)) + ' };')
# S without its first 100 or 1000 characters, in one match (never if shorter): a
# match makes the rest a new string type, so a long string is cut in few steps
for k in (100, 1000):
    out.append(f'// S without its first {k} characters, or never')
    out.append(f'export type Skip{k}<S extends string> = S extends `' + '${string}' * k + '${infer R}` ? R : never;')
out.append('')
open(os.path.join(ROOT, 'lib', 'pure', 'tables.ts'), 'w').write('\n'.join(out) + '\n')
