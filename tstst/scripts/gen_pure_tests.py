#!/usr/bin/env python3
"""Writes tests/pure/int.ts: int64 operations of lib/pure on chosen and
random values, each compared with the result computed here (Go semantics).
Every alias must evaluate to true, both in tstst and in tsc (difftest)."""
import os, random
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
random.seed(7)
M = 1 << 64
def s64(x): x %= M; return x - M if x >= 1 << 63 else x
def u64(x): return x % M
def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q
def wrapk(a, k):
    if k in (64, -64): return a
    if k < 0: return u64(a) % (1 << -k)
    x = u64(a) % (1 << k)
    return x - (1 << k) if x >= 1 << (k - 1) else x
vals = [0, 1, -1, 2, 7, -7, 10, 99, 100, -100, 255, 256, 1 << 31, -(1 << 31), (1 << 32) - 1, (1 << 62),
        (1 << 63) - 1, -(1 << 63), 123456789012345678, -987654321098765432, 1000000007]
vals += [s64(random.getrandbits(64)) for _ in range(6)] + [random.randint(-10**6, 10**6) for _ in range(6)]
def lit(x): return f'{x}n' if x >= 0 else f'-{-x}n'
def b(x): return 'true' if x else 'false'
cases = []
pairs = [(random.choice(vals), random.choice(vals)) for _ in range(70)]
for a, c in pairs:
    cases += [('iadd', [a, c], lit(s64(a + c))), ('isub', [a, c], lit(s64(a - c))), ('imul', [a, c], lit(s64(a * c))),
              ('ilt', [a, c], b(a < c)), ('ige', [a, c], b(a >= c)), ('iult', [a, c], b(u64(a) < u64(c))),
              ('iand', [a, c], lit(s64(u64(a) & u64(c)))), ('ior', [a, c], lit(s64(u64(a) | u64(c)))),
              ('ixor', [a, c], lit(s64(u64(a) ^ u64(c)))), ('iandnot', [a, c], lit(s64(u64(a) & ~u64(c))))]
    if c != 0:
        q = s64(tdiv(a, c)) if not (a == -(1 << 63) and c == -1) else a
        cases += [('idiv', [a, c], lit(q)), ('irem', [a, c], lit(a - tdiv(a, c) * c if not (a == -(1 << 63) and c == -1) else 0)),
                  ('udiv', [a, c], lit(s64(u64(a) // u64(c)))), ('urem', [a, c], lit(s64(u64(a) % u64(c))))]
for a in vals:
    cases += [('ineg', [a], lit(s64(-a))), ('inot', [a], lit(s64(~a)))]
    for sh in (0, 1, 7, 31, 63, 64, 100):
        cases += [('ishl', [a, sh], lit(s64(a << sh) if sh < 64 else 0)), ('ishr', [a, sh], lit(a >> min(sh, 63))),
                  ('iushr', [a, sh], lit(s64(u64(a) >> sh) if sh < 64 else 0))]
    for k in (8, 16, 32, -8, -16, -32, 64, -64):
        cases += [('iwrap', [a, k], lit(wrapk(a, k)))]
    cases += [('uitoa', [a], f'"{u64(a)}"'), ('itoa', [a], f'"{a}"')]
out = ['// Generated by scripts/gen_pure_tests.py. Do not edit.',
       'import type * as p from "../../lib/pure/int";', '',
       'type Same<X, Y> = [X] extends [Y] ? [Y] extends [X] ? true : false : false;', '']
for i, (op, args, want) in enumerate(cases):
    out.append(f'type C{i} = Same<p.{op}<{", ".join(lit(x) for x in args)}>, {want}>;')
open(os.path.join(ROOT, 'tests', 'pure', 'int.ts'), 'w').write('\n'.join(out) + '\n')
print(len(cases), 'cases')
